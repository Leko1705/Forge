/**
 * Generates one Java file: a class (named after the file, e.g. `Kiln`) whose nested classes are the nodes,
 * records, enums and parsers of the module, and whose static methods are its functions and attributes.
 *
 * - nodes become classes with typed fields and accessors for their attributes: `num.type()`; interface
 *   nodes become interfaces, so `instanceof` works
 * - an attribute is a static method (`attr_type(node)`) that dispatches on the kind of the node
 * - `external fun`s are static methods of a class `<Name>Externals` in the same package, e.g.
 *   `public static String int_text(Integer self)`
 * - values are passed as `Object`: `int` is an `Integer`, lists are `java.util.List<Object>`, maps
 *   `java.util.Map<Object, Object>`
 *
 * Options: `-p <package>`.
 */
object JavaTarget : Target {
    override val name: String get() = "java"
    override val extension: String get() = ".java"

    override fun outputName(module: LLIRModule, base: String): String = className(module, base)

    override fun generate(module: LLIRModule, context: Context): ByteArray {
        val options = Options.instance(context)
        val base = java.io.File(options.get("-o")?.firstOrNull() ?: module.sourceName ?: "out").nameWithoutExtension
        return JavaGeneration(module, className(module, base), options.get("-p")?.firstOrNull()).run().toByteArray()
    }

    /** The class of the file: the file name as a class name, unless the module declares a type of that name. */
    fun className(module: LLIRModule, base: String): String {
        val name = base.split(Regex("[^A-Za-z0-9_]+")).filter { it.isNotEmpty() }
            .joinToString("") { it.replaceFirstChar { c -> c.uppercase() } }
            .let { if (it.isEmpty() || it[0].isDigit()) "Forge$it" else it }
        val declared = module.nodes.map { it.name } + module.records.map { it.name } + module.enums.map { it.name } + module.parsers.map { it.name }
        return if (name in declared || name in JAVA_LANG) name + "Module" else name
    }
}

private val JAVA_KEYWORDS = setOf(
    "abstract", "assert", "boolean", "break", "byte", "case", "catch", "char", "class", "const", "continue",
    "default", "do", "double", "else", "enum", "extends", "final", "finally", "float", "for", "goto", "if",
    "implements", "import", "instanceof", "int", "interface", "long", "native", "new", "package", "private",
    "protected", "public", "return", "short", "static", "strictfp", "super", "switch", "synchronized", "this",
    "throw", "throws", "transient", "try", "void", "volatile", "while", "true", "false", "null", "var", "record",
    "yield", "sealed", "permits", "_",
)

/** Types of java.lang the generated code uses; declarations of these names are renamed. */
private val JAVA_LANG = setOf(
    "Object", "String", "Integer", "Float", "Boolean", "Math", "System", "RuntimeException", "Exception",
    "StringBuilder", "Character", "Long", "Iterable", "Override", "SuppressWarnings", "IllegalStateException",
    "IllegalArgumentException", "Throwable", "Error", "Record", "Class", "Comparable", "Number", "Void", "Byte",
    "Short", "Double", "Thread", "Runnable", "ClassCastException", "NullPointerException", "Vertex", "Edge",
    "Graph", "Span", "ParseException", "ForgeError",
)

private val OBJECT_METHODS = setOf("toString", "hashCode", "equals", "getClass", "notify", "notifyAll", "wait", "clone", "finalize")

private class JavaGeneration(private val module: LLIRModule, private val outer: String, private val pkg: String?) {
    private val s = TargetSupport(module)
    private val names = Names(JAVA_KEYWORDS)
    private val out = StringBuilder()
    private val kinds: Map<Node, Int> = s.concrete.withIndex().associate { (i, n) -> n to i }
    private val exitKind = s.concrete.size
    private val syntheticKind = s.concrete.size + 1

    private fun id(name: String) = names.id(name)
    /** Type names: declared types that would hide types of java.lang are renamed. */
    private fun tid(name: String) = when {
        name == VERTEX || name == GRAPH || name == EDGE || name == SPAN -> name
        name in JAVA_LANG || name in JAVA_KEYWORDS -> name + "_"
        else -> name
    }
    private fun line(text: String = "") { out.append(text).append('\n') }

    fun run(): String {
        line("// Generated by Forge${module.sourceName?.let { " from ${java.io.File(it).name}" } ?: ""}. Do not edit.")
        if (pkg != null) line("package $pkg;\n")
        line("@SuppressWarnings({\"unchecked\", \"rawtypes\", \"unused\"})")
        line("public final class $outer {")
        line("    private $outer() {}")
        line()
        line("    static final int __KIND_EXIT = $exitKind;")
        line("    static final int __KIND_SYNTHETIC = $syntheticKind;")
        line(runtimeResource("java.java"))
        generateTypes()
        generateAttributes()
        module.functions.forEach { generateFunction(it) }
        module.graphs.forEach { generateGraph(it) }
        module.parsers.forEach { generateParser(it) }
        line("}")
        return out.toString()
    }

    // ---- types ---------------------------------------------------------------------------------------

    private fun jtype(type: Type): String = when (type) {
        IntType -> "Integer"
        FloatType -> "Float"
        BoolType -> "Boolean"
        StrType -> "String"
        is ListType -> "java.util.List<Object>"
        is MapType -> "java.util.Map<Object, Object>"
        is SetType -> "java.util.Set<Object>"
        is OptionalType -> jtype(type.elem)
        is ComplexType -> tid(type.name)
        is FlowGraphType -> "__FlowGraph"
        PortType -> "__Port"
        PortRefType -> "__PortRef"
        else -> "Object"
    }

    /** [e] (an `Object`) as a value of [type]. */
    private fun cast(type: Type, e: String): String = when (val t = jtype(type)) {
        "Object" -> e
        "java.util.List<Object>" -> "__l($e)"
        "java.util.Map<Object, Object>" -> "__m($e)"
        "java.util.Set<Object>" -> "__s($e)"
        else -> "(($t) ($e))"
    }

    private fun accessors(node: Node, isInterface: Boolean) {
        val all = buildList {
            for (name in s.attributeNames) {
                if (isInterface) {
                    if ((listOf(node) + node.ancestors()).any { name in it.synthetics || name in it.circulars }) add(name to "attr_$name")
                } else if (s.equation(node, name) != null) add(name to "attr_$name")
            }
            if (!isInterface) for (name in node.collections.keys) add(name to "coll_$name")
            for (name in module.inherited.keys) add(name to "inh_$name")
        }
        for ((name, fn) in all) {
            if (name in OBJECT_METHODS) continue
            val type = s.attributeTypes.getValue(name)
            val modifier = if (isInterface) "default " else ""
            line("        public $modifier${jtype(type)} ${id(name)}() { return ${cast(type, "$fn(this)")}; }")
        }
    }

    private fun generateTypes() {
        for (node in s.interfaces) {
            val parents = s.parentsOf(node).map { tid(it.name) }.ifEmpty { listOf("Vertex") }
            line("    public interface ${tid(node.name)} extends ${parents.joinToString(", ")} {")
            accessors(node, true)
            line("    }")
            line()
        }
        for (node in s.concrete) {
            val ifaces = s.parentsOf(node).filter { it !== s.vertex }.map { tid(it.name) }
            val cls = tid(node.name)
            line("    public static final class $cls extends __Node${if (ifaces.isEmpty()) "" else " implements " + ifaces.joinToString(", ")} {")
            for ((f, t) in node.fields) line("        public final ${jtype(t)} ${id(f)};")
            line("        public $cls(${node.fields.entries.joinToString(", ") { (f, t) -> "${jtype(t)} ${id(f)}" }}) {")
            line("            super(${kinds.getValue(node)});")
            for (f in node.fields.keys) line("            this.${id(f)} = ${id(f)};")
            line("            __adopt();")
            line("        }")
            line("        @Override java.util.List<__Node> __children() {")
            line("            java.util.ArrayList<__Node> c = new java.util.ArrayList<>();")
            for (f in node.fields.keys) line("            __addChildren(c, ${id(f)});")
            line("            return c;")
            line("        }")
            val shown = node.fields.keys.joinToString(" + \", \" + ") { id(it) }
            line("        @Override public String toString() { return \"${node.name}(\"${if (shown.isEmpty()) "" else " + $shown"} + \")\"; }")
            accessors(node, false)
            line("    }")
            line()
        }
        for (enum in module.enums) {
            val e = tid(enum.name)
            line("    public static abstract class $e {")
            for (item in enum.items) {
                if (item.fields.isEmpty()) {
                    line("        public static final $e ${id(item.itemName)} = new __${item.itemName}();")
                    line("        public static final class __${item.itemName} extends $e {")
                    line("            @Override public boolean equals(Object o) { return o instanceof __${item.itemName}; }")
                    line("            @Override public int hashCode() { return ${item.itemName.hashCode()}; }")
                    line("            @Override public String toString() { return \"${item.itemName}\"; }")
                    line("        }")
                } else {
                    valueClass("        ", id(item.itemName), item.itemName, item.fields, "extends $e")
                }
            }
            line("    }")
            line()
        }
        for (record in module.records) {
            if (s.isBuiltinRecord(record.name)) continue
            valueClass("    ", tid(record.name), record.name, record.fields, "")
            line()
        }
        for (port in module.ports) {
            if (!port.isNext) line("    static final __Port __port_${port.name} = new __Port(\"${port.name}\", ${port.inherited});")
        }
        line()
    }

    /** A class compared by value, shown like a Kotlin data class. */
    private fun valueClass(indent: String, cls: String, shownName: String, fields: Map<String, Type>, extends: String) {
        line("${indent}public static final class $cls ${extends} {")
        for ((f, t) in fields) line("$indent    public final ${jtype(t)} ${id(f)};")
        line("$indent    public $cls(${fields.entries.joinToString(", ") { (f, t) -> "${jtype(t)} ${id(f)}" }}) {")
        for (f in fields.keys) line("$indent        this.${id(f)} = ${id(f)};")
        line("$indent    }")
        val eq = fields.keys.joinToString("") { " && java.util.Objects.equals(${id(it)}, other.${id(it)})" }
        line("$indent    @Override public boolean equals(Object o) {")
        line("$indent        if (!(o instanceof $cls)) return false;")
        line("$indent        $cls other = ($cls) o;")
        line("$indent        return true$eq;")
        line("$indent    }")
        line("$indent    @Override public int hashCode() { return java.util.Objects.hash(${fields.keys.joinToString(", ") { id(it) }}); }")
        val shown = fields.keys.withIndex().joinToString("") { (i, f) -> " + \"${if (i > 0) ", " else ""}$f=\" + ${id(f)}" }
        line("$indent    @Override public String toString() { return \"$shownName(\"$shown + \")\"; }")
        line("$indent}")
    }

    // ---- attributes ----------------------------------------------------------------------------------

    private fun dispatchTargets(): List<Pair<Int, Node>> =
        s.concrete.map { kinds.getValue(it) to it } + listOf(exitKind to s.vertex, syntheticKind to s.vertex)

    private fun body(v: Value): String = names.scoped {
        names.alias("this", "self")
        expr(v)
    }

    private fun generateAttributes() {
        for (name in s.attributeNames) {
            line("    static final __Cache __cache_syn_$name = new __Cache(\"$name\");")
            line("    static final __Circular __circ_$name = new __Circular();")
        }
        for (name in module.inherited.keys) line("    static final __Cache __cache_inh_$name = new __Cache(\"$name\");")
        for (name in s.collectionNames) line("    static final __Cache __cache_coll_$name = new __Cache(\"$name\");")
        line()

        for (name in s.attributeNames) {
            val cases = mutableListOf<String>()
            for ((kind, node) in dispatchTargets()) {
                val eq = s.equation(node, name) ?: continue
                val fn = "__${name}_$kind"
                cases += "            case $kind: return $fn(n);"
                when (eq) {
                    is TargetSupport.Equation.Syn ->
                        line("    static Object $fn(Object self) { return __cache_syn_$name.get(self, () -> ${body(eq.body)}); }")
                    is TargetSupport.Equation.Circular ->
                        line("    static Object $fn(Object self) { return __circ_$name.get(self, ${body(eq.attr.init)}, () -> ${body(eq.attr.body)}); }")
                    TargetSupport.Equation.Missing ->
                        line("    static Object $fn(Object self) { throw new ForgeError(\"attribute '$name' is not defined for \" + self); }")
                }
            }
            line("    public static Object attr_$name(Object n) {")
            line("        switch (((__Obj) n).__kind) {")
            cases.forEach { line(it) }
            line("            default: throw new ForgeError(\"attribute '$name' is not defined for \" + n);")
            line("        }")
            line("    }")
            line()
        }

        for (inh in module.inherited.values) {
            val name = inh.name
            line("    public static Object inh_$name(Object n) {")
            line("        __Node node = (__Node) n;")
            line("        return __cache_inh_$name.get(n, () -> node.__parent == null ? (Object) (${body(inh.init)}) : __pass_$name(node.__parent, node));")
            line("    }")
            val cases = mutableListOf<String>()
            for (node in s.concrete) {
                val eq = node.inhEquations[name] ?: continue
                val fn = "__pass_${name}_${kinds.getValue(node)}"
                cases += "            case ${kinds.getValue(node)}: return $fn(parent, child);"
                line("    static Object $fn(Object self, __Node child) {")
                val cls = tid(node.name)
                names.scoped {
                    names.alias("this", "self")
                    for (d in eq.delegates) {
                        val field = "(($cls) self).${id(d.field)}"
                        val key = d.key
                        if (key == null || node.fields[d.field] !is ListType) {
                            line("        if (child == $field) return ${expr(d.value)};")
                        } else {
                            val index = names.fresh("index")
                            val k = names.fresh("k")
                            line("        {")
                            line("            java.util.List<Object> list = $field;")
                            line("            int $index = -1;")
                            line("            for (int $k = 0; $k < list.size(); $k++) if (list.get($k) == child) { $index = $k; break; }")
                            line("            if ($index >= 0) {")
                            val binder = d.binder
                            if (binder != null) {
                                names.scoped {
                                    val b = names.bind(binder.name)
                                    line("                for (int $k = 0; $k < list.size(); $k++) {")
                                    line("                    final Object $b = $k;")
                                    line("                    if (__int(${expr(key)}) == $index) return ${expr(d.value)};")
                                    line("                }")
                                }
                            } else {
                                line("                if (__int(${expr(key)}) == $index) return ${expr(d.value)};")
                            }
                            line("            }")
                            line("        }")
                        }
                    }
                }
                line("        return inh_$name(self);")
                line("    }")
            }
            line("    static Object __pass_$name(__Node parent, __Node child) {")
            line("        switch (parent.__kind) {")
            cases.forEach { line(it) }
            line("            default: return inh_$name(parent);")
            line("        }")
            line("    }")
            line()
        }

        for (name in s.collectionNames) {
            val cases = mutableListOf<String>()
            for (node in s.concrete) {
                val coll = node.collections[name] ?: continue
                val fn = "__coll_${name}_${kinds.getValue(node)}"
                cases += "            case ${kinds.getValue(node)}: return $fn(n);"
                line("    static Object $fn(Object self) {")
                line("        return __cache_coll_$name.get(self, () -> {")
                line("            Object acc = ${body(coll.init)};")
                if (coll.contributions.isNotEmpty()) {
                    val n = names.fresh("n")
                    line("            for (__Node $n : __preorder(((__Node) self).__root())) {")
                    for (c in coll.contributions) {
                        names.scoped {
                            names.alias("this", n)
                            line("                if ($n instanceof ${tid(c.source.name)} && (${expr(c.target)}) == self) {")
                            names.scoped {
                                val alias = names.bind(c.alias)
                                line("                    final Object $alias = acc;")
                                line("                    acc = ${expr(c.value)};")
                            }
                            line("                }")
                        }
                    }
                    line("            }")
                }
                line("            return acc;")
                line("        });")
                line("    }")
            }
            line("    public static Object coll_$name(Object n) {")
            line("        switch (((__Obj) n).__kind) {")
            cases.forEach { line(it) }
            line("            default: throw new ForgeError(\"collection '$name' is not defined for \" + n);")
            line("        }")
            line("    }")
            line()
        }
    }

    // ---- functions -----------------------------------------------------------------------------------

    private val externals = "${outer}Externals"

    private fun functionId(fn: Function): String = id(s.functionName(fn))

    private fun generateFunction(fn: Function) {
        val body = fn.body ?: return
        names.scoped {
            val params = mutableListOf<String>()
            fn.receiver?.let {
                params += "${jtype(it)} self"
                names.alias("this", "self")
            }
            for (p in fn.parameters) params += "${jtype(p.type)} ${names.bind(p.name)}"
            line("    public static ${jtype(fn.returnType)} ${functionId(fn)}(${params.joinToString(", ")}) {")
            line("        return ${cast(fn.returnType, expr(body))};")
            line("    }")
            line()
        }
    }

    // ---- graphs --------------------------------------------------------------------------------------

    private fun generateGraph(graph: FlowGraphDecl) {
        line("    static boolean __flow_${graph.name}(__FlowScope _s, Object n) {")
        for (rule in s.flowRules(graph)) {
            line("        if (n instanceof ${tid(rule.node.name)}) {")
            names.scoped {
                names.alias("this", "n")
                for ((local, field) in rule.binders) {
                    val v = names.bind(local)
                    line("            final Object $v = ((${tid(rule.node.name)}) n).${id(field)};")
                }
                rule.body.forEach { flowStmt(it, "            ") }
            }
            line("            return true;")
            line("        }")
        }
        line("        return false;")
        line("    }")
        line("    public static final __FlowGraph ${id(graph.name)} = new __FlowGraph(x -> x instanceof ${tid(graph.root.name)}, $outer::__flow_${graph.name});")
        line()
    }

    private fun flowStmt(stmt: FlowStmt, indent: String) {
        when (stmt) {
            is FlowEntry -> line("${indent}_s.entry(${expr(stmt.target)});")
            is FlowConnect -> line("${indent}_s.connect(${expr(stmt.source)}, ${expr(stmt.target)}, ${stmt.label?.let { expr(it) } ?: "null"});")
            is FlowSequence -> line("${indent}_s.sequence(${expr(stmt.items)});")
            is FlowVertex -> {
                val label = stmt.label?.let { "(String) (${expr(it)})" } ?: string(stmt.name)
                val v = names.bind(stmt.name)
                line("${indent}final Object $v = _s.vertex(new __SyntheticVertex($label, n));")
            }
            is FlowIf -> {
                line("${indent}if (__bool(${expr(stmt.cond)})) {")
                names.scoped { stmt.then.forEach { flowStmt(it, "$indent    ") } }
                line("$indent} else {")
                names.scoped { stmt.alt.forEach { flowStmt(it, "$indent    ") } }
                line("$indent}")
            }
            is FlowFor -> {
                val iterable = expr(stmt.iterable)
                names.scoped {
                    val v = names.bind(stmt.name)
                    line("${indent}for (final Object $v : __iter($iterable)) {")
                    stmt.body.forEach { flowStmt(it, "$indent    ") }
                    line("$indent}")
                }
            }
        }
    }

    // ---- parsers -------------------------------------------------------------------------------------

    private var terminalNames: Map<GTerminal, String> = emptyMap()
    private var bitNames: Map<GBits, String> = emptyMap()
    private var parserClass = ""
    private var left: String? = null

    private fun generateParser(parser: ParserDecl) {
        val p = tid(parser.name)
        parserClass = p
        terminalNames = s.terminals(parser).withIndex().associate { (i, t) -> t to "$p.__t$i" }
        bitNames = s.bitPatterns(parser).withIndex().associate { (i, b) -> b to "$p.__b$i" }
        line("    public static final class $p {")
        line("        private $p() {}")
        line("        static final java.util.regex.Pattern __skip = ${parser.skip?.let { "java.util.regex.Pattern.compile(${string(it)})" } ?: "null"};")
        line("        static final java.util.Set<String> __keywords = new java.util.HashSet<>(java.util.Arrays.asList(${parser.keywords.joinToString(", ") { string(it) }}));")
        for ((t, n) in terminalNames) {
            line("        static final __Terminal ${n.substringAfter('.')} = new __Terminal(${string(t.regex)}, ${t.literal?.let { string(it) } ?: "null"}, ${string(s.display(t))});")
        }
        for ((b, n) in bitNames) line("        static final __Bits ${n.substringAfter('.')} = new __Bits(${string(b.bits)}, ${string(b.description)});")
        for (rule in parser.rules.values) {
            if (rule.isAbstract) {
                line("        static final __AbstractRule __r_${rule.name} = new __AbstractRule(${string(rule.name)});")
            } else {
                line("        static final __Rule __r_${rule.name} = new __Rule(${string(rule.name)}, _s -> ${alternative(rule.alternatives.single(), null)});")
            }
        }
        val abstract = parser.rules.values.filter { it.isAbstract }
        if (abstract.isNotEmpty()) {
            line("        static {")
            for (rule in abstract) {
                for (alt in rule.alternatives) {
                    val r = "__r_${rule.name}"
                    when (alt.operator) {
                        null -> line("            $r.on(_s -> ${alternative(alt, null)});")
                        OperatorKind.PREFIX -> line("            $r.prefix(${alt.precedence}, _s -> ${alternative(alt, null)});")
                        else -> {
                            val method = when (alt.operator) {
                                OperatorKind.INFIX_LEFT -> "infixLeft"
                                OperatorKind.INFIX_RIGHT -> "infixRight"
                                else -> "postfix"
                            }
                            line("            $r.$method(${alt.precedence}, (_s, _left) -> ${alternative(alt, "_left")});")
                        }
                    }
                }
            }
            line("        }")
        }
        for (rule in parser.rules.values) {
            val type = jtype(rule.type)
            val fn = id(rule.name)
            val result = { call: String -> cast(rule.type, call) }
            if (parser.binary) {
                line("        public static $type $fn(byte[] source, String sourceName) { return ${result("__parseBinary(__r_${rule.name}, source, __skip, __keywords, sourceName)")}; }")
                line("        public static $type $fn(byte[] source) { return $fn(source, null); }")
                line("        public static $type $fn(java.util.List<Object> source) { return $fn(__bytes(source), null); }")
            } else {
                line("        public static $type $fn(String source, String sourceName) { return ${result("__parseText(__r_${rule.name}, source, __skip, __keywords, sourceName)")}; }")
                line("        public static $type $fn(String source) { return $fn(source, null); }")
            }
        }
        line("    }")
        line()
    }

    private fun alternative(alt: GrammarAlternative, leftName: String?): String {
        left = leftName
        val options = alt.options.map { option(it) }
        return options.singleOrNull() ?: "_s.oneOf(${options.joinToString(", ") { "() -> $it" }})"
    }

    private fun option(option: GrammarOption): String = names.scoped {
        val cells = option.labels.map { (name, _) ->
            val cell = names.fresh("label_$name")
            names.alias(name, "$cell.get()")
            name to cell
        }
        val labels = cells.toMap()
        val body = grammar(option.body, labels)
        var result = if (option.producer == null) body else "__then($body, () -> ${expr(option.producer!!)})"
        for ((name, cell) in cells.reversed()) result = "__label(${string(name)}, ($cell) -> $result)"
        result
    }

    private fun grammar(e: GExpr, labels: Map<String, String>): String = when (e) {
        is GTerminal -> "_s.terminal(${terminalNames.getValue(e)})"
        is GBits -> "_s.bits(${bitNames.getValue(e)})"
        is GPrimitive -> "_s.${e.name}(${e.argument?.let { expr(it) } ?: ""})"
        is GNonterminal -> when (e.role) {
            NonterminalRole.RULE -> "_s.apply($parserClass.__r_${e.rule})"
            NonterminalRole.LEFT -> left ?: "null"
            NonterminalRole.OPERAND -> "_s.operand()"
        }
        is GRepeat -> {
            val body = "() -> ${grammar(e.expr, labels)}"
            when (e.kind) {
                RepeatKind.OPTIONAL -> "_s.optional($body)"
                RepeatKind.MANY -> "_s.many($body)"
                RepeatKind.SOME -> "_s.some($body)"
                RepeatKind.COUNT -> "_s.repeat(${expr(e.count!!)}, $body)"
            }
        }
        is GPredicate -> if (e.negate) "_s.not(${string(s.describe(e.expr))}, () -> ${grammar(e.expr, labels)})"
            else "_s.and(() -> ${grammar(e.expr, labels)})"
        is GChoice -> "_s.oneOf(${e.alternatives.joinToString(", ") { "() -> ${grammar(it, labels)}" }})"
        is GSequence -> {
            val items = e.items.joinToString(", ") { "() -> ${grammar(it.expr, labels)}" }
            val cells = e.items.joinToString(", ") { it.label?.let { l -> labels.getValue(l) } ?: "null" }
            "_s.seq(new __Parse[]{$items}, new __Label[]{$cells}, ${e.valueIndex ?: -2})"
        }
    }

    // ---- values --------------------------------------------------------------------------------------

    private fun string(text: String): String = buildString {
        append('"')
        for (c in text) {
            when {
                c == '\\' -> append("\\\\")
                c == '"' -> append("\\\"")
                c == '\n' -> append("\\n")
                c == '\r' -> append("\\r")
                c == '\t' -> append("\\t")
                c.code < 32 || c.code > 126 -> append("\\u%04x".format(c.code))
                else -> append(c)
            }
        }
        append('"')
    }

    private fun args(values: List<Value>) = values.joinToString(", ") { expr(it) }
    private fun typedArgs(values: List<Value>, types: List<Type>) = values.zip(types).joinToString(", ") { (v, t) -> cast(t, expr(v)) }
    private fun i(v: Value) = "__int(${expr(v)})"
    private fun f(v: Value) = "__float(${expr(v)})"
    private fun b(v: Value) = "__bool(${expr(v)})"

    private fun isTest(type: Type, v: String): String = when {
        type is OptionalType -> "($v == null || ${isTest(type.elem, v)})"
        type == IntType -> "($v instanceof Integer)"
        type == FloatType -> "($v instanceof Float)"
        type == BoolType -> "($v instanceof Boolean)"
        type == StrType -> "($v instanceof String)"
        type is ListType -> "($v instanceof java.util.List)"
        type is MapType -> "($v instanceof java.util.Map)"
        type is SetType -> "($v instanceof java.util.Set)"
        type is ComplexType -> "($v instanceof ${tid(type.name)})"
        else -> "true"
    }

    private fun let(value: String, name: String, body: (String) -> String): String = names.scoped {
        val v = names.bind(name)
        "__let($value, (Object $v) -> ${body(v)})"
    }

    private fun nodeClass(node: Node) = tid(node.name)

    fun expr(v: Value): String = when (v) {
        is IntValue -> if (v.value == Int.MIN_VALUE) "Integer.MIN_VALUE" else v.value.toString()
        is FloatValue -> "${v.value}f"
        is BoolValue -> v.value.toString()
        is StringValue -> string(v.value)
        NullValue -> "null"

        is Parameter -> names.lookup(v.name)
        is LocalRef -> names.lookup(v.name)
        is This -> names.lookup("this")
        is AccessParentInhAttr -> "inh_${v.name}(${names.lookup("this")})"

        is ListLiteral -> "__list(${args(v.list)})"
        is MapLiteral -> "__map(${v.entries.joinToString(", ") { (k, x) -> "${expr(k)}, ${expr(x)}" }})"

        is Call -> call(v)
        is CreateRecord -> "new ${tid(v.target.name)}(${typedArgs(v.args, v.target.fields.values.toList())})"
        is CreateEnum -> if (v.target.fields.isEmpty()) "${tid(v.target.enumName)}.${id(v.target.itemName)}"
            else "new ${tid(v.target.enumName)}.${id(v.target.itemName)}(${typedArgs(v.args, v.target.fields.values.toList())})"
        is CreateNode -> "new ${nodeClass(v.target)}(${typedArgs(v.args, v.target.fields.values.toList())})"

        is AccessRecordField -> when (v.target.name) {
            "List" -> "__l(${expr(v.accessed)}).size()"
            "Map" -> "__m(${expr(v.accessed)}).size()"
            "Set" -> "__s(${expr(v.accessed)}).size()"
            "str" -> "((String) (${expr(v.accessed)})).length()"
            else -> "((${tid(v.target.name)}) (${expr(v.accessed)})).${id(v.name)}"
        }
        is AccessNodeField -> "((${nodeClass(v.target)}) (${expr(v.accessed)})).${id(v.name)}"
        is AccessNodeAttr -> when {
            v.name in module.inherited -> "inh_${v.name}(${expr(v.receiver)})"
            v.name in s.collectionNames && v.name !in s.attributeNames -> "coll_${v.name}(${expr(v.receiver)})"
            else -> "attr_${v.name}(${expr(v.receiver)})"
        }
        is AccessListContainer -> "__get(${expr(v.container)}, ${expr(v.key)})"
        is AccessMapContainer -> "__at(${expr(v.container)}, ${expr(v.key)})"

        is Int2Float -> "((float) ${i(v.value)})"
        is Float2Int -> "__f2i(${expr(v.value)})"
        is Cast -> {
            val type = v.type
            if (type is ComplexType && type.name in s.nodeNames) "__cast(${expr(v.value)}, ${tid(type.name)}.class, \"${type.name}\")"
            else expr(v.value)
        }
        is IsInstanceOf -> let(expr(v.value), "x") { x -> isTest(v.target, x) }

        is NegateInt -> "(-${i(v.value)})"
        is NegateFloat -> "(-${f(v.value)})"
        is InvertBool -> "(!${b(v.value)})"
        is InvertInt -> "(~${i(v.value)})"
        is IsNull -> "(${expr(v.checked)} == null)"
        is NotNull -> "__nn(${expr(v.value)})"
        is Elvis -> "__elvis(${expr(v.value)}, () -> ${expr(v.alt)})"

        is MulInt -> "(${i(v.lhs)} * ${i(v.rhs)})"
        is DivInt -> "(${i(v.lhs)} / ${i(v.rhs)})"
        is ModInt -> "(${i(v.lhs)} % ${i(v.rhs)})"
        is AddInt -> "(${i(v.lhs)} + ${i(v.rhs)})"
        is SubInt -> "(${i(v.lhs)} - ${i(v.rhs)})"
        is AndInt, is IAnd -> "(${i((v as BinaryValue).lhs)} & ${i(v.rhs)})"
        is OrInt, is IOr -> "(${i((v as BinaryValue).lhs)} | ${i(v.rhs)})"
        is XorInt -> "(${i(v.lhs)} ^ ${i(v.rhs)})"
        is ShlInt -> "(${i(v.lhs)} << ${i(v.rhs)})"
        is ShrInt -> "(${i(v.lhs)} >> ${i(v.rhs)})"
        is UshrInt -> "(${i(v.lhs)} >>> ${i(v.rhs)})"
        is SetEquals -> "java.util.Objects.equals(${expr(v.lhs)}, ${expr(v.rhs)})"
        is Builtin -> builtin(v)
        is MulFloat -> "(${f(v.lhs)} * ${f(v.rhs)})"
        is DivFloat -> "(${f(v.lhs)} / ${f(v.rhs)})"
        is AddFloat -> "(${f(v.lhs)} + ${f(v.rhs)})"
        is SubFloat -> "(${f(v.lhs)} - ${f(v.rhs)})"
        is LtInt -> "(${i(v.lhs)} < ${i(v.rhs)})"
        is GtInt -> "(${i(v.lhs)} > ${i(v.rhs)})"
        is LeqInt -> "(${i(v.lhs)} <= ${i(v.rhs)})"
        is GeqInt -> "(${i(v.lhs)} >= ${i(v.rhs)})"
        is LtFloat -> "(${f(v.lhs)} < ${f(v.rhs)})"
        is GtFloat -> "(${f(v.lhs)} > ${f(v.rhs)})"
        is LeqFloat -> "(${f(v.lhs)} <= ${f(v.rhs)})"
        is GeqFloat -> "(${f(v.lhs)} >= ${f(v.rhs)})"
        is AndBool -> "(${b(v.lhs)} && ${b(v.rhs)})"
        is OrBool -> "(${b(v.lhs)} || ${b(v.rhs)})"
        is XorBool -> "(${b(v.lhs)} ^ ${b(v.rhs)})"
        is IntEquals -> "(${i(v.lhs)} == ${i(v.rhs)})"
        is FloatEquals -> "(${f(v.lhs)} == ${f(v.rhs)})"
        is BoolEquals, is StringEquals, is ListEquals, is MapEquals, is EnumEquals, is RecordEquals ->
            "java.util.Objects.equals(${expr((v as BinaryValue).lhs)}, ${expr(v.rhs)})"
        is NodeEquals -> "(${expr(v.lhs)} == ${expr(v.rhs)})"
        is ConcatStr -> "((String) (${expr(v.lhs)}) + (String) (${expr(v.rhs)}))"
        is MergeLists -> "__concat(${expr(v.lhs)}, ${expr(v.rhs)})"
        is MergeMaps -> "__merge(${expr(v.lhs)}, ${expr(v.rhs)})"

        is InList -> "__l(${expr(v.list)}).contains(${expr(v.element)})"
        is InMapKeys -> "__m(${expr(v.map)}).containsKey(${expr(v.key)})"
        is AppendListItem -> "__append(${expr(v.list)}, ${expr(v.element)})"
        is AppendAllListItems -> "__concat(${expr(v.list)}, ${expr(v.elements)})"
        is PutMapItem -> "__put(${expr(v.map)}, ${expr(v.key)}, ${expr(v.value)})"
        is PutAllMapItems -> "__merge(${expr(v.map)}, ${expr(v.elements)})"

        is IfElse -> "(${b(v.cond)} ? (Object) (${expr(v.then)}) : (Object) (${expr(v.alt)}))"
        is Panic -> "__panic(${string(v.message)})"

        is MapOp -> {
            val iterable = expr(v.iterable)
            names.scoped {
                val x = names.bind(v.name)
                "__mapList($iterable, (Object $x) -> ${expr(v.body)})"
            }
        }
        is FoldOp -> {
            val iterable = expr(v.iterable)
            val init = expr(v.initAcc)
            names.scoped {
                val x = names.bind(v.item)
                val acc = names.bind(v.acc)
                "__fold($iterable, $init, (Object $acc, Object $x) -> ${expr(v.body)})"
            }
        }

        is PortValue -> if (v.port.isNext) "__PORT_NEXT" else "__port_${v.port.name}"
        is PortRefValue -> "new __PortRef(${expr(v.child)}, ${expr(PortValue(v.port))})"
        is BoundCheck -> "_s.bound(${expr(v.port)})"
        is FlowGraphRef -> id(v.graph.name)

        is Match -> match(v)
    }

    private fun builtin(b: Builtin): String {
        val r = b.receiver?.let { expr(it) }
        val a = b.args.map { expr(it) }
        val s = "((String) ($r))"
        return when (b.name) {
            "int.str", "float.str", "bool.str" -> "String.valueOf($r)"
            "str.toInt" -> "__toInt($r)"
            "str.toFloat" -> "__toFloat($r)"
            "str.indexOf" -> "$s.indexOf((String) (${a[0]}))"
            "str.startsWith" -> "$s.startsWith((String) (${a[0]}))"
            "str.endsWith" -> "$s.endsWith((String) (${a[0]}))"
            "str.replace" -> "__replace($r, ${a[0]}, ${a[1]})"
            "str.upper" -> "$s.toUpperCase(java.util.Locale.ROOT)"
            "str.lower" -> "$s.toLowerCase(java.util.Locale.ROOT)"
            "str.trim" -> "$s.strip()"
            "str.split" -> "__split($r, ${a[0]})"
            "str.code" -> "__code($r, ${a[0]})"
            "str.utf8" -> "__utf8($r)"
            "str.unescape" -> "__unescape($r)"
            "char" -> "__char(${a[0]})"
            "fail" -> "__panic((String) (${a[0]}))"
            "str.get" -> "__charAt($r, ${a[0]})"
            "str.slice", "List.slice" -> "__slice($r, ${a[0]}, ${a[1]})"
            "str.contains" -> "$s.contains((String) (${a[0]}))"
            "range" -> "__range(${a[0]}, ${a[1]})"
            "List.indexOf" -> "__l($r).indexOf(${a[0]})"
            "List.reversed" -> "__reversed($r)"
            "List.toSet" -> "new java.util.LinkedHashSet<Object>(__l($r))"
            "List.join" -> "__join($r, ${a[0]})"
            "Map.keys" -> "new java.util.ArrayList<Object>(__m($r).keySet())"
            "Map.values" -> "new java.util.ArrayList<Object>(__m($r).values())"
            "Map.remove" -> "__mapRemove($r, ${a[0]})"
            "Set.toList" -> "new java.util.ArrayList<Object>(__s($r))"
            "Set.remove" -> "__setRemove($r, ${a[0]})"
            "Set.of" -> "__set(${a.joinToString(", ")})"
            "Set.contains" -> "__s($r).contains(${a[0]})"
            "Set.union" -> "__union($r, ${a[0]})"
            else -> throw IllegalStateException("unknown builtin ${b.name}")
        }
    }

    private fun call(v: Call): String {
        val fn = v.target
        val owner = fn.receiver
        val receiver = v.receiver
        val types = fn.parameters.map { it.type }
        return when {
            owner is ParserType -> "${tid(owner.name)}.${id(fn.name)}(${typedArgs(v.args, types)})"
            owner is FlowGraphType -> "${expr(receiver!!)}.${fn.name}(${args(v.args)})"
            owner is ComplexType && owner.name == GRAPH -> "((Graph) (${expr(receiver!!)})).${fn.name}(${typedArgs(v.args, types)})"
            owner == null && fn.body == null && fn.name == "graphOf" -> "graphOf(${typedArgs(v.args, types)})"
            owner == null && fn.body == null && fn.name == "spanOf" -> "spanOf(${args(v.args)})"
            else -> {
                val all = (listOfNotNull(receiver) + v.args)
                val allTypes = listOfNotNull(owner) + types
                val host = if (fn.body == null) "$externals." else ""
                "$host${functionId(fn)}(${typedArgs(all, allTypes)})"
            }
        }
    }

    private val patterns = object : TargetSupport.Patterns {
        override fun fresh(): String = names.fresh("m")
        override fun isItem(subject: String, item: EnumItem): String =
            "($subject instanceof ${tid(item.enumName)}.${if (item.fields.isEmpty()) "__" + item.itemName else id(item.itemName)})"
        override fun itemField(subject: String, item: EnumItem, field: String): String =
            "((${tid(item.enumName)}.${id(item.itemName)}) $subject).${id(field)}"
        override fun sizeIs(subject: String, size: Int): String = "(__l($subject).size() == $size)"
        override fun notEmpty(subject: String): String = "(!__l($subject).isEmpty())"
        override fun element(subject: String, index: Int): String = "__l($subject).get($index)"
        override fun tail(subject: String): String = "__tail($subject)"
        override fun equalTo(subject: String, value: Value): String = "java.util.Objects.equals($subject, ${expr(value)})"
        override fun bindVariable(variable: LocalRef): String = names.bind(variable.name)
    }

    private fun match(m: Match): String {
        val scrutinee = expr(m.scrutinee)
        return names.scoped {
            val subject = names.fresh("subject")
            val cases = m.cases.map { case ->
                names.scoped {
                    val steps = s.steps(case.pattern, subject, patterns)
                    val guard = case.guard?.let { b(it) }
                    val body = expr(case.body)
                    var result = if (guard != null) "($guard ? (Object) ($body) : __NOMATCH)" else body
                    for (step in steps.reversed()) {
                        result = when (step) {
                            is TargetSupport.Step.Test -> "(${step.cond} ? (Object) ($result) : __NOMATCH)"
                            is TargetSupport.Step.Bind -> "__let(${step.value}, (Object ${step.name}) -> $result)"
                        }
                    }
                    "() -> $result"
                }
            }
            val alt = m.alt?.let { "() -> ${expr(it)}" } ?: "null"
            "__let($scrutinee, (Object $subject) -> __match($subject, new __Fn0[]{${cases.joinToString(", ")}}, $alt))"
        }
    }
