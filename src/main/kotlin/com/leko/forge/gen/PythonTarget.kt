package com.leko.forge.gen

import com.leko.forge.context.Context
import com.leko.forge.llir.*
import com.leko.forge.llir.Function
import com.leko.forge.model.GRAPH
import com.leko.forge.types.*

/**
 * Generates one Python 3 module from a module.
 *
 * - nodes become classes (interfaces become base classes, so `isinstance` works), with the attributes as
 *   properties: `node.type`; records and enum items are compared by value
 * - an attribute is a function that dispatches on the class of the node to the equation that applies
 * - functions become functions (methods are named `Receiver_name`); `external fun`s are imported from
 *   `<module>_externals`, e.g. `def int_text(self): return str(self)` in `conformance_externals.py`
 * - parsers become classes with a static method per rule: `Calc.program(source)`
 */
object PythonTarget : Target {
    override val name: String get() = "python"
    override val extension: String get() = ".py"

    override fun generate(module: LLIRModule, context: Context): ByteArray =
        PythonGeneration(module, moduleName(module, context)).run().toByteArray()

    private fun moduleName(module: LLIRModule, context: Context): String {
        val out = com.leko.forge.utils.Options.instance(context).get("-o")?.firstOrNull() ?: module.sourceName ?: "out"
        return java.io.File(out).nameWithoutExtension
    }
}

private val PYTHON_KEYWORDS = setOf(
    "False", "None", "True", "and", "as", "assert", "async", "await", "break", "class", "continue", "def", "del",
    "elif", "else", "except", "finally", "for", "from", "global", "if", "import", "in", "is", "lambda", "nonlocal",
    "not", "or", "pass", "raise", "return", "try", "while", "with", "yield",
)

/** Global names must not hide the builtins the runtime uses. */
private val PYTHON_BUILTINS = setOf(
    "type", "abs", "all", "any", "bytes", "dict", "enumerate", "float", "getattr", "hash", "id", "int", "isinstance", "iter",
    "len", "list", "max", "min", "next", "object", "print", "range", "reversed", "set", "str", "tuple", "super",
    "property", "staticmethod", "frozenset", "bool", "map", "sum", "repr", "format", "open", "vars", "self",
)

private class PythonGeneration(private val module: LLIRModule, private val moduleName: String) {
    private val s = TargetSupport(module)
    private val names = Names(PYTHON_KEYWORDS)
    private val out = StringBuilder()

    private fun id(name: String) = names.id(name)
    private fun gid(name: String) = if (name in PYTHON_BUILTINS || name in PYTHON_KEYWORDS) name + "_" else name
    private fun line(text: String = "") { out.append(text).append('\n') }

    fun run(): String {
        line("# Generated by Forge${module.sourceName?.let { " from ${java.io.File(it).name}" } ?: ""}. Do not edit.")
        line(runtimeResource("python.py"))
        if (module.functions.any { it.body == null && !isBuiltinFunction(it) }) {
            line("from ${moduleName}_externals import *")
            line()
        }
        generateTypes()
        generateAttributes()
        module.functions.forEach { generateFunction(it) }
        module.graphs.forEach { generateGraph(it) }
        module.parsers.forEach { generateParser(it) }
        generateProperties()
        return out.toString()
    }

    private fun isBuiltinFunction(fn: Function) = fn.receiver == null && fn.name in setOf("graphOf", "spanOf")

    // ---- declarations ------------------------------------------------------------------------------

    private fun className(node: Node): String = if (node === s.vertex) "Vertex" else gid(node.name)

    private fun generateTypes() {
        // interfaces before the nodes that implement them
        val ordered = s.interfaces.sortedBy { it.ancestors().size }
        for (node in ordered) {
            val bases = s.parentsOf(node).map { className(it) }.ifEmpty { listOf("Vertex") }
            line("class ${gid(node.name)}(${bases.joinToString(", ")}):")
            line("    __slots__ = ()")
            line()
        }
        for (node in s.concrete) {
            val bases = listOf("_Node") + s.parentsOf(node).filter { it !== s.vertex }.map { className(it) }
            val fields = node.fields.keys.map { id(it) }
            line("class ${gid(node.name)}(${bases.joinToString(", ")}):")
            line("    __slots__ = (${fields.joinToString("") { "\"$it\", " }})")
            line("    _fields = (${fields.joinToString("") { "\"$it\", " }})")
            line("    _name = \"${node.name}\"")
            line("    def __init__(self${fields.joinToString("") { ", $it" }}):")
            for (f in fields) line("        self.$f = $f")
            line("        self._adopt()")
            line()
        }
        for (enum in module.enums) {
            line("class ${gid(enum.name)}(_EnumItem):")
            line("    __slots__ = ()")
            line()
            for (item in enum.items) {
                val cls = "_${enum.name}_${item.itemName}"
                val fields = item.fields.keys.map { id(it) }
                line("class $cls(${gid(enum.name)}):")
                line("    __slots__ = (${fields.joinToString("") { "\"$it\", " }})")
                line("    _fields = (${fields.joinToString("") { "\"$it\", " }})")
                line("    _name = \"${item.itemName}\"")
                if (fields.isNotEmpty()) {
                    line("    def __init__(self${fields.joinToString("") { ", $it" }}):")
                    for (f in fields) line("        self.$f = $f")
                }
                line()
                line(if (fields.isEmpty()) "${gid(enum.name)}.${id(item.itemName)} = $cls()" else "${gid(enum.name)}.${id(item.itemName)} = $cls")
                line()
            }
        }
        for (record in module.records) {
            if (s.isBuiltinRecord(record.name)) continue
            val fields = record.fields.keys.map { id(it) }
            line("class ${gid(record.name)}(_Record):")
            line("    __slots__ = (${fields.joinToString("") { "\"$it\", " }})")
            line("    _fields = (${fields.joinToString("") { "\"$it\", " }})")
            line("    _name = \"${record.name}\"")
            line("    def __init__(self${fields.joinToString("") { ", $it" }}):")
            for (f in fields) line("        self.$f = $f")
            if (fields.isEmpty()) line("        pass")
            line()
        }
        for (port in module.ports) {
            if (!port.isNext) line("_port_${port.name} = _Port(\"${port.name}\", ${if (port.inherited) "True" else "False"})")
        }
        line()
    }

    // ---- attributes --------------------------------------------------------------------------------

    /** The concrete classes and the vertices of the runtime, each with the node that declares its equations. */
    private fun dispatchTargets(): List<Pair<String, Node>> =
        s.concrete.map { gid(it.name) to it } + listOf("_ExitVertex" to s.vertex, "_SyntheticVertex" to s.vertex)

    private fun generateAttributes() {
        for (name in s.attributeNames) {
            line("_cache_syn_$name = _Cache(\"$name\")")
            line("_circ_$name = _Circular()")
        }
        for (name in module.inherited.keys) line("_cache_inh_$name = _Cache(\"$name\")")
        for (name in s.collectionNames) line("_cache_coll_$name = _Cache(\"$name\")")
        line()

        for (name in s.attributeNames) {
            val table = mutableListOf<String>()
            for ((cls, node) in dispatchTargets()) {
                val eq = s.equation(node, name) ?: continue
                val fn = "_${name}_$cls"
                table += "$cls: $fn"
                line("def $fn(self):")
                when (eq) {
                    is TargetSupport.Equation.Syn -> line("    return _cache_syn_$name.get(self, lambda: ${body(eq.body)})")
                    is TargetSupport.Equation.Circular ->
                        line("    return _circ_$name.get(self, ${body(eq.attr.init)}, lambda: ${body(eq.attr.body)})")
                    TargetSupport.Equation.Missing -> line("    raise ForgeError(\"attribute '$name' is not defined for \" + _show(self))")
                }
            }
            line("_attr_table_$name = {${table.joinToString(", ")}}")
            line("def attr_$name(n):")
            line("    f = _attr_table_$name.get(type(n))")
            line("    if f is None:")
            line("        raise ForgeError(\"attribute '$name' is not defined for \" + _show(n))")
            line("    return f(n)")
            line()
        }

        for (inh in module.inherited.values) {
            val name = inh.name
            line("def inh_$name(n):")
            line("    return _cache_inh_$name.get(n, lambda: (${body(inh.init)}) if n._parent is None else _pass_$name(n._parent, n))")
            val table = mutableListOf<String>()
            for (node in s.concrete) {
                val eq = node.inhEquations[name] ?: continue
                val fn = "_pass_${name}_${node.name}"
                table += "${gid(node.name)}: $fn"
                line("def $fn(self, child):")
                names.scoped {
                    names.alias("this", "self")
                    for (d in eq.delegates) {
                        val field = "self.${id(d.field)}"
                        val key = d.key
                        if (key == null || node.fields[d.field] !is ListType) {
                            line("    if child is $field:")
                            line("        return ${expr(d.value)}")
                        } else {
                            val index = names.fresh("index")
                            line("    $index = next((i for i, c in enumerate($field) if c is child), -1)")
                            line("    if $index >= 0:")
                            val binder = d.binder
                            if (binder != null) {
                                names.scoped {
                                    val b = names.bind(binder.name)
                                    line("        for $b in range(len($field)):")
                                    line("            if ${expr(key)} == $index:")
                                    line("                return ${expr(d.value)}")
                                }
                            } else {
                                line("        if ${expr(key)} == $index:")
                                line("            return ${expr(d.value)}")
                            }
                        }
                    }
                }
                line("    return inh_$name(self)")
            }
            line("_pass_table_$name = {${table.joinToString(", ")}}")
            line("def _pass_$name(parent, child):")
            line("    f = _pass_table_$name.get(type(parent))")
            line("    return inh_$name(parent) if f is None else f(parent, child)")
            line()
        }

        for (name in s.collectionNames) {
            val table = mutableListOf<String>()
            for (node in s.concrete) {
                val coll = node.collections[name] ?: continue
                val fn = "_coll_${name}_${node.name}"
                table += "${gid(node.name)}: $fn"
                line("def $fn(self):")
                line("    def compute():")
                line("        acc = ${body(coll.init)}")
                if (coll.contributions.isNotEmpty()) {
                    line("        for n in _preorder(self._root()):")
                    for (c in coll.contributions) {
                        names.scoped {
                            names.alias("this", "n")
                            line("            if isinstance(n, ${className(c.source)}) and (${expr(c.target)}) is self:")
                            names.scoped {
                                val alias = names.bind(c.alias)
                                line("                $alias = acc")
                                line("                acc = ${expr(c.value)}")
                            }
                        }
                    }
                }
                line("        return acc")
                line("    return _cache_coll_$name.get(self, compute)")
            }
            line("_coll_table_$name = {${table.joinToString(", ")}}")
            line("def coll_$name(n):")
            line("    f = _coll_table_$name.get(type(n))")
            line("    if f is None:")
            line("        raise ForgeError(\"collection '$name' is not defined for \" + _show(n))")
            line("    return f(n)")
            line()
        }
    }

    /** An attribute equation: `this` is `self`. */
    private fun body(v: Value): String = names.scoped {
        names.alias("this", "self")
        expr(v)
    }

    /** Properties, so that attributes read like fields: `node.type`. */
    private fun generateProperties() {
        for (name in s.attributeNames) {
            for ((cls, node) in dispatchTargets()) {
                if (s.equation(node, name) != null) line("$cls.${id(name)} = property(attr_$name)")
            }
        }
        for (name in s.collectionNames) {
            for (node in s.concrete) if (name in node.collections) line("${gid(node.name)}.${id(name)} = property(coll_$name)")
        }
        for (name in module.inherited.keys) line("_Node.${id(name)} = property(inh_$name)")
    }

    // ---- functions ---------------------------------------------------------------------------------

    private fun functionId(fn: Function): String = gid(s.functionName(fn))

    private fun generateFunction(fn: Function) {
        val body = fn.body ?: return
        names.scoped {
            val params = mutableListOf<String>()
            if (fn.receiver != null) {
                params += "self"
                names.alias("this", "self")
            }
            for (p in fn.parameters) params += names.bind(p.name)
            line("def ${functionId(fn)}(${params.joinToString(", ")}):")
            line("    return ${expr(body)}")
            line()
        }
    }

    // ---- graphs ------------------------------------------------------------------------------------

    private fun generateGraph(graph: FlowGraphDecl) {
        line("def _flow_${graph.name}(_s, n):")
        for (rule in s.flowRules(graph)) {
            line("    if isinstance(n, ${className(rule.node)}):")
            names.scoped {
                names.alias("this", "n")
                for ((local, field) in rule.binders) {
                    val v = names.bind(local)
                    line("        $v = n.${id(field)}")
                }
                rule.body.forEach { flowStmt(it, "        ") }
            }
            line("        return True")
        }
        line("    return False")
        line("${gid(graph.name)} = _FlowGraph(lambda x: isinstance(x, ${className(graph.root)}), _flow_${graph.name})")
        line()
    }

    private fun flowStmt(stmt: FlowStmt, indent: String) {
        when (stmt) {
            is FlowEntry -> line("${indent}_s.entry(${expr(stmt.target)})")
            is FlowConnect -> line("${indent}_s.connect(${expr(stmt.source)}, ${expr(stmt.target)}, ${stmt.label?.let { expr(it) } ?: "None"})")
            is FlowSequence -> line("${indent}_s.sequence(${expr(stmt.items)})")
            is FlowVertex -> {
                val label = stmt.label?.let { expr(it) } ?: string(stmt.name)
                val v = names.bind(stmt.name)
                line("$indent$v = _s.vertex(_SyntheticVertex($label, n))")
            }
            is FlowIf -> {
                line("${indent}if ${expr(stmt.cond)}:")
                line("$indent    pass")
                names.scoped { stmt.then.forEach { flowStmt(it, "$indent    ") } }
                line("${indent}else:")
                line("$indent    pass")
                names.scoped { stmt.alt.forEach { flowStmt(it, "$indent    ") } }
            }
            is FlowFor -> {
                val iterable = expr(stmt.iterable)
                names.scoped {
                    val v = names.bind(stmt.name)
                    line("${indent}for $v in $iterable:")
                    line("$indent    pass")
                    stmt.body.forEach { flowStmt(it, "$indent    ") }
                }
            }
        }
    }

    // ---- parsers -----------------------------------------------------------------------------------

    private var terminalNames: Map<GTerminal, String> = emptyMap()
    private var bitNames: Map<GBits, String> = emptyMap()
    private var parserName = ""
    private var operandRule: GrammarRule? = null

    private fun generateParser(parser: ParserDecl) {
        val p = gid(parser.name)
        parserName = p
        terminalNames = s.terminals(parser).withIndex().associate { (i, t) -> t to "$p._t$i" }
        bitNames = s.bitPatterns(parser).withIndex().associate { (i, b) -> b to "$p._b$i" }
        line("class $p:")
        line("    _skip = ${parser.skip?.let { "_re.compile(${string(it)}, _re.ASCII)" } ?: "None"}")
        line("    _keywords = frozenset([${parser.keywords.joinToString(", ") { string(it) }}])")
        line()
        for ((t, n) in terminalNames) {
            line("${n} = _Terminal(${string(t.regex)}, ${t.literal?.let { string(it) } ?: "None"}, ${string(s.display(t))})")
        }
        for ((b, n) in bitNames) line("$n = _Bits(${string(b.bits)}, ${string(b.description)})")
        for (rule in parser.rules.values) {
            operandRule = rule
            if (rule.isAbstract) {
                line("$p._r_${rule.name} = _AbstractRule(${string(rule.name)})")
            } else {
                line("$p._r_${rule.name} = _Rule(${string(rule.name)}, lambda _s: ${alternative(rule.alternatives.single(), null)})")
            }
        }
        for (rule in parser.rules.values.filter { it.isAbstract }) {
            operandRule = rule
            for (alt in rule.alternatives) {
                val r = "$p._r_${rule.name}"
                when (alt.operator) {
                    null -> line("$r.on(lambda _s: ${alternative(alt, null)})")
                    OperatorKind.PREFIX -> line("$r.prefix(${alt.precedence}, lambda _s: ${alternative(alt, null)})")
                    else -> {
                        val method = when (alt.operator) {
                            OperatorKind.INFIX_LEFT -> "infixLeft"
                            OperatorKind.INFIX_RIGHT -> "infixRight"
                            else -> "postfix"
                        }
                        line("$r.$method(${alt.precedence}, lambda _s, _left: ${alternative(alt, "_left")})")
                    }
                }
            }
        }
        for (rule in parser.rules.values) {
            val fn = id(rule.name)
            val entry = if (parser.binary) "_parse_binary" else "_parse_text"
            line("$p.$fn = staticmethod(lambda source, sourceName=None: $entry($p._r_${rule.name}, source, $p._skip, $p._keywords, sourceName))")
        }
        line()
    }

    private var left: String? = null

    private fun alternative(alt: GrammarAlternative, leftName: String?): String {
        left = leftName
        val options = alt.options.map { option(it) }
        return options.singleOrNull() ?: "_s.one_of(${options.joinToString(", ") { "lambda: $it" }})"
    }

    /** Labels are cells, created when the option starts; the producer reads them. */
    private fun option(option: GrammarOption): String = names.scoped {
        val cells = option.labels.map { (name, _) ->
            val cell = names.fresh("label_$name")
            names.alias(name, "$cell.get()")
            Triple(name, cell, cell)
        }
        val labelCells = cells.associate { it.first to it.second }
        val body = grammar(option.body, labelCells)
        val inner = if (option.producer == null) body else "($body, ${expr(option.producer!!)})[1]"
        if (cells.isEmpty()) inner
        else "(lambda ${cells.joinToString(", ") { "${it.second}=_Label(${string(it.first)})" }}: $inner)()"
    }

    private fun grammar(e: GExpr, labels: Map<String, String>): String = when (e) {
        is GTerminal -> "_s.terminal(${terminalNames.getValue(e)})"
        is GBits -> "_s.bits(${bitNames.getValue(e)})"
        is GPrimitive -> "_s.${e.name}(${e.argument?.let { expr(it) } ?: ""})"
        is GNonterminal -> when (e.role) {
            NonterminalRole.RULE -> "_s.apply($parserName._r_${e.rule})"
            NonterminalRole.LEFT -> left ?: "None"
            NonterminalRole.OPERAND -> "_s.operand()"
        }
        is GRepeat -> {
            val body = "lambda: ${grammar(e.expr, labels)}"
            when (e.kind) {
                RepeatKind.OPTIONAL -> "_s.optional($body)"
                RepeatKind.MANY -> "_s.many($body)"
                RepeatKind.SOME -> "_s.some($body)"
                RepeatKind.COUNT -> "_s.repeat(${expr(e.count!!)}, $body)"
            }
        }
        is GPredicate -> if (e.negate) "_s.not_(${string(s.describe(e.expr))}, lambda: ${grammar(e.expr, labels)})"
            else "_s.and_(lambda: ${grammar(e.expr, labels)})"
        is GChoice -> "_s.one_of(${e.alternatives.joinToString(", ") { "lambda: ${grammar(it, labels)}" }})"
        is GSequence -> {
            val items = e.items.joinToString(", ") { item ->
                "(lambda: ${grammar(item.expr, labels)}, ${item.label?.let { labels.getValue(it) } ?: "None"})"
            }
            "_s.seq([$items], ${e.valueIndex?.toString() ?: "None"})"
        }
    }

    // ---- values ------------------------------------------------------------------------------------

    private fun string(text: String): String = buildString {
        append('"')
        for (c in text) {
            when {
                c == '\\' -> append("\\\\")
                c == '"' -> append("\\\"")
                c == '\n' -> append("\\n")
                c == '\r' -> append("\\r")
                c == '\t' -> append("\\t")
                c.code < 32 || c.code == 127 -> append("\\x%02x".format(c.code))
                else -> append(c)
            }
        }
        append('"')
    }

    private fun bin(v: BinaryValue, op: String) = "(${expr(v.lhs)} $op ${expr(v.rhs)})"
    private fun args(values: List<Value>) = values.joinToString(", ") { expr(it) }

    private fun isTest(type: Type, v: String): String = when {
        type is OptionalType -> "($v is None or ${isTest(type.elem, v)})"
        type == IntType -> "(type($v) is int)"
        type == FloatType -> "isinstance($v, float)"
        type == BoolType -> "isinstance($v, bool)"
        type == StrType -> "isinstance($v, str)"
        type is ListType -> "isinstance($v, list)"
        type is SetType -> "isinstance($v, _Set)"
        type is MapType -> "(isinstance($v, dict) and not isinstance($v, _Set))"
        type is ComplexType -> "isinstance($v, ${typeClass(type.name)})"
        else -> "True"
    }

    private fun typeClass(name: String): String = when {
        name in s.nodeNames -> className(s.module.nodes.first { it.name == name })
        else -> gid(name)
    }

    private fun let(value: String, name: String, body: (String) -> String): String = names.scoped {
        val v = names.bind(name)
        "(lambda $v: ${body(v)})($value)"
    }

    fun expr(v: Value): String = when (v) {
        is IntValue -> v.value.toString()
        is FloatValue -> "_f32(${v.value.toDouble()})"
        is BoolValue -> if (v.value) "True" else "False"
        is StringValue -> string(v.value)
        NullValue -> "None"

        is Parameter -> names.lookup(v.name)
        is LocalRef -> names.lookup(v.name)
        is This -> names.lookup("this")
        is AccessParentInhAttr -> "inh_${v.name}(${names.lookup("this")})"

        is ListLiteral -> "[${args(v.list)}]"
        is MapLiteral -> "_map(${v.entries.joinToString(", ") { (k, x) -> "(${expr(k)}, ${expr(x)})" }})"

        is Call -> call(v)
        is CreateRecord -> "${gid(v.target.name)}(${args(v.args)})"
        is CreateEnum -> if (v.target.fields.isEmpty()) "${gid(v.target.enumName)}.${id(v.target.itemName)}"
            else "${gid(v.target.enumName)}.${id(v.target.itemName)}(${args(v.args)})"
        is CreateNode -> "${gid(v.target.name)}(${args(v.args)})"

        is AccessRecordField -> if (v.target.name in setOf("List", "Map", "Set", "str") && v.name == "size") "len(${expr(v.accessed)})"
            else "${expr(v.accessed)}.${id(v.name)}"
        is AccessNodeField -> "${expr(v.accessed)}.${id(v.name)}"
        is AccessNodeAttr -> when {
            v.name in module.inherited -> "inh_${v.name}(${expr(v.receiver)})"
            v.name in s.collectionNames && v.name !in s.attributeNames -> "coll_${v.name}(${expr(v.receiver)})"
            else -> "attr_${v.name}(${expr(v.receiver)})"
        }
        is AccessListContainer -> "_get(${expr(v.container)}, ${expr(v.key)})"
        is AccessMapContainer -> "_at(${expr(v.container)}, ${expr(v.key)})"

        is Int2Float -> "_f32(float(${expr(v.value)}))"
        is Float2Int -> "_f2i(${expr(v.value)})"
        is Cast -> {
            val type = v.type
            if (type is ComplexType && type.name in s.nodeNames) let(expr(v.value), "cast") { x ->
                "($x if ${isTest(type, x)} else _panic(\"can not cast \" + _show($x) + \" to ${type.name}\"))"
            } else expr(v.value)
        }
        is IsInstanceOf -> let(expr(v.value), "x") { x -> isTest(v.target, x) }

        is NegateInt -> "_i32(-${expr(v.value)})"
        is NegateFloat -> "_f32(-${expr(v.value)})"
        is InvertBool -> "(not ${expr(v.value)})"
        is InvertInt -> "_i32(~${expr(v.value)})"
        is IsNull -> "(${expr(v.checked)} is None)"
        is NotNull -> "_nn(${expr(v.value)})"
        is Elvis -> "_elvis(${expr(v.value)}, lambda: ${expr(v.alt)})"

        is MulInt -> "_i32(${expr(v.lhs)} * ${expr(v.rhs)})"
        is DivInt -> "_div(${expr(v.lhs)}, ${expr(v.rhs)})"
        is ModInt -> "_mod(${expr(v.lhs)}, ${expr(v.rhs)})"
        is AddInt -> "_i32(${expr(v.lhs)} + ${expr(v.rhs)})"
        is SubInt -> "_i32(${expr(v.lhs)} - ${expr(v.rhs)})"
        is AndInt, is IAnd -> bin(v as BinaryValue, "&")
        is OrInt, is IOr -> bin(v as BinaryValue, "|")
        is XorInt -> bin(v, "^")
        is ShlInt -> "_i32(${expr(v.lhs)} << (${expr(v.rhs)} & 31))"
        is ShrInt -> "(${expr(v.lhs)} >> (${expr(v.rhs)} & 31))"
        is UshrInt -> "_i32((${expr(v.lhs)} & 0xFFFFFFFF) >> (${expr(v.rhs)} & 31))"
        is SetEquals -> bin(v, "==")
        is Builtin -> builtin(v)
        is MulFloat -> "_f32(${expr(v.lhs)} * ${expr(v.rhs)})"
        is DivFloat -> "_f32(${expr(v.lhs)} / ${expr(v.rhs)})"
        is AddFloat -> "_f32(${expr(v.lhs)} + ${expr(v.rhs)})"
        is SubFloat -> "_f32(${expr(v.lhs)} - ${expr(v.rhs)})"
        is LtInt, is LtFloat -> bin(v as BinaryValue, "<")
        is GtInt, is GtFloat -> bin(v as BinaryValue, ">")
        is LeqInt, is LeqFloat -> bin(v as BinaryValue, "<=")
        is GeqInt, is GeqFloat -> bin(v as BinaryValue, ">=")
        is AndBool -> bin(v, "and")
        is OrBool -> bin(v, "or")
        is XorBool -> bin(v, "!=")
        is IntEquals, is FloatEquals, is BoolEquals, is StringEquals, is ListEquals, is MapEquals, is EnumEquals,
        is RecordEquals -> bin(v as BinaryValue, "==")
        is NodeEquals -> bin(v, "is")
        is ConcatStr -> bin(v, "+")
        is MergeLists -> bin(v, "+")
        is MergeMaps -> "_merge(${expr(v.lhs)}, ${expr(v.rhs)})"

        is InList -> "(${expr(v.element)} in ${expr(v.list)})"
        is InMapKeys -> "_in_map(${expr(v.map)}, ${expr(v.key)})"
        is AppendListItem -> "(${expr(v.list)} + [${expr(v.element)}])"
        is AppendAllListItems -> "(${expr(v.list)} + ${expr(v.elements)})"
        is PutMapItem -> "_put(${expr(v.map)}, ${expr(v.key)}, ${expr(v.value)})"
        is PutAllMapItems -> "_merge(${expr(v.map)}, ${expr(v.elements)})"

        is IfElse -> "(${expr(v.then)} if ${expr(v.cond)} else ${expr(v.alt)})"
        is Panic -> "_panic(${string(v.message)})"

        is MapOp -> {
            val iterable = expr(v.iterable)
            names.scoped {
                val x = names.bind(v.name)
                "[${expr(v.body)} for $x in $iterable]"
            }
        }
        is FoldOp -> {
            val iterable = expr(v.iterable)
            val init = expr(v.initAcc)
            names.scoped {
                val x = names.bind(v.item)
                val acc = names.bind(v.acc)
                "_fold($iterable, $init, lambda $acc, $x: ${expr(v.body)})"
            }
        }

        is PortValue -> if (v.port.isNext) "_PORT_NEXT" else "_port_${v.port.name}"
        is PortRefValue -> "_PortRef(${expr(v.child)}, ${expr(PortValue(v.port))})"
        is BoundCheck -> "_s.bound(${expr(v.port)})"
        is FlowGraphRef -> gid(v.graph.name)

        is Match -> match(v)
    }

    private fun builtin(b: Builtin): String {
        val r = b.receiver?.let { expr(it) }
        val a = b.args.map { expr(it) }
        return when (b.name) {
            "int.str" -> "str($r)"
            "float.str" -> "_show_float($r)"
            "bool.str" -> "(\"true\" if $r else \"false\")"
            "str.toInt" -> "_to_int($r)"
            "str.toFloat" -> "_to_float($r)"
            "str.indexOf" -> "$r.find(${a[0]})"
            "str.startsWith" -> "$r.startswith(${a[0]})"
            "str.endsWith" -> "$r.endswith(${a[0]})"
            "str.replace" -> "_replace($r, ${a[0]}, ${a[1]})"
            "str.upper" -> "$r.upper()"
            "str.lower" -> "$r.lower()"
            "str.trim" -> "$r.strip()"
            "str.split" -> "_split($r, ${a[0]})"
            "str.code" -> "ord(_char_at($r, ${a[0]}))"
            "str.utf8" -> "list($r.encode(\"utf-8\"))"
            "str.unescape" -> "_unescape($r)"
            "char" -> "chr(${a[0]})"
            "str.get" -> "_char_at($r, ${a[0]})"
            "str.slice", "List.slice" -> "$r[${a[0]}:${a[1]}]"
            "str.contains" -> "(${a[0]} in $r)"
            "range" -> "list(range(${a[0]}, ${a[1]}))"
            "List.indexOf" -> "_index_of($r, ${a[0]})"
            "List.reversed" -> "$r[::-1]"
            "List.toSet" -> "_set(*$r)"
            "List.join" -> "${a[0]}.join($r)"
            "Map.keys" -> "list($r.keys())"
            "Map.values" -> "list($r.values())"
            "Map.remove" -> "_map_remove($r, ${a[0]})"
            "Set.toList" -> "list($r)"
            "Set.remove" -> "_set_remove($r, ${a[0]})"
            "Set.of" -> "_set(${a.joinToString(", ")})"
            "Set.contains" -> "_in_map($r, ${a[0]})"
            "Set.union" -> "_set_union($r, ${a[0]})"
            else -> throw IllegalStateException("unknown builtin ${b.name}")
        }
    }

    private fun call(v: Call): String {
        val fn = v.target
        val owner = fn.receiver
        val receiver = v.receiver
        return when {
            owner is ParserType -> "${gid(owner.name)}.${id(fn.name)}(${args(v.args)})"
            owner is FlowGraphType || (owner is ComplexType && owner.name == GRAPH) ->
                "${expr(receiver!!)}.${fn.name}(${args(v.args)})"
            owner == null && fn.body == null && fn.name in setOf("graphOf", "spanOf") -> "${fn.name}(${args(v.args)})"
            receiver != null -> "${functionId(fn)}(${(listOf(receiver) + v.args).joinToString(", ") { expr(it) }})"
            else -> "${functionId(fn)}(${args(v.args)})"
        }
    }

    private val patterns = object : TargetSupport.Patterns {
        override fun fresh(): String = names.fresh("m")
        override fun isItem(subject: String, item: EnumItem): String = "isinstance($subject, _${item.enumName}_${item.itemName})"
        override fun itemField(subject: String, item: EnumItem, field: String): String = "$subject.${id(field)}"
        override fun sizeIs(subject: String, size: Int): String = "len($subject) == $size"
        override fun notEmpty(subject: String): String = "len($subject) > 0"
        override fun element(subject: String, index: Int): String = "$subject[$index]"
        override fun tail(subject: String): String = "$subject[1:]"
        override fun equalTo(subject: String, value: Value): String = "$subject == ${expr(value)}"
        override fun bindVariable(variable: LocalRef): String = names.bind(variable.name)
    }

    /** `_match(subject, [lambda: <case or _NOMATCH>, ...], alternative)` */
    private fun match(m: Match): String {
        val scrutinee = expr(m.scrutinee)
        return names.scoped {
            val subject = names.fresh("subject")
            val cases = m.cases.map { case ->
                names.scoped {
                    val steps = s.steps(case.pattern, subject, patterns)
                    val guard = case.guard?.let { expr(it) }
                    val body = expr(case.body)
                    var result = if (guard != null) "($body if $guard else _NOMATCH)" else body
                    for (step in steps.reversed()) {
                        result = when (step) {
                            is TargetSupport.Step.Test -> "($result if ${step.cond} else _NOMATCH)"
                            is TargetSupport.Step.Bind -> "(lambda ${step.name}: $result)(${step.value})"
                        }
                    }
                    "lambda: $result"
                }
            }
            val alt = m.alt?.let { "lambda: ${expr(it)}" } ?: "None"
            "(lambda $subject: _match($subject, [${cases.joinToString(", ")}], $alt))($scrutinee)"
        }
    }
}
