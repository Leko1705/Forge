package com.leko.forge.gen

import com.leko.forge.context.Context
import com.leko.forge.llir.*
import com.leko.forge.llir.Function
import com.leko.forge.model.GRAPH
import com.leko.forge.types.*

/**
 * Generates one JavaScript file, an ES module (ECMAScript 2020) that runs in browsers
 * (`<script type="module">`) and in Node.js, and needs nothing but the language.
 *
 * - nodes become classes; interface nodes become objects that work with `instanceof`
 *   (`x instanceof Expr`); attributes are getters: `node.type`
 * - an attribute is a function (`attr_type(node)`) that dispatches on the class of the node
 * - functions become functions (methods are named `Receiver_name`); `ext fun`s are imported from the
 *   sibling module `./<module>_externals.js`, e.g. `export function int_text(self) { return String(self); }`
 * - parsers become objects with a function per rule: `Calc.program(source)`
 * - `int` is a number (32 bits, wrapping like the JVM), `float` a number rounded to 32 bits, lists are
 *   arrays, maps and sets classes of the runtime that compare keys by value
 *
 * The module exports the declarations of the program, `ForgeError`, `ParseException`, `Graph`, `Edge`,
 * `Span`, `Vertex`, `graphOf` and `spanOf`.
 */
object JavaScriptTarget : Target {
    override val name: String get() = "javascript"
    override val extension: String get() = ".js"

    override fun generate(module: LLIRModule, context: Context): ByteArray =
        JavaScriptGeneration(module, moduleName(module, context)).run().toByteArray()

    private fun moduleName(module: LLIRModule, context: Context): String {
        val out = com.leko.forge.utils.Options.instance(context).get("-o")?.firstOrNull() ?: module.sourceName ?: "out"
        return java.io.File(out).nameWithoutExtension
    }
}

private val JS_KEYWORDS = setOf(
    "break", "case", "catch", "class", "const", "continue", "debugger", "default", "delete", "do", "else", "enum",
    "export", "extends", "false", "finally", "for", "function", "if", "import", "in", "instanceof", "new", "null",
    "return", "super", "switch", "this", "throw", "true", "try", "typeof", "var", "void", "while", "with", "yield",
    "let", "static", "implements", "interface", "package", "private", "protected", "public", "await", "async",
    "arguments", "eval", "undefined", "NaN", "Infinity",
)

/** Global names must not hide the globals and the public names of the runtime. */
private val JS_GLOBALS = setOf(
    "Object", "Array", "String", "Number", "Boolean", "Symbol", "Math", "JSON", "Map", "Set", "WeakMap", "Error",
    "RegExp", "Date", "Promise", "Reflect", "Proxy", "Function", "TextEncoder", "Uint8Array", "Float32Array",
    "ArrayBuffer", "BigInt", "TypeError", "RangeError", "globalThis", "window", "document", "console", "self",
    "ForgeError", "ParseException", "constructor", "prototype",
)

private class JavaScriptGeneration(private val module: LLIRModule, private val moduleName: String) {
    private val s = TargetSupport(module)
    private val names = Names(JS_KEYWORDS)
    private val out = StringBuilder()
    private val exports = mutableListOf<String>()

    private fun id(name: String) = names.id(name)
    private fun gid(name: String) = if (name in JS_GLOBALS || name in JS_KEYWORDS) name + "_" else name
    private fun line(text: String = "") { out.append(text).append('\n') }

    fun run(): String {
        line("// Generated by Forge${module.sourceName?.let { " from ${java.io.File(it).name}" } ?: ""}. Do not edit.")
        val externals = module.functions.filter { it.body == null && !isBuiltinFunction(it) }.map { functionId(it) }.distinct()
        if (externals.isNotEmpty()) {
            line("import { ${externals.joinToString(", ")} } from \"./${moduleName}_externals.js\";")
            line()
        }
        line(runtimeResource("javascript.js"))
        exports += listOf("ForgeError", "ParseException", "Graph", "Edge", "Span", "Vertex", "graphOf", "spanOf")
        generateTypes()
        generateAttributes()
        module.functions.forEach { generateFunction(it) }
        module.graphs.forEach { generateGraph(it) }
        module.parsers.forEach { generateParser(it) }
        generateProperties()
        line("export { ${exports.distinct().joinToString(", ")} };")
        return out.toString()
    }

    private fun isBuiltinFunction(fn: Function) = fn.receiver == null && fn.name in setOf("graphOf", "spanOf")

    // ---- declarations ------------------------------------------------------------------------------

    private fun className(node: Node): String = if (node === s.vertex) "Vertex" else gid(node.name)

    /** How a field is shown: 1 for floats, 2 for lists and sets of floats, else 0. */
    private fun kind(type: Type): Int = when {
        type is OptionalType -> kind(type.elem)
        type == FloatType -> 1
        type is ListType && kind(type.elem) == 1 -> 2
        type is SetType && kind(type.elem) == 1 -> 2
        else -> 0
    }

    private fun fieldInfo(cls: String, name: String, fields: Map<String, Type>) {
        line("$cls.prototype.\$name = ${string(name)};")
        line("$cls.prototype.\$fields = [${fields.keys.joinToString(", ") { string(it) }}];")
        line("$cls.prototype.\$kinds = [${fields.values.joinToString(", ") { kind(it).toString() }}];")
    }

    private fun constructor(fields: Collection<String>, superCall: Boolean, adopt: Boolean) {
        val params = fields.indices.map { "a$it" }
        line("    constructor(${params.joinToString(", ")}) {")
        if (superCall) line("        super();")
        fields.forEachIndexed { i, f -> line("        this[${string(f)}] = a$i;") }
        if (adopt) line("        this.\$adopt();")
        line("    }")
    }

    private fun generateTypes() {
        for (node in s.interfaces) {
            val cls = gid(node.name)
            line("class $cls {")
            line("    static [Symbol.hasInstance](x) { return x != null && x.\$is_${node.name} === true; }")
            line("}")
            exports += cls
        }
        for (node in s.concrete) {
            val cls = gid(node.name)
            line("class $cls extends \$Node {")
            constructor(node.fields.keys, superCall = true, adopt = true)
            line("}")
            fieldInfo(cls, node.name, node.fields)
            for (parent in node.ancestors()) if (parent !== s.vertex) line("$cls.prototype.\$is_${parent.name} = true;")
            exports += cls
        }
        for (enum in module.enums) {
            val cls = gid(enum.name)
            line("class $cls extends \$EnumItem {}")
            for (item in enum.items) {
                val itemClass = "\$${enum.name}_${item.itemName}"
                line("class $itemClass extends $cls {")
                if (item.fields.isNotEmpty()) constructor(item.fields.keys, superCall = true, adopt = false)
                line("}")
                fieldInfo(itemClass, item.itemName, item.fields)
                line("\$def($cls, ${string(item.itemName)}, ${if (item.fields.isEmpty()) "new $itemClass()" else itemClass});")
            }
            exports += cls
        }
        for (record in module.records) {
            if (s.isBuiltinRecord(record.name)) continue
            val cls = gid(record.name)
            line("class $cls extends \$Record {")
            constructor(record.fields.keys, superCall = true, adopt = false)
            line("}")
            fieldInfo(cls, record.name, record.fields)
            exports += cls
        }
        for (port in module.ports) {
            if (!port.isNext) line("const \$port_${port.name} = new \$Port(${string(port.name)}, ${port.inherited});")
        }
        line()
    }

    // ---- attributes --------------------------------------------------------------------------------

    /** The concrete classes and the vertices of the runtime, each with the node that declares its equations. */
    private fun dispatchTargets(): List<Pair<String, Node>> =
        s.concrete.map { gid(it.name) to it } + listOf("\$ExitVertex" to s.vertex, "\$SyntheticVertex" to s.vertex)

    private fun generateAttributes() {
        for (name in s.attributeNames) {
            line("const \$cache_syn_$name = new \$Cache(${string(name)});")
            line("const \$circ_$name = new \$Circular();")
        }
        for (name in module.inherited.keys) line("const \$cache_inh_$name = new \$Cache(${string(name)});")
        for (name in s.collectionNames) line("const \$cache_coll_$name = new \$Cache(${string(name)});")
        line()

        for (name in s.attributeNames) {
            for ((cls, node) in dispatchTargets()) {
                val eq = s.equation(node, name) ?: continue
                val fn = "\$syn_${name}_$cls"
                line("function $fn(self) {")
                when (eq) {
                    is TargetSupport.Equation.Syn -> line("    return \$cache_syn_$name.get(self, () => ${body(eq.body)});")
                    is TargetSupport.Equation.Circular ->
                        line("    return \$circ_$name.get(self, ${body(eq.attr.init)}, () => ${body(eq.attr.body)});")
                    TargetSupport.Equation.Missing -> line("    throw new ForgeError(\"attribute '$name' is not defined for \" + \$show(self));")
                }
                line("}")
                line("$cls.prototype.\$syn_$name = $fn;")
            }
            line("function attr_$name(n) {")
            line("    const f = n.\$syn_$name;")
            line("    if (f === undefined) throw new ForgeError(\"attribute '$name' is not defined for \" + \$show(n));")
            line("    return f(n);")
            line("}")
            line()
            exports += "attr_$name"
        }

        for (inh in module.inherited.values) {
            val name = inh.name
            line("function inh_$name(n) {")
            line("    return \$cache_inh_$name.get(n, () => n.\$parent === null ? ${body(inh.init, "n")} : \$pass_$name(n.\$parent, n));")
            line("}")
            for (node in s.concrete) {
                val eq = node.inhEquations[name] ?: continue
                val cls = gid(node.name)
                val fn = "\$pass_${name}_${node.name}"
                line("function $fn(self, child) {")
                names.scoped {
                    names.alias("this", "self")
                    for (d in eq.delegates) {
                        val field = "self[${string(d.field)}]"
                        val key = d.key
                        if (key == null || node.fields[d.field] !is ListType) {
                            line("    if (child === $field) return ${expr(d.value)};")
                        } else {
                            val index = names.fresh("index")
                            line("    const $index = $field.indexOf(child);")
                            line("    if ($index >= 0) {")
                            val binder = d.binder
                            if (binder != null) {
                                names.scoped {
                                    val b = names.bind(binder.name)
                                    line("        for (let $b = 0; $b < $field.length; $b++) {")
                                    line("            if (${expr(key)} === $index) return ${expr(d.value)};")
                                    line("        }")
                                }
                            } else {
                                line("        if (${expr(key)} === $index) return ${expr(d.value)};")
                            }
                            line("    }")
                        }
                    }
                }
                line("    return inh_$name(self);")
                line("}")
                line("$cls.prototype.\$pass_$name = $fn;")
            }
            line("function \$pass_$name(parent, child) {")
            line("    const f = parent.\$pass_$name;")
            line("    return f === undefined ? inh_$name(parent) : f(parent, child);")
            line("}")
            line()
            exports += "inh_$name"
        }

        for (name in s.collectionNames) {
            for (node in s.concrete) {
                val coll = node.collections[name] ?: continue
                val cls = gid(node.name)
                val fn = "\$coll_${name}_${node.name}"
                line("function $fn(self) {")
                line("    return \$cache_coll_$name.get(self, () => {")
                line("        let acc = ${body(coll.init)};")
                if (coll.contributions.isNotEmpty()) {
                    line("        for (const n of \$preorder(self.\$root())) {")
                    for (c in coll.contributions) {
                        names.scoped {
                            names.alias("this", "n")
                            line("            if (${isTest(ComplexType(c.source.name), "n")} && ${expr(c.target)} === self) {")
                            names.scoped {
                                val alias = names.bind(c.alias)
                                line("                const $alias = acc;")
                                line("                acc = ${expr(c.value)};")
                            }
                            line("            }")
                        }
                    }
                    line("        }")
                }
                line("        return acc;")
                line("    });")
                line("}")
                line("$cls.prototype.\$coll_$name = $fn;")
            }
            line("function coll_$name(n) {")
            line("    const f = n.\$coll_$name;")
            line("    if (f === undefined) throw new ForgeError(\"collection '$name' is not defined for \" + \$show(n));")
            line("    return f(n);")
            line("}")
            line()
            exports += "coll_$name"
        }
    }

    /** An attribute equation: `this` is [self]. */
    private fun body(v: Value, self: String = "self"): String = names.scoped {
        names.alias("this", self)
        expr(v)
    }

    /** Getters, so that attributes read like fields: `node.type`. A field of the same name comes first. */
    private fun generateProperties() {
        fun getter(cls: String, node: Node?, name: String, fn: String) {
            if (node != null && name in node.fields) return
            line("\$getter($cls.prototype, ${string(name)}, $fn);")
        }
        for (name in s.attributeNames) {
            for ((cls, node) in dispatchTargets()) {
                if (s.equation(node, name) != null) getter(cls, node.takeIf { it !== s.vertex }, name, "attr_$name")
            }
        }
        for (name in s.collectionNames) {
            for (node in s.concrete) if (name in node.collections) getter(gid(node.name), node, name, "coll_$name")
        }
        for (name in module.inherited.keys) {
            for (node in s.concrete) getter(gid(node.name), node, name, "inh_$name")
        }
        line()
    }

    // ---- functions ---------------------------------------------------------------------------------

    private fun functionId(fn: Function): String = gid(s.functionName(fn))

    private fun generateFunction(fn: Function) {
        val body = fn.body ?: return
        names.scoped {
            val params = mutableListOf<String>()
            if (fn.receiver != null) {
                params += "self"
                names.alias("this", "self")
            }
            for (p in fn.parameters) params += names.bind(p.name)
            line("function ${functionId(fn)}(${params.joinToString(", ")}) {")
            line("    return ${expr(body)};")
            line("}")
            line()
        }
        exports += functionId(fn)
    }

    // ---- graphs ------------------------------------------------------------------------------------

    private fun generateGraph(graph: FlowGraphDecl) {
        line("function \$flow_${graph.name}(\$s, n) {")
        for (rule in s.flowRules(graph)) {
            line("    if (${isTest(ComplexType(rule.node.name), "n")}) {")
            names.scoped {
                names.alias("this", "n")
                for ((local, field) in rule.binders) {
                    val v = names.bind(local)
                    line("        const $v = n[${string(field)}];")
                }
                rule.body.forEach { flowStmt(it, "        ") }
            }
            line("        return true;")
            line("    }")
        }
        line("    return false;")
        line("}")
        line("const ${gid(graph.name)} = new \$FlowGraph(x => ${isTest(ComplexType(graph.root.name), "x")}, \$flow_${graph.name});")
        line()
        exports += gid(graph.name)
    }

    private fun flowStmt(stmt: FlowStmt, indent: String) {
        when (stmt) {
            is FlowEntry -> line("$indent\$s.entry(${expr(stmt.target)});")
            is FlowConnect -> line("$indent\$s.connect(${expr(stmt.source)}, ${expr(stmt.target)}, ${stmt.label?.let { expr(it) } ?: "null"});")
            is FlowSequence -> line("$indent\$s.sequence(${expr(stmt.items)});")
            is FlowVertex -> {
                val label = stmt.label?.let { expr(it) } ?: string(stmt.name)
                val v = names.bind(stmt.name)
                line("${indent}const $v = \$s.vertex(new \$SyntheticVertex($label, n));")
            }
            is FlowIf -> {
                line("${indent}if (${expr(stmt.cond)}) {")
                names.scoped { stmt.then.forEach { flowStmt(it, "$indent    ") } }
                line("$indent} else {")
                names.scoped { stmt.alt.forEach { flowStmt(it, "$indent    ") } }
                line("$indent}")
            }
            is FlowFor -> {
                val iterable = expr(stmt.iterable)
                names.scoped {
                    val v = names.bind(stmt.name)
                    line("${indent}for (const $v of $iterable) {")
                    stmt.body.forEach { flowStmt(it, "$indent    ") }
                    line("$indent}")
                }
            }
        }
    }

    // ---- parsers -----------------------------------------------------------------------------------

    private var terminalNames: Map<GTerminal, String> = emptyMap()
    private var bitNames: Map<GBits, String> = emptyMap()
    private var parserName = ""

    private fun generateParser(parser: ParserDecl) {
        val p = gid(parser.name)
        parserName = parser.name
        terminalNames = s.terminals(parser).withIndex().associate { (i, t) -> t to "\$${parser.name}_t$i" }
        bitNames = s.bitPatterns(parser).withIndex().associate { (i, b) -> b to "\$${parser.name}_b$i" }
        val skip = parser.skip?.let { val (source, flags) = jsRegex(it); "\$regex(${string(source)}, ${string(flags)})" } ?: "null"
        line("const $p = {};")
        line("const \$${parser.name}_skip = $skip;")
        line("const \$${parser.name}_keywords = new Set([${parser.keywords.joinToString(", ") { string(it) }}]);")
        for ((t, n) in terminalNames) {
            val (source, flags) = jsRegex(t.regex)
            line("const $n = new \$Terminal(${string(source)}, ${string(flags)}, ${t.literal?.let { string(it) } ?: "null"}, ${string(s.display(t))});")
        }
        for ((b, n) in bitNames) line("const $n = new \$Bits(${string(b.bits)}, ${string(b.description)});")
        for (rule in parser.rules.values) {
            val r = ruleRef(rule.name)
            if (rule.isAbstract) {
                line("const $r = new \$AbstractRule(${string(rule.name)});")
            } else {
                line("const $r = new \$Rule(${string(rule.name)}, \$s => ${alternative(rule.alternatives.single(), null)});")
            }
        }
        for (rule in parser.rules.values.filter { it.isAbstract }) {
            val r = ruleRef(rule.name)
            for (alt in rule.alternatives) {
                when (alt.operator) {
                    null -> line("$r.on(\$s => ${alternative(alt, null)});")
                    OperatorKind.PREFIX -> line("$r.prefix(${alt.precedence}, \$s => ${alternative(alt, null)});")
                    else -> {
                        val method = when (alt.operator) {
                            OperatorKind.INFIX_LEFT -> "infixLeft"
                            OperatorKind.INFIX_RIGHT -> "infixRight"
                            else -> "postfix"
                        }
                        line("$r.$method(${alt.precedence}, (\$s, \$left) => ${alternative(alt, "\$left")});")
                    }
                }
            }
        }
        for (rule in parser.rules.values) {
            val entry = if (parser.binary) "\$parseBinary" else "\$parseText"
            line("\$def($p, ${string(rule.name)}, (source, sourceName = null) => $entry(${ruleRef(rule.name)}, source, \$${parser.name}_skip, \$${parser.name}_keywords, sourceName));")
        }
        line()
        exports += p
    }

    private fun ruleRef(rule: String) = "\$${parserName}_r_$rule"

    private var left: String? = null

    private fun alternative(alt: GrammarAlternative, leftName: String?): String {
        left = leftName
        val options = alt.options.map { option(it) }
        return options.singleOrNull() ?: "\$s.oneOf(${options.joinToString(", ") { "() => $it" }})"
    }

    /** Labels are cells, created when the option starts; the producer reads them. */
    private fun option(option: GrammarOption): String = names.scoped {
        val cells = option.labels.map { (name, _) ->
            val cell = names.fresh("label_$name")
            names.alias(name, "$cell.get()")
            name to cell
        }
        val labelCells = cells.toMap()
        val body = grammar(option.body, labelCells)
        val inner = if (option.producer == null) body else "($body, ${expr(option.producer!!)})"
        if (cells.isEmpty()) inner
        else "((${cells.joinToString(", ") { "${it.second} = new \$Label(${string(it.first)})" }}) => $inner)()"
    }

    private fun grammar(e: GExpr, labels: Map<String, String>): String = when (e) {
        is GTerminal -> "\$s.terminal(${terminalNames.getValue(e)})"
        is GBits -> "\$s.bits(${bitNames.getValue(e)})"
        is GPrimitive -> "\$s.${e.name}(${e.argument?.let { expr(it) } ?: ""})"
        is GNonterminal -> when (e.role) {
            NonterminalRole.RULE -> "\$s.apply(${ruleRef(e.rule)})"
            NonterminalRole.LEFT -> left ?: "null"
            NonterminalRole.OPERAND -> "\$s.operand()"
        }
        is GRepeat -> {
            val body = "() => ${grammar(e.expr, labels)}"
            when (e.kind) {
                RepeatKind.OPTIONAL -> "\$s.optional($body)"
                RepeatKind.MANY -> "\$s.many($body)"
                RepeatKind.SOME -> "\$s.some($body)"
                RepeatKind.COUNT -> "\$s.repeat(${expr(e.count!!)}, $body)"
            }
        }
        is GPredicate -> if (e.negate) "\$s.notP(${string(s.describe(e.expr))}, () => ${grammar(e.expr, labels)})"
            else "\$s.andP(() => ${grammar(e.expr, labels)})"
        is GChoice -> "\$s.oneOf(${e.alternatives.joinToString(", ") { "() => ${grammar(it, labels)}" }})"
        is GSequence -> {
            val items = e.items.joinToString(", ") { item ->
                "[() => ${grammar(item.expr, labels)}, ${item.label?.let { labels.getValue(it) } ?: "null"}]"
            }
            "\$s.seq([$items], ${e.valueIndex?.toString() ?: "null"})"
        }
    }

    // ---- values ------------------------------------------------------------------------------------

    private fun bin(v: BinaryValue, op: String) = "(${expr(v.lhs)} $op ${expr(v.rhs)})"
    private fun args(values: List<Value>) = values.joinToString(", ") { expr(it) }

    /** Whether the value of the variable [v] is of [type]. */
    private fun isTest(type: Type, v: String): String = when {
        type is OptionalType -> "($v === null || ${isTest(type.elem, v)})"
        type == IntType || type == FloatType -> "(typeof $v === \"number\")"
        type == BoolType -> "(typeof $v === \"boolean\")"
        type == StrType -> "(typeof $v === \"string\")"
        type is ListType -> "Array.isArray($v)"
        type is SetType -> "($v instanceof \$Set)"
        type is MapType -> "($v instanceof \$Map)"
        type is ComplexType -> {
            val node = s.nodeOf(type)
            when {
                node === s.vertex -> "($v != null && $v.\$is_Vertex === true)"
                node != null && node.isInterface -> "($v != null && $v.\$is_${node.name} === true)"
                node != null -> "($v instanceof ${className(node)})"
                else -> "($v instanceof ${gid(type.name)})"
            }
        }
        else -> "true"
    }

    private fun let(value: String, name: String, body: (String) -> String): String = names.scoped {
        val v = names.bind(name)
        "(($v) => ${body(v)})($value)"
    }

    private fun float(value: Double): String = when {
        value.isNaN() -> "NaN"
        value == Double.POSITIVE_INFINITY -> "Infinity"
        value == Double.NEGATIVE_INFINITY -> "-Infinity"
        else -> "Math.fround(${value})"
    }

    fun expr(v: Value): String = when (v) {
        is IntValue -> if (v.value < 0) "(${v.value})" else v.value.toString()
        is FloatValue -> float(v.value.toDouble())
        is BoolValue -> if (v.value) "true" else "false"
        is StringValue -> string(v.value)
        NullValue -> "null"

        is Parameter -> names.lookup(v.name)
        is LocalRef -> names.lookup(v.name)
        is This -> names.lookup("this")
        is AccessParentInhAttr -> "inh_${v.name}(${names.lookup("this")})"

        is ListLiteral -> "[${args(v.list)}]"
        is MapLiteral -> "\$map([${v.entries.joinToString(", ") { (k, x) -> "[${expr(k)}, ${expr(x)}]" }}])"

        is Call -> call(v)
        is CreateRecord -> "new ${gid(v.target.name)}(${args(v.args)})"
        is CreateEnum -> if (v.target.fields.isEmpty()) "${gid(v.target.enumName)}[${string(v.target.itemName)}]"
            else "new \$${v.target.enumName}_${v.target.itemName}(${args(v.args)})"
        is CreateNode -> "new ${gid(v.target.name)}(${args(v.args)})"

        is AccessRecordField -> when {
            v.name == "size" && v.target.name in setOf("List", "str") -> "${expr(v.accessed)}.length"
            v.name == "size" && v.target.name in setOf("Map", "Set") -> "${expr(v.accessed)}.size"
            else -> "${expr(v.accessed)}[${string(v.name)}]"
        }
        is AccessNodeField -> "${expr(v.accessed)}[${string(v.name)}]"
        is AccessNodeAttr -> when {
            v.name in module.inherited -> "inh_${v.name}(${expr(v.receiver)})"
            v.name in s.collectionNames && v.name !in s.attributeNames -> "coll_${v.name}(${expr(v.receiver)})"
            else -> "attr_${v.name}(${expr(v.receiver)})"
        }
        is AccessListContainer -> "\$get(${expr(v.container)}, ${expr(v.key)})"
        is AccessMapContainer -> "${expr(v.container)}.at(${expr(v.key)})"

        is Int2Float -> "Math.fround(${expr(v.value)})"
        is Float2Int -> "\$f2i(${expr(v.value)})"
        is Cast -> {
            val type = v.type
            if (type is ComplexType && type.name in s.nodeNames) let(expr(v.value), "cast") { x ->
                "(${isTest(type, x)} ? $x : \$panic(\"can not cast \" + \$show($x) + \" to ${type.name}\"))"
            } else expr(v.value)
        }
        is IsInstanceOf -> let(expr(v.value), "x") { x -> isTest(v.target, x) }

        is NegateInt -> "((-${expr(v.value)}) | 0)"
        is NegateFloat -> "Math.fround(-${expr(v.value)})"
        is InvertBool -> "(!${expr(v.value)})"
        is InvertInt -> "(~${expr(v.value)})"
        is IsNull -> "(${expr(v.checked)} === null)"
        is NotNull -> "\$nn(${expr(v.value)})"
        is Elvis -> let(expr(v.value), "elvis") { x -> "($x === null ? ${expr(v.alt)} : $x)" }

        is MulInt -> "Math.imul(${expr(v.lhs)}, ${expr(v.rhs)})"
        is DivInt -> "\$div(${expr(v.lhs)}, ${expr(v.rhs)})"
        is ModInt -> "\$mod(${expr(v.lhs)}, ${expr(v.rhs)})"
        is AddInt -> "((${expr(v.lhs)} + ${expr(v.rhs)}) | 0)"
        is SubInt -> "((${expr(v.lhs)} - ${expr(v.rhs)}) | 0)"
        is AndInt, is IAnd -> bin(v as BinaryValue, "&")
        is OrInt, is IOr -> bin(v as BinaryValue, "|")
        is XorInt -> bin(v, "^")
        is ShlInt -> bin(v, "<<")
        is ShrInt -> bin(v, ">>")
        is UshrInt -> "((${expr(v.lhs)} >>> ${expr(v.rhs)}) | 0)"
        is SetEquals -> "\$eq(${expr(v.lhs)}, ${expr(v.rhs)})"
        is Builtin -> builtin(v)
        is MulFloat -> "Math.fround(${expr(v.lhs)} * ${expr(v.rhs)})"
        is DivFloat -> "Math.fround(${expr(v.lhs)} / ${expr(v.rhs)})"
        is AddFloat -> "Math.fround(${expr(v.lhs)} + ${expr(v.rhs)})"
        is SubFloat -> "Math.fround(${expr(v.lhs)} - ${expr(v.rhs)})"
        is LtInt, is LtFloat -> bin(v as BinaryValue, "<")
        is GtInt, is GtFloat -> bin(v as BinaryValue, ">")
        is LeqInt, is LeqFloat -> bin(v as BinaryValue, "<=")
        is GeqInt, is GeqFloat -> bin(v as BinaryValue, ">=")
        is AndBool -> bin(v, "&&")
        is OrBool -> bin(v, "||")
        is XorBool -> bin(v, "!==")
        is IntEquals, is FloatEquals, is BoolEquals, is StringEquals, is NodeEquals -> bin(v as BinaryValue, "===")
        is ListEquals, is MapEquals, is EnumEquals, is RecordEquals -> "\$eq(${expr((v as BinaryValue).lhs)}, ${expr(v.rhs)})"
        is ConcatStr -> bin(v, "+")
        is MergeLists -> "${expr(v.lhs)}.concat(${expr(v.rhs)})"
        is MergeMaps -> "${expr(v.lhs)}.merge(${expr(v.rhs)})"

        is InList -> "\$inList(${expr(v.list)}, ${expr(v.element)})"
        is InMapKeys -> "${expr(v.map)}.has(${expr(v.key)})"
        is AppendListItem -> "${expr(v.list)}.concat([${expr(v.element)}])"
        is AppendAllListItems -> "${expr(v.list)}.concat(${expr(v.elements)})"
        is PutMapItem -> "${expr(v.map)}.put(${expr(v.key)}, ${expr(v.value)})"
        is PutAllMapItems -> "${expr(v.map)}.merge(${expr(v.elements)})"

        is IfElse -> "(${expr(v.cond)} ? ${expr(v.then)} : ${expr(v.alt)})"
        is Panic -> "\$panic(${string(v.message)})"

        is MapOp -> {
            val iterable = expr(v.iterable)
            names.scoped {
                val x = names.bind(v.name)
                "Array.from($iterable, ($x) => ${expr(v.body)})"
            }
        }
        is FoldOp -> {
            val iterable = expr(v.iterable)
            val init = expr(v.initAcc)
            names.scoped {
                val x = names.bind(v.item)
                val acc = names.bind(v.acc)
                "\$fold($iterable, $init, ($acc, $x) => ${expr(v.body)})"
            }
        }

        is PortValue -> if (v.port.isNext) "\$PORT_NEXT" else "\$port_${v.port.name}"
        is PortRefValue -> "new \$PortRef(${expr(v.child)}, ${expr(PortValue(v.port))})"
        is BoundCheck -> "\$s.bound(${expr(v.port)})"
        is FlowGraphRef -> gid(v.graph.name)

        is Match -> match(v)
    }

    private fun builtin(b: Builtin): String {
        val r = b.receiver?.let { expr(it) }
        val a = b.args.map { expr(it) }
        return when (b.name) {
            "int.str" -> "String($r)"
            "float.str" -> "\$showFloat($r)"
            "bool.str" -> "String($r)"
            "str.toInt" -> "\$toInt($r)"
            "str.toFloat" -> "\$toFloat($r)"
            "str.indexOf" -> "$r.indexOf(${a[0]})"
            "str.startsWith" -> "$r.startsWith(${a[0]})"
            "str.endsWith" -> "$r.endsWith(${a[0]})"
            "str.replace" -> "\$replace($r, ${a[0]}, ${a[1]})"
            "str.upper" -> "$r.toUpperCase()"
            "str.lower" -> "$r.toLowerCase()"
            "str.trim" -> "$r.trim()"
            "str.split" -> "\$split($r, ${a[0]})"
            "str.code" -> "\$code($r, ${a[0]})"
            "str.utf8" -> "\$utf8($r)"
            "str.unescape" -> "\$unescape($r)"
            "char" -> "String.fromCodePoint(${a[0]})"
            "fail" -> "\$panic(${a[0]})"
            "str.get" -> "\$charAt($r, ${a[0]})"
            "str.slice", "List.slice" -> "\$slice($r, ${a[0]}, ${a[1]})"
            "str.contains" -> "$r.includes(${a[0]})"
            "range" -> "\$range(${a[0]}, ${a[1]})"
            "List.indexOf" -> "\$indexOf($r, ${a[0]})"
            "List.reversed" -> "$r.slice().reverse()"
            "List.toSet" -> "\$setOf($r)"
            "List.join" -> "$r.join(${a[0]})"
            "Map.keys" -> "$r.keys()"
            "Map.values" -> "$r.values()"
            "Map.remove" -> "$r.remove(${a[0]})"
            "Set.toList" -> "$r.toList()"
            "Set.remove" -> "$r.remove(${a[0]})"
            "Set.of" -> "\$setOf([${a.joinToString(", ")}])"
            "Set.contains" -> "$r.has(${a[0]})"
            "Set.union" -> "$r.union(${a[0]})"
            else -> throw IllegalStateException("unknown builtin ${b.name}")
        }
    }

    private fun call(v: Call): String {
        val fn = v.target
        val owner = fn.receiver
        val receiver = v.receiver
        return when {
            owner is ParserType -> "${gid(owner.name)}[${string(fn.name)}](${args(v.args)})"
            owner is FlowGraphType || (owner is ComplexType && owner.name == GRAPH) ->
                "${expr(receiver!!)}.${fn.name}(${args(v.args)})"
            owner == null && fn.body == null && fn.name in setOf("graphOf", "spanOf") -> "${fn.name}(${args(v.args)})"
            receiver != null -> "${functionId(fn)}(${(listOf(receiver) + v.args).joinToString(", ") { expr(it) }})"
            else -> "${functionId(fn)}(${args(v.args)})"
        }
    }

    private val patterns = object : TargetSupport.Patterns {
        override fun fresh(): String = names.fresh("m")
        override fun isItem(subject: String, item: EnumItem): String = "($subject instanceof \$${item.enumName}_${item.itemName})"
        override fun itemField(subject: String, item: EnumItem, field: String): String = "$subject[${string(field)}]"
        override fun sizeIs(subject: String, size: Int): String = "$subject.length === $size"
        override fun notEmpty(subject: String): String = "$subject.length > 0"
        override fun element(subject: String, index: Int): String = "$subject[$index]"
        override fun tail(subject: String): String = "$subject.slice(1)"
        override fun equalTo(subject: String, value: Value): String = "\$eq($subject, ${expr(value)})"
        override fun bindVariable(variable: LocalRef): String = names.bind(variable.name)
    }

    /**
     * `((subject) => { c0: { if (!test) break c0; const x = ...; return body; } ...; return alternative; })(scrutinee)`
     */
    private fun match(m: Match): String {
        val scrutinee = expr(m.scrutinee)
        return names.scoped {
            val subject = names.fresh("subject")
            val sb = StringBuilder("(($subject) => { ")
            m.cases.forEachIndexed { i, case ->
                names.scoped {
                    val label = names.fresh("case")
                    sb.append("$label: { ")
                    for (step in s.steps(case.pattern, subject, patterns)) {
                        when (step) {
                            is TargetSupport.Step.Test -> sb.append("if (!(${step.cond})) break $label; ")
                            is TargetSupport.Step.Bind -> sb.append("const ${step.name} = ${step.value}; ")
                        }
                    }
                    case.guard?.let { sb.append("if (!(${expr(it)})) break $label; ") }
                    sb.append("return ${expr(case.body)}; } ")
                }
            }
            sb.append(m.alt?.let { "return ${expr(it)}; " } ?: "return \$noMatch($subject); ")
            sb.append("})($scrutinee)")
            sb.toString()
        }
    }
}

/** A JavaScript string literal. */
private fun string(text: String): String = buildString {
    append('"')
    for (c in text) {
        when {
            c == '\\' -> append("\\\\")
            c == '"' -> append("\\\"")
            c == '\n' -> append("\\n")
            c == '\r' -> append("\\r")
            c == '\t' -> append("\\t")
            c.code < 32 || c.code == 127 || c == '\u2028' || c == '\u2029' -> append("\\u%04x".format(c.code))
            else -> append(c)
        }
    }
    append('"')
}

private val POSIX_CLASSES = mapOf(
    "Lower" to "a-z", "Upper" to "A-Z", "ASCII" to "\\x00-\\x7F", "Alpha" to "a-zA-Z", "Digit" to "0-9",
    "Alnum" to "a-zA-Z0-9", "Punct" to "!-\\/:-@\\[-`{-~", "Graph" to "!-~", "Print" to " -~", "Blank" to " \\t",
    "Cntrl" to "\\x00-\\x1F\\x7F", "XDigit" to "0-9a-fA-F", "Space" to " \\t\\n\\x0B\\f\\r",
    "javaLowerCase" to "a-z", "javaUpperCase" to "A-Z", "javaWhitespace" to " \\t\\n\\x0B\\f\\r\\x1C-\\x1F",
    "IsAlphabetic" to "a-zA-Z", "IsLetter" to "a-zA-Z", "IsDigit" to "0-9", "L" to "a-zA-Z", "N" to "0-9",
)

private const val JAVA_SPACE = "\\t\\n\\x0B\\f\\r "
private const val LINE_TERMINATORS = "\\n\\r\\u0085\\u2028\\u2029"

/**
 * A Java regular expression as the source and flags of a JavaScript one, with Java's meaning where the
 * syntax differs: `\s` and `.` as in Java, `$`, `\A`, `\z`, `\Z`, `\Q...\E`, `\p{Alpha}` and the other
 * POSIX classes, `\h`, `\v`, `\R`, `\e`, octal escapes and a leading `(?i)`. Possessive quantifiers and
 * atomic groups are matched like greedy ones, as in the C++, Rust and OCaml targets.
 */
internal fun jsRegex(regex: String): Pair<String, String> {
    var flags = ""
    var source = regex
    if (source.startsWith("(?i)")) {
        flags = "i"
        source = source.substring(4)
    }
    val sb = StringBuilder()
    var i = 0
    var inClass = false
    var afterParen = false
    var afterQuantifier = false
    fun escapeLiteral(c: Char) {
        if (c in "\\^$.|?*+()[]{}/-") sb.append('\\')
        sb.append(c)
    }
    while (i < source.length) {
        val c = source[i]
        when {
            c == '\\' && i + 1 < source.length -> {
                val d = source[i + 1]
                i += 2
                when (d) {
                    'Q' -> {
                        val end = source.indexOf("\\E", i).let { if (it < 0) source.length else it }
                        for (q in source.substring(i, end)) escapeLiteral(q)
                        i = if (end + 2 <= source.length) end + 2 else source.length
                    }
                    'E' -> {}
                    'A' -> sb.append(if (inClass) "A" else "^")
                    'z' -> sb.append(if (inClass) "z" else "(?![\\s\\S])")
                    'Z' -> sb.append(if (inClass) "Z" else "(?=(?:\\r\\n|[$LINE_TERMINATORS])?(?![\\s\\S]))")
                    's' -> sb.append(if (inClass) JAVA_SPACE else "[$JAVA_SPACE]")
                    'S' -> sb.append(if (inClass) "\\S" else "[^$JAVA_SPACE]")
                    'h' -> sb.append(if (inClass) " \\t\\xA0\\u1680\\u180e\\u2000-\\u200a\\u202f\\u205f\\u3000"
                        else "[ \\t\\xA0\\u1680\\u180e\\u2000-\\u200a\\u202f\\u205f\\u3000]")
                    'H' -> sb.append("[^ \\t\\xA0\\u1680\\u180e\\u2000-\\u200a\\u202f\\u205f\\u3000]")
                    'v' -> sb.append(if (inClass) "\\n\\x0B\\f\\r\\x85\\u2028\\u2029" else "[\\n\\x0B\\f\\r\\x85\\u2028\\u2029]")
                    'V' -> sb.append("[^\\n\\x0B\\f\\r\\x85\\u2028\\u2029]")
                    'R' -> sb.append("(?:\\r\\n|[\\n\\x0B\\f\\r\\x85\\u2028\\u2029])")
                    'e' -> sb.append("\\x1B")
                    'a' -> sb.append("\\x07")
                    '0' -> {
                        var digits = ""
                        while (i < source.length && digits.length < 3 && source[i] in '0'..'7') digits += source[i++]
                        val code = digits.ifEmpty { "0" }.toInt(8)
                        sb.append("\\x%02X".format(code and 0xFF))
                    }
                    'x' -> if (source.getOrNull(i) == '{') {
                        val close = source.indexOf('}', i)
                        val code = source.substring(i + 1, close).toInt(16)
                        i = close + 1
                        if (code <= 0xFFFF) sb.append("\\u%04X".format(code))
                        else String(Character.toChars(code)).forEach { sb.append("\\u%04X".format(it.code)) }
                    } else sb.append("\\x")
                    'p', 'P' -> {
                        val name: String
                        if (source.getOrNull(i) == '{') {
                            val close = source.indexOf('}', i)
                            name = source.substring(i + 1, close).removePrefix("Is").let { if (it.isEmpty()) "L" else it }
                            i = close + 1
                        } else {
                            name = source[i].toString()
                            i++
                        }
                        val chars = POSIX_CLASSES[name] ?: POSIX_CLASSES["Is$name"]
                            ?: throw UnsupportedRegexException(regex, "the class \\$d{$name} is not supported")
                        sb.append(when {
                            inClass && d == 'p' -> chars
                            inClass -> throw UnsupportedRegexException(regex, "\\P{$name} in a class is not supported")
                            d == 'p' -> "[$chars]"
                            else -> "[^$chars]"
                        })
                    }
                    else -> sb.append('\\').append(d)
                }
            }
            inClass -> {
                if (c == ']') inClass = false
                if (c == '[' ) sb.append("\\[") else sb.append(c)
                i++
            }
            c == '[' -> {
                inClass = true
                sb.append(c)
                i++
                if (source.getOrNull(i) == '^') { sb.append('^'); i++ }
                if (source.getOrNull(i) == ']') { sb.append("\\]"); i++ }
            }
            c == '.' -> { sb.append("[^$LINE_TERMINATORS]"); i++ }
            c == '$' -> { sb.append("(?=(?:\\r\\n|[$LINE_TERMINATORS])?(?![\\s\\S]))"); i++ }
            c == '/' -> { sb.append("\\/"); i++ }
            c == '(' && source.startsWith("(?>", i) -> { sb.append("(?:"); i += 3 }
            c == '(' -> { sb.append(c); i++; afterParen = true; continue }
            c == '*' || c == '+' || c == '?' -> {
                when {
                    afterParen -> sb.append(c)                       // (?: (?= ...
                    afterQuantifier && c == '+' -> {}                // possessive: matched greedily
                    afterQuantifier && c == '?' -> sb.append(c)      // lazy
                    else -> { sb.append(c); i++; afterParen = false; afterQuantifier = true; continue }
                }
                i++
            }
            c == '}' -> { sb.append(c); i++; afterParen = false; afterQuantifier = true; continue }
            else -> { sb.append(c); i++ }
        }
        afterParen = false
        afterQuantifier = false
    }
    return sb.toString() to flags
}
