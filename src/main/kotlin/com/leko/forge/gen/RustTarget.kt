/**
 * Generates one Rust module file (standard library only), e.g. `kiln.rs` for `mod kiln;`.
 *
 * Values are `rt::V` (`V::Int(1)`, `rt::s("x")`, `rt::list(vec![...])`, nodes, records, ...). Functions take
 * and return them: `report()`, `compile(rt::s("Main"), rt::s(source))`; methods are named after their receiver
 * (`Type_repr`). Attributes are functions too: `attr_type(node)`, `inh_scope(node)`, `coll_diags(node)`.
 * `ext fun`s are functions of the sibling module `<name>_externals`, e.g.
 * `pub fn int_text(this: V) -> V` in `conformance_externals.rs`. A failed parse panics with an
 * `rt::ParseError`; `rt::catch_parse(|| ...)` turns it into an `Err`.
 */
object RustTarget : Target {
    override val name: String get() = "rust"
    override val extension: String get() = ".rs"

    override fun outputName(module: LLIRModule, base: String): String = base.replace(Regex("[^A-Za-z0-9_]"), "_").lowercase()

    override fun generate(module: LLIRModule, context: Context): ByteArray {
        val options = com.leko.forge.utils.Options.instance(context)
        val base = java.io.File(options.get("-o")?.firstOrNull() ?: module.sourceName ?: "out").nameWithoutExtension
        return RustGeneration(module, outputName(module, base)).run().toByteArray()
    }
}

private val RUST_KEYWORDS = setOf(
    "as", "break", "const", "continue", "crate", "else", "enum", "extern", "false", "fn", "for", "if", "impl", "in",
    "let", "loop", "match", "mod", "move", "mut", "pub", "ref", "return", "self", "Self", "static", "struct",
    "super", "trait", "true", "type", "unsafe", "use", "where", "while", "async", "await", "dyn", "abstract",
    "become", "box", "do", "final", "macro", "override", "priv", "typeof", "unsized", "virtual", "yield", "try",
    "union", "rt", "V", "std", "core", "Rc", "Some", "None", "Ok", "Err", "Box", "Vec", "String", "Option", "Result",
    "main", "drop", "vec", "format", "panic",
)

private class RustGeneration(private val module: LLIRModule, private val moduleName: String) {
    private val s = TargetSupport(module)
    private val names = Names(RUST_KEYWORDS)
    private val out = StringBuilder()
    private val kinds: Map<Node, Int> = s.concrete.withIndex().associate { (i, n) -> n to i }
    private val rids = mutableMapOf<String, Int>()
    private fun rid(key: String) = rids.getOrPut(key) { rids.size + 1 }
    private val cacheIds = mutableMapOf<String, Int>()
    private fun cacheId(key: String) = cacheIds.getOrPut(key) { cacheIds.size + 1 }
    private var labels = 0

    private fun line(text: String = "") { out.append(text).append('\n') }
    private fun id(name: String) = names.id(name)

    /** A local variable for [name]; every use clones it. */
    private fun bind(name: String): String {
        val target = names.fresh(name)
        names.alias(name, "$target.clone()")
        return target
    }

    fun run(): String {
        line("// Generated by Forge${module.sourceName?.let { " from ${java.io.File(it).name}" } ?: ""}. Do not edit.")
        line("#![allow(dead_code, unused_variables, unused_mut, unused_labels, unused_parens, unused_braces, unused_imports, non_snake_case, non_upper_case_globals, unreachable_code, clippy::all)]")
        line(runtimeResource("rust.rs"))
        line("use self::rt::V;")
        line("use std::rc::Rc;")
        line()
        line("static FLOWS: rt::Flows = rt::Flows { rule: __flow, is_root: __is_root };")
        for (enum in module.enums) for (item in enum.items) {
            if (item.fields.isEmpty()) {
                line("fn ${itemConst(item)}() -> V { thread_local!(static X: V = rt::new_rec(${rid(enum.name + "." + item.itemName)}, ${string(item.itemName)}, &[], true, vec![])); X.with(|x| x.clone()) }")
            }
        }
        for (port in module.ports) {
            if (!port.isNext) line("fn port_${port.name}() -> V { thread_local!(static X: V = rt::new_port(${string(port.name)}, ${port.inherited})); X.with(|x| x.clone()) }")
        }
        line()
        generateAttributes()
        module.functions.forEach { generateFunction(it) }
        module.graphs.forEach { generateGraph(it) }
        line("fn __flow(graph: usize, b: &mut rt::Build, n: &V) -> bool {")
        line("    match graph {")
        module.graphs.forEachIndexed { i, g -> line("        $i => flow_${g.name}(b, n),") }
        line("        _ => false,")
        line("    }")
        line("}")
        line("fn __is_root(graph: usize, n: &V) -> bool {")
        line("    match graph {")
        module.graphs.forEachIndexed { i, g -> line("        $i => ${isNode(g.root, "n")},") }
        line("        _ => false,")
        line("    }")
        line("}")
        module.parsers.forEach { generateParser(it) }
        return out.toString()
    }

    private fun itemConst(item: EnumItem) = "e_${item.enumName}_${item.itemName}"
    private fun functionId(fn: Function): String = id(s.functionName(fn))

    // ---- attributes ----------------------------------------------------------------------------------

    private fun dispatchTargets(): List<Pair<String, Node>> =
        s.concrete.map { kinds.getValue(it).toString() to it } + listOf("rt::EXIT_KIND" to s.vertex, "rt::SYNTHETIC_KIND" to s.vertex)

    private fun body(v: Value): String = names.scoped {
        names.alias("this", "self_.clone()")
        expr(v)
    }

    private fun generateAttributes() {
        for (name in s.attributeNames) {
            line("pub fn attr_$name(self_: V) -> V {")
            line("    match rt::kind(&self_) {")
            for ((kind, node) in dispatchTargets()) {
                when (val eq = s.equation(node, name) ?: continue) {
                    is TargetSupport.Equation.Syn ->
                        line("        $kind => rt::cached(${cacheId("syn $name")}, ${string(name)}, &self_, || ${body(eq.body)}),")
                    is TargetSupport.Equation.Circular ->
                        line("        $kind => rt::circular(${cacheId("circ $name")}, &self_, ${body(eq.attr.init)}, || ${body(eq.attr.body)}),")
                    TargetSupport.Equation.Missing -> {}
                }
            }
            line("        _ => rt::fail(format!(\"attribute '$name' is not defined for {}\", rt::show(&self_))),")
            line("    }")
            line("}")
        }

        for (inh in module.inherited.values) {
            val name = inh.name
            line("pub fn inh_$name(self_: V) -> V {")
            line("    rt::cached(${cacheId("inh $name")}, ${string(name)}, &self_, || { let p = rt::parent(&self_); if rt::is_null(&p) { ${body(inh.init)} } else { pass_$name(p, self_.clone()) } })")
            line("}")
            line("fn pass_$name(self_: V, child: V) -> V {")
            line("    match rt::kind(&self_) {")
            for (node in s.concrete) {
                val eq = node.inhEquations[name] ?: continue
                line("        ${kinds.getValue(node)} => {")
                names.scoped {
                    names.alias("this", "self_.clone()")
                    for (d in eq.delegates) {
                        val field = "rt::field(&self_, ${node.fields.keys.indexOf(d.field)})"
                        val key = d.key
                        if (key == null || node.fields[d.field] !is ListType) {
                            line("            if rt::same(&child, &$field) { return ${expr(d.value)}; }")
                        } else {
                            val list = names.fresh("list")
                            val index = names.fresh("index")
                            val k = names.fresh("k")
                            names.scoped {
                                val b = d.binder?.let { bind(it.name) } ?: names.fresh("i")
                                line("            { let $list: V = $field; let $index = rt::index_of_child(&$list, &child); if $index >= 0 { for $k in 0..rt::items(&$list).len() { let $b: V = V::Int($k as i32); if rt::int_of(&(${expr(key)})) == $index { return ${expr(d.value)}; } } } }")
                            }
                        }
                    }
                }
                line("        }")
            }
            line("        _ => {}")
            line("    }")
            line("    inh_$name(self_)")
            line("}")
        }

        for (name in s.collectionNames) {
            line("pub fn coll_$name(self_: V) -> V {")
            line("    match rt::kind(&self_) {")
            for (node in s.concrete) {
                val coll = node.collections[name] ?: continue
                val acc = names.fresh("acc")
                val n = names.fresh("n")
                val code = StringBuilder("{ let mut $acc: V = ${body(coll.init)}; ")
                if (coll.contributions.isNotEmpty()) {
                    code.append("for $n in rt::preorder(&rt::root(&self_)) { ")
                    for (c in coll.contributions) {
                        names.scoped {
                            names.alias("this", "$n.clone()")
                            code.append("if ${isNode(c.source, "&$n")} && rt::same(&(${expr(c.target)}), &self_) { ")
                            names.scoped {
                                val alias = bind(c.alias)
                                code.append("let $alias: V = $acc.clone(); $acc = ${expr(c.value)}; ")
                            }
                            code.append("} ")
                        }
                    }
                    code.append("} ")
                }
                code.append("$acc }")
                line("        ${kinds.getValue(node)} => rt::cached(${cacheId("coll $name")}, ${string(name)}, &self_, || $code),")
            }
            line("        _ => rt::fail(format!(\"collection '$name' is not defined for {}\", rt::show(&self_))),")
            line("    }")
            line("}")
        }
        line()
    }

    // ---- functions -----------------------------------------------------------------------------------

    private fun generateFunction(fn: Function) {
        val body = fn.body ?: return
        names.scoped {
            val params = mutableListOf<String>()
            if (fn.receiver != null) {
                params += "self_"
                names.alias("this", "self_.clone()")
            }
            for (p in fn.parameters) params += bind(p.name)
            line("pub fn ${functionId(fn)}(${params.joinToString(", ") { "$it: V" }}) -> V {")
            line("    ${expr(body)}")
            line("}")
        }
    }

    // ---- graphs --------------------------------------------------------------------------------------

    private fun generateGraph(graph: FlowGraphDecl) {
        line("fn flow_${graph.name}(_b: &mut rt::Build, n: &V) -> bool {")
        for (rule in s.flowRules(graph)) {
            line("    if ${isNode(rule.node, "n")} {")
            names.scoped {
                names.alias("this", "n.clone()")
                for ((local, field) in rule.binders) {
                    val v = bind(local)
                    line("        let $v: V = rt::field(n, ${rule.node.fields.keys.indexOf(field)});")
                }
                rule.body.forEach { flowStmt(it, "        ") }
            }
            line("        return true;")
            line("    }")
        }
        line("    false")
        line("}")
    }

    private fun flowStmt(stmt: FlowStmt, indent: String) {
        when (stmt) {
            is FlowEntry -> line("${indent}rt::f_entry(_b, &(${expr(stmt.target)}));")
            is FlowConnect -> line("${indent}rt::f_connect(_b, &(${expr(stmt.source)}), &(${expr(stmt.target)}), &(${stmt.label?.let { expr(it) } ?: "V::Null"}));")
            is FlowSequence -> line("${indent}rt::f_sequence(_b, &(${expr(stmt.items)}));")
            is FlowVertex -> {
                val label = stmt.label?.let { expr(it) } ?: "rt::s(${string(stmt.name)})"
                val v = bind(stmt.name)
                line("${indent}let $v: V = rt::f_vertex(_b, rt::synthetic_vertex($label, n.clone()));")
            }
            is FlowIf -> {
                line("${indent}if rt::truth(&(${expr(stmt.cond)})) {")
                names.scoped { stmt.then.forEach { flowStmt(it, "$indent    ") } }
                line("$indent} else {")
                names.scoped { stmt.alt.forEach { flowStmt(it, "$indent    ") } }
                line("$indent}")
            }
            is FlowFor -> {
                val iterable = expr(stmt.iterable)
                names.scoped {
                    val list = names.fresh("list")
                    val item = names.fresh("item")
                    val v = bind(stmt.name)
                    line("${indent}{ let $list: V = $iterable; for $item in rt::items(&$list).iter() { let $v: V = $item.clone();")
                    stmt.body.forEach { flowStmt(it, "$indent    ") }
                    line("$indent} }")
                }
            }
        }
    }

    // ---- parsers -------------------------------------------------------------------------------------

    private fun regex(regex: String): String {
        val p = RegexProgram.compile(regex)
        return "rt::Regex { code: &[${p.code.joinToString(", ")}], sets: &[${p.sets.joinToString(", ") { "&[${it.joinToString(", ")}]" }}], slots: ${p.slots} }"
    }

    private var terminalIds: Map<GTerminal, Int> = emptyMap()
    private var bitIds: Map<GBits, Int> = emptyMap()
    private var ruleIds: Map<String, Int> = emptyMap()
    private var left: String? = null

    private fun generateParser(parser: ParserDecl) {
        val p = parser.name
        val terminals = s.terminals(parser)
        val bits = s.bitPatterns(parser)
        terminalIds = terminals.withIndex().associate { (i, t) -> t to i }
        bitIds = bits.withIndex().associate { (i, b) -> b to i }
        ruleIds = parser.rules.keys.withIndex().associate { (i, r) -> r to i }
        line("fn grammar_$p() -> Rc<rt::Grammar> { thread_local!(static G: Rc<rt::Grammar> = Rc::new(build_$p())); G.with(|g| g.clone()) }")
        line("fn build_$p() -> rt::Grammar {")
        line("    let mut rules: Vec<rt::Rule> = Vec::new();")
        for (rule in parser.rules.values) {
            if (!rule.isAbstract) {
                line("    rules.push(rt::Rule::new(${string(rule.name)}, Some(Rc::new(|_s: &mut rt::PScope| -> rt::R { Ok(${alternative(rule.alternatives.single(), null)}) }))));")
                continue
            }
            line("    rules.push({")
            line("        let mut r = rt::Rule::new(${string(rule.name)}, None);")
            for (alt in rule.alternatives) {
                when (alt.operator) {
                    null -> line("        r.on(Rc::new(|_s: &mut rt::PScope| -> rt::R { Ok(${alternative(alt, null)}) }));")
                    OperatorKind.PREFIX -> line("        r.prefix(${alt.precedence}, Rc::new(|_s: &mut rt::PScope| -> rt::R { Ok(${alternative(alt, null)}) }));")
                    else -> {
                        val method = when (alt.operator) {
                            OperatorKind.INFIX_LEFT -> "infix_left"
                            OperatorKind.INFIX_RIGHT -> "infix_right"
                            else -> "postfix"
                        }
                        line("        r.$method(${alt.precedence}, Rc::new(|_s: &mut rt::PScope, _left: &V| -> rt::R { Ok(${alternative(alt, "_left.clone()")}) }));")
                    }
                }
            }
            line("        r")
            line("    });")
        }
        line("    rt::Grammar {")
        line("        skip: ${parser.skip?.let { "Some(${regex(it)})" } ?: "None"},")
        line("        keywords: &[${parser.keywords.joinToString(", ") { string(it) }}],")
        line("        terminals: vec![${terminals.joinToString(", ") { t -> "rt::Terminal { re: ${regex(t.regex)}, literal: ${t.literal?.let { "Some(${string(it)})" } ?: "None"}, display: ${string(s.display(t))} }" }}],")
        line("        bits: vec![${bits.joinToString(", ") { b -> "rt::Bits { bits: &[${b.bits.map { it == '1' }.joinToString(", ")}], display: ${string(b.description)} }" }}],")
        line("        rules,")
        line("    }")
        line("}")
        for (rule in parser.rules.values) {
            val entry = if (parser.binary) "rt::parse_binary" else "rt::parse_text"
            line("pub fn parse_${p}_${rule.name}(input: V) -> V { $entry(grammar_$p(), ${ruleIds.getValue(rule.name)}, &input) }")
        }
        line()
    }

    private fun closure(code: String) = "&(|_s: &mut rt::PScope| -> rt::R { Ok($code) }) as &rt::P<'_>"

    private fun alternative(alt: GrammarAlternative, leftName: String?): String {
        left = leftName
        val options = alt.options.map { option(it) }
        return options.singleOrNull() ?: "_s.one_of(&[${options.joinToString(", ") { closure(it) }}])?"
    }

    private fun option(option: GrammarOption): String = names.scoped {
        val cells = option.labels.map { (name, _) ->
            val cell = names.fresh("label_$name")
            names.alias(name, "$cell.get()")
            name to cell
        }
        val labels = cells.toMap()
        val body = grammar(option.body, labels)
        if (cells.isEmpty() && option.producer == null) body
        else {
            val declarations = cells.joinToString(" ") { (name, cell) -> "let $cell = rt::Label::new(${string(name)});" }
            val result = if (option.producer == null) body else "{ let _ = $body; ${expr(option.producer!!)} }"
            "{ $declarations $result }"
        }
    }

    private fun grammar(e: GExpr, labels: Map<String, String>): String = when (e) {
        is GTerminal -> "_s.terminal(${terminalIds.getValue(e)})?"
        is GBits -> "_s.bits(${bitIds.getValue(e)})?"
        is GPrimitive -> "_s.${e.name}(${e.argument?.let { "&(${expr(it)})" } ?: ""})?"
        is GNonterminal -> when (e.role) {
            NonterminalRole.RULE -> "_s.apply(${ruleIds.getValue(e.rule)})?"
            NonterminalRole.LEFT -> left ?: "V::Null"
            NonterminalRole.OPERAND -> "_s.operand()?"
        }
        is GRepeat -> {
            val body = closure(grammar(e.expr, labels))
            when (e.kind) {
                RepeatKind.OPTIONAL -> "_s.optional($body)?"
                RepeatKind.MANY -> "_s.many($body)?"
                RepeatKind.SOME -> "_s.some($body)?"
                RepeatKind.COUNT -> "_s.repeat(&(${expr(e.count!!)}), $body)?"
            }
        }
        is GPredicate -> if (e.negate) "_s.not_(${string(s.describe(e.expr))}, ${closure(grammar(e.expr, labels))})?"
            else "_s.and_(${closure(grammar(e.expr, labels))})?"
        is GChoice -> "_s.one_of(&[${e.alternatives.joinToString(", ") { closure(grammar(it, labels)) }}])?"
        is GSequence -> {
            val items = e.items.joinToString(", ") { item ->
                "(${closure(grammar(item.expr, labels))}, ${item.label?.let { "Some(&${labels.getValue(it)})" } ?: "None"})"
            }
            "_s.seq(&[$items], ${e.valueIndex ?: -2})?"
        }
    }

    // ---- values --------------------------------------------------------------------------------------

    private fun string(text: String): String = buildString {
        append('"')
        for (c in text) {
            when {
                c == '\\' -> append("\\\\")
                c == '"' -> append("\\\"")
                c == '\n' -> append("\\n")
                c == '\t' -> append("\\t")
                c == '\r' -> append("\\r")
                c.code < 32 || c.code == 127 -> append("\\u{%x}".format(c.code))
                else -> append(c)
            }
        }
        append('"')
    }

    private fun isNode(node: Node, v: String): String =
        if (node === s.vertex) "rt::is_vertex($v)" else "rt::kind_in($v, &[${s.concreteOf(node).joinToString(", ") { kinds.getValue(it).toString() }}])"

    private fun isTest(type: Type, v: String): String = when {
        type is OptionalType -> "(rt::is_null(&$v) || ${isTest(type.elem, v)})"
        type == IntType -> "matches!($v, V::Int(_))"
        type == LongType -> "matches!($v, V::Long(_))"
        type is TupleType -> "matches!($v, V::List(_))"
        type is FunctionType -> "matches!($v, V::Func(_))"
        type == FloatType -> "matches!($v, V::Float(_))"
        type == BoolType -> "matches!($v, V::Bool(_))"
        type == StrType -> "matches!($v, V::Str(_))"
        type is ListType -> "matches!($v, V::List(_))"
        type is MapType -> "matches!($v, V::Map(_))"
        type is SetType -> "matches!($v, V::Set(_))"
        type is ComplexType -> when {
            type.name == EDGE -> "matches!($v, V::Edge(_))"
            type.name == GRAPH -> "matches!($v, V::Graph(_))"
            type.name == SPAN -> "rt::rec_is(&$v, rt::SPAN_RID)"
            type.name in s.nodeNames -> isNode(s.nodeOf(type)!!, "&$v")
            type.name in s.enumNames -> module.enums.first { it.name == type.name }.items
                .joinToString(" || ", "(", ")") { "rt::rec_is(&$v, ${rid(type.name + "." + it.itemName)})" }
            else -> "rt::rec_is(&$v, ${rid(type.name)})"
        }
        else -> "true"
    }

    private fun r(v: Value) = "&(${expr(v)})"
    private fun b(v: Value) = "rt::truth(${r(v)})"
    private fun i(v: Value) = if (v.type == LongType) "rt::long_of(${r(v)})" else "rt::int_of(${r(v)})"
    private fun f(v: Value) = "rt::float_of(${r(v)})"
    private fun call(fn: String, vararg args: Value) = "$fn(${args.joinToString(", ") { r(it) }})"
    private fun vec(values: List<Value>) = "vec![${values.joinToString(", ") { expr(it) }}]"

    private fun let(value: String, name: String, body: (String) -> String): String = names.scoped {
        val x = names.fresh(name)
        "{ let $x: V = $value; ${body(x)} }"
    }

    fun expr(v: Value): String = when (v) {
        is LongValue -> if (v.value == Long.MIN_VALUE) "V::Long(i64::MIN)" else "V::Long(${v.value}i64)"
        is Int2Long -> call("rt::i2l", v.value)
        is Long2Int -> call("rt::l2i", v.value)
        is Long2Float -> call("rt::l2f", v.value)
        is Float2Long -> call("rt::f2l", v.value)
        is Let -> names.scoped {
            val value = expr(v.value)
            val x = bind(v.name)
            "{ let $x: V = $value; ${expr(v.body)} }"
        }
        // a `move` closure: it owns copies of the variables it uses, made where it is created
        is Lambda -> names.scoped {
            val copies = StringBuilder()
            for (name in s.referencedNames(v.body)) {
                val outer = try { names.lookup(name) } catch (_: IllegalStateException) { continue }
                val copy = names.fresh(name)
                copies.append("let $copy: V = $outer; ")
                names.alias(name, "$copy.clone()")
            }
            val args = names.fresh("args")
            val params = v.params.mapIndexed { index, p -> "let ${bind(p.name)}: V = $args[$index].clone(); " }.joinToString("")
            "{ ${copies}rt::func(move |$args: &[V]| -> V { $params${expr(v.body)} }) }"
        }
        is CallValue -> "rt::call(${r(v.function)}, &${vec(v.args)})"
        // a tuple is a list: equal as lists are
        is TupleLiteral -> "rt::list(${vec(v.elems)})"
        is TupleGet -> "rt::tuple_get(${r(v.tuple)}, ${v.index})"
        is IntValue -> if (v.value == Int.MIN_VALUE) "V::Int(i32::MIN)" else "V::Int(${v.value})"
        is FloatValue -> "V::Float(${v.value}f32)"
        is BoolValue -> "V::Bool(${v.value})"
        is StringValue -> "rt::s(${string(v.value)})"
        NullValue -> "V::Null"

        is Parameter -> names.lookup(v.name)
        is LocalRef -> names.lookup(v.name)
        is This -> names.lookup("this")
        is AccessParentInhAttr -> "inh_${v.name}(${names.lookup("this")})"

        is ListLiteral -> "rt::list(${vec(v.list)})"
        is MapLiteral -> "rt::map_of(vec![${v.entries.joinToString(", ") { (k, x) -> "(${expr(k)}, ${expr(x)})" }}])"

        is Call -> callOf(v)
        is CreateRecord -> when (v.target.name) {
            EDGE -> "rt::new_edge(${v.args.joinToString(", ") { expr(it) }})"
            SPAN -> "rt::new_span(${v.args.joinToString(", ") { expr(it) }})"
            else -> "rt::new_rec(${rid(v.target.name)}, ${string(v.target.name)}, &[${v.target.fields.keys.joinToString(", ") { string(it) }}], false, ${vec(v.args)})"
        }
        is CreateEnum -> if (v.target.fields.isEmpty()) "${itemConst(v.target)}()"
            else "rt::new_rec(${rid(v.target.enumName + "." + v.target.itemName)}, ${string(v.target.itemName)}, &[${v.target.fields.keys.joinToString(", ") { string(it) }}], true, ${vec(v.args)})"
        is CreateNode -> "rt::new_node(${kinds.getValue(v.target)}, ${string(v.target.name)}, ${vec(v.args)})"

        is AccessRecordField -> when (v.target.name) {
            "List", "Map", "Set", "str" -> call("rt::size", v.accessed)
            EDGE -> "rt::edge_field(${r(v.accessed)}, ${listOf("from", "to", "label").indexOf(v.name)})"
            GRAPH -> "rt::graph_field(${r(v.accessed)}, ${listOf("entry", "vertices", "edges", "root").indexOf(v.name)})"
            else -> "rt::field(${r(v.accessed)}, ${v.target.fields.keys.indexOf(v.name)})"
        }
        is AccessNodeField -> "rt::field(${r(v.accessed)}, ${v.target.fields.keys.indexOf(v.name)})"
        is AccessNodeAttr -> when {
            v.name in module.inherited -> "inh_${v.name}(${expr(v.receiver)})"
            v.name in s.collectionNames && v.name !in s.attributeNames -> "coll_${v.name}(${expr(v.receiver)})"
            else -> "attr_${v.name}(${expr(v.receiver)})"
        }
        is AccessListContainer -> call("rt::get", v.container, v.key)
        is AccessMapContainer -> call("rt::map_at", v.container, v.key)

        is Int2Float -> call("rt::i2f", v.value)
        is Float2Int -> call("rt::f2i", v.value)
        is Cast -> {
            val node = s.nodeOf(v.type)
            if (node != null && node !== s.vertex) let(expr(v.value), "cast") { x ->
                "if ${isNode(node, "&$x")} || rt::is_null(&$x) { $x } else { rt::fail(format!(\"can not cast {} to ${node.name}\", rt::show(&$x))) }"
            } else expr(v.value)
        }
        is IsInstanceOf -> let(expr(v.value), "x") { x -> "V::Bool(${isTest(v.target, x)})" }

        is NegateInt -> call("rt::neg", v.value)
        is NegateFloat -> call("rt::fneg", v.value)
        is InvertBool -> "V::Bool(!${b(v.value)})"
        is InvertInt -> call("rt::bnot", v.value)
        is IsNull -> "V::Bool(rt::is_null(${r(v.checked)}))"
        is NotNull -> "rt::nn(${expr(v.value)})"
        is Elvis -> "rt::elvis(${expr(v.value)}, || ${expr(v.alt)})"

        is MulInt -> call("rt::mul", v.lhs, v.rhs)
        is DivInt -> call("rt::div", v.lhs, v.rhs)
        is ModInt -> call("rt::rem", v.lhs, v.rhs)
        is AddInt -> call("rt::add", v.lhs, v.rhs)
        is SubInt -> call("rt::sub", v.lhs, v.rhs)
        is AndInt, is IAnd -> call("rt::band", (v as BinaryValue).lhs, v.rhs)
        is OrInt, is IOr -> call("rt::bor", (v as BinaryValue).lhs, v.rhs)
        is XorInt -> call("rt::bxor", v.lhs, v.rhs)
        is ShlInt -> call("rt::shl", v.lhs, v.rhs)
        is ShrInt -> call("rt::shr", v.lhs, v.rhs)
        is UshrInt -> call("rt::ushr", v.lhs, v.rhs)
        is SetEquals -> "V::Bool(rt::eq(${r(v.lhs)}, ${r(v.rhs)}))"
        is Builtin -> builtin(v)
        is MulFloat -> call("rt::fmul", v.lhs, v.rhs)
        is DivFloat -> call("rt::fdiv", v.lhs, v.rhs)
        is AddFloat -> call("rt::fadd", v.lhs, v.rhs)
        is SubFloat -> call("rt::fsub", v.lhs, v.rhs)
        is LtInt -> "V::Bool(${i(v.lhs)} < ${i(v.rhs)})"
        is GtInt -> "V::Bool(${i(v.lhs)} > ${i(v.rhs)})"
        is LeqInt -> "V::Bool(${i(v.lhs)} <= ${i(v.rhs)})"
        is GeqInt -> "V::Bool(${i(v.lhs)} >= ${i(v.rhs)})"
        is LtFloat -> "V::Bool(${f(v.lhs)} < ${f(v.rhs)})"
        is GtFloat -> "V::Bool(${f(v.lhs)} > ${f(v.rhs)})"
        is LeqFloat -> "V::Bool(${f(v.lhs)} <= ${f(v.rhs)})"
        is GeqFloat -> "V::Bool(${f(v.lhs)} >= ${f(v.rhs)})"
        is AndBool -> "V::Bool(${b(v.lhs)} && ${b(v.rhs)})"
        is OrBool -> "V::Bool(${b(v.lhs)} || ${b(v.rhs)})"
        is XorBool -> "V::Bool(${b(v.lhs)} != ${b(v.rhs)})"
        is IntEquals -> "V::Bool(${i(v.lhs)} == ${i(v.rhs)})"
        is FloatEquals -> "V::Bool(${f(v.lhs)} == ${f(v.rhs)})"
        is BoolEquals, is StringEquals, is ListEquals, is MapEquals, is EnumEquals, is RecordEquals, is NodeEquals ->
            "V::Bool(rt::eq(${r((v as BinaryValue).lhs)}, ${r(v.rhs)}))"
        is ConcatStr -> call("rt::concat", v.lhs, v.rhs)
        is MergeLists -> call("rt::list_concat", v.lhs, v.rhs)
        is MergeMaps -> call("rt::map_merge", v.lhs, v.rhs)

        is InList -> "V::Bool(rt::contains(${r(v.list)}, ${r(v.element)}))"
        is InMapKeys -> "V::Bool(rt::map_has(${r(v.map)}, ${r(v.key)}))"
        is AppendListItem -> call("rt::list_append", v.list, v.element)
        is AppendAllListItems -> call("rt::list_concat", v.list, v.elements)
        is PutMapItem -> call("rt::map_put", v.map, v.key, v.value)
        is PutAllMapItems -> call("rt::map_merge", v.map, v.elements)

        is IfElse -> "(if ${b(v.cond)} { ${expr(v.then)} } else { ${expr(v.alt)} })"
        is Panic -> "rt::fail(${string(v.message)})"

        is MapOp -> {
            val iterable = expr(v.iterable)
            names.scoped {
                val item = names.fresh("item")
                val x = bind(v.name)
                "rt::map_list(&($iterable), |$item: &V| { let $x: V = $item.clone(); ${expr(v.body)} })"
            }
        }
        is FoldOp -> {
            val iterable = expr(v.iterable)
            val init = expr(v.initAcc)
            names.scoped {
                val list = names.fresh("list")
                val storage = names.fresh("fold")
                val item = names.fresh("item")
                val x = bind(v.item)
                val acc = bind(v.acc)
                "{ let $list: V = $iterable; let mut $storage: V = $init; for $item in rt::items(&$list).iter() { let $x: V = $item.clone(); let $acc: V = $storage; $storage = ${expr(v.body)}; } $storage }"
            }
        }

        is PortValue -> if (v.port.isNext) "rt::port_next()" else "port_${v.port.name}()"
        is PortRefValue -> "rt::port_ref(${expr(v.child)}, ${expr(PortValue(v.port))})"
        is BoundCheck -> "rt::f_bound(_b, ${r(v.port)})"
        is FlowGraphRef -> "V::FlowGraph(${module.graphs.indexOf(v.graph)})"

        is Match -> match(v)
    }

    private fun builtin(b: Builtin): String {
        val all = (listOfNotNull(b.receiver) + b.args).toTypedArray()
        fun rt(fn: String) = call("rt::$fn", *all)
        return when (b.name) {
            "int.str" -> "rt::s(&rt::int_of(${r(b.receiver!!)}).to_string())"
            "long.str" -> "rt::s(&rt::long_of(${r(b.receiver!!)}).to_string())"
            "str.toLong" -> rt("to_long")
            "float.str" -> "rt::s(&rt::show_float(rt::float_of(${r(b.receiver!!)})))"
            "bool.str" -> "rt::s(&rt::show(${r(b.receiver!!)}))"
            "str.toInt" -> rt("to_int")
            "str.toFloat" -> rt("to_float")
            "str.indexOf" -> rt("str_index_of")
            "str.startsWith" -> rt("starts_with")
            "str.endsWith" -> rt("ends_with")
            "str.replace" -> rt("replace")
            "str.upper" -> rt("upper")
            "str.lower" -> rt("lower")
            "str.trim" -> rt("trim")
            "str.split" -> rt("split")
            "str.code" -> rt("code")
            "str.utf8" -> rt("utf8")
            "str.unescape" -> rt("unescape")
            "char" -> rt("char_of")
            "fail" -> "rt::fail(rt::str_of(${r(b.args[0])}).to_string())"
            "str.get" -> rt("char_at")
            "str.slice", "List.slice" -> rt("slice")
            "str.contains" -> rt("str_contains")
            "range" -> rt("range")
            "List.indexOf" -> rt("list_index_of")
            "List.reversed" -> rt("reversed")
            "List.toSet" -> rt("to_set")
            "List.join" -> rt("join_str")
            "Map.keys" -> rt("map_keys")
            "Map.values" -> rt("map_values")
            "Map.remove" -> rt("map_remove")
            "Set.toList" -> rt("to_list")
            "Set.remove" -> rt("set_remove")
            "Set.of" -> "rt::make_set(${vec(b.args)})"
            "Set.contains" -> rt("set_contains")
            "Set.union" -> rt("set_union")
            else -> throw IllegalStateException("unknown builtin ${b.name}")
        }
    }

    private fun callOf(v: Call): String {
        val fn = v.target
        val owner = fn.receiver
        val all = listOfNotNull(v.receiver) + v.args
        fun owned(values: List<Value>) = values.joinToString(", ") { expr(it) }
        fun refs(values: List<Value>) = values.joinToString(", ") { r(it) }
        return when {
            owner is ParserType -> "parse_${owner.name}_${fn.name}(${owned(v.args)})"
            owner is FlowGraphType -> {
                val id = module.graphs.indexOfFirst { it.name == owner.name }
                val method = mapOf("get" to "fg_get", "of" to "fg_of", "succ" to "fg_succ", "pred" to "fg_pred").getValue(fn.name)
                "rt::$method(&FLOWS, $id, ${refs(v.args)})"
            }
            owner is ComplexType && owner.name == GRAPH -> {
                val method = mapOf(
                    "succ" to "g_succ", "pred" to "g_pred", "outEdges" to "g_out", "inEdges" to "g_in", "contains" to "g_contains",
                    "indexOf" to "g_index", "exit" to "g_exit", "reachable" to "g_reachable", "postorder" to "g_postorder",
                    "reversePostorder" to "g_rpo", "toDot" to "g_dot",
                ).getValue(fn.name)
                "rt::$method(${refs(all)})"
            }
            owner == null && fn.body == null && fn.name == "graphOf" -> "rt::graph_from(${refs(v.args)})"
            owner == null && fn.body == null && fn.name == "spanOf" -> "rt::span_of(${refs(v.args)})"
            fn.body == null -> "super::${moduleName}_externals::${s.functionName(fn)}(${owned(all)})"
            else -> "${functionId(fn)}(${owned(all)})"
        }
    }

    private val patterns = object : TargetSupport.Patterns {
        override fun fresh(): String = names.fresh("m")
        override fun isItem(subject: String, item: EnumItem): String = "rt::rec_is(&$subject, ${rid(item.enumName + "." + item.itemName)})"
        override fun itemField(subject: String, item: EnumItem, field: String): String = "rt::field(&$subject, ${item.fields.keys.indexOf(field)})"
        override fun sizeIs(subject: String, size: Int): String = "rt::items(&$subject).len() == $size"
        override fun notEmpty(subject: String): String = "!rt::items(&$subject).is_empty()"
        override fun element(subject: String, index: Int): String = "rt::items(&$subject)[$index].clone()"
        override fun tail(subject: String): String = "rt::tail(&$subject)"
        override fun equalTo(subject: String, value: Value): String = "rt::eq(&$subject, ${r(value)})"
        override fun bindVariable(variable: LocalRef): String = bind(variable.name)
        override fun use(name: String): String = "$name.clone()"
    }

    /** Labeled blocks: a case breaks out of its block when a test fails, or out of the match with its value. */
    private fun match(m: Match): String {
        val scrutinee = expr(m.scrutinee)
        return names.scoped {
            val subject = names.fresh("subject")
            val label = "'m${labels++}"
            val sb = StringBuilder("{ let $subject: V = $scrutinee; $label: { ")
            for (case in m.cases) {
                names.scoped {
                    val caseLabel = "'c${labels++}"
                    sb.append("$caseLabel: { ")
                    for (step in s.steps(case.pattern, subject, patterns)) {
                        when (step) {
                            is TargetSupport.Step.Test -> sb.append("if !(${step.cond}) { break $caseLabel; } ")
                            is TargetSupport.Step.Bind -> sb.append("let ${step.name}: V = ${step.value}; ")
                        }
                    }
                    case.guard?.let { sb.append("if !${b(it)} { break $caseLabel; } ") }
                    sb.append("break $label (${expr(case.body)}); } ")
                }
            }
            val alt = m.alt
            sb.append(if (alt != null) expr(alt) else "rt::fail(format!(\"no match for {}\", rt::show(&$subject)))")
            sb.append(" } }")
            sb.toString()
        }
    }
