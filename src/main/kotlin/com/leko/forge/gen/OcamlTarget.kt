package com.leko.forge.gen

import com.leko.forge.context.Context
import com.leko.forge.llir.*
import com.leko.forge.llir.Function
import com.leko.forge.model.EDGE
import com.leko.forge.model.GRAPH
import com.leko.forge.model.SPAN
import com.leko.forge.model.VERTEX
import com.leko.forge.types.*

/**
 * Generates one OCaml module (OCaml 4.14 or later, no libraries).
 *
 * Values are of the runtime's type `Rt.v` (`Int`, `Str`, `List`, `Node`, ...). Functions take and return
 * them: `report ()`, `compile (Str "Main") (Str source)`; methods are named after their receiver
 * (`f_Type_repr`). Attributes are functions too: `attr_type node`, `inh_scope node`, `coll_diags node`.
 * `ext fun`s are references to set before use: `Conformance.ext_int_text := (fun v -> ...)`.
 * A failed parse raises `Rt.Parse_error`.
 */
object OcamlTarget : Target {
    override val name: String get() = "ocaml"
    override val extension: String get() = ".ml"

    override fun outputName(module: LLIRModule, base: String): String = base.replace(Regex("[^A-Za-z0-9_]"), "_").lowercase()

    override fun generate(module: LLIRModule, context: Context): ByteArray = OcamlGeneration(module).run().toByteArray()
}

private val OCAML_KEYWORDS = setOf(
    "and", "as", "assert", "asr", "begin", "class", "constraint", "do", "done", "downto", "else", "end", "exception",
    "external", "false", "for", "fun", "function", "functor", "if", "in", "include", "inherit", "initializer", "land",
    "lazy", "let", "lor", "lsl", "lsr", "lxor", "match", "method", "mod", "module", "mutable", "new", "nonrec",
    "object", "of", "open", "or", "private", "rec", "sig", "struct", "then", "to", "true", "try", "type", "val",
    "virtual", "when", "while", "with", "ref", "not", "fst", "snd", "ignore", "print_endline", "raise",
)

private class OcamlGeneration(private val module: LLIRModule) {
    private val s = TargetSupport(module)
    private val names = Names(OCAML_KEYWORDS) { name -> if (name[0].isUpperCase()) "u$name" else name }
    private val out = StringBuilder()
    private val kinds: Map<Node, Int> = s.concrete.withIndex().associate { (i, n) -> n to i }
    private val rids = mutableMapOf<String, Int>()
    private fun rid(key: String) = rids.getOrPut(key) { rids.size + 1 }

    private fun line(text: String = "") { out.append(text).append('\n') }

    fun run(): String {
        line("(* Generated by Forge${module.sourceName?.let { " from ${java.io.File(it).name}" } ?: ""}. Do not edit. *)")
        line("[@@@warning \"-a\"]")
        line(runtimeResource("ocaml.ml"))
        line("open Rt")
        line()
        line("let () = Rt.kind_names := [| ${s.concrete.joinToString("; ") { string(it.name) }} |]")
        for (enum in module.enums) for (item in enum.items) {
            if (item.fields.isEmpty()) line("let ${itemConst(item)} = Rt.new_rec ${rid(enum.name + "." + item.itemName)} ${string(item.itemName)} [||] true [||]")
        }
        for (port in module.ports) if (!port.isNext) line("let port_${port.name} = Rt.new_port ${string(port.name)} ${port.inherited}")
        for (name in s.attributeNames) {
            line("let cache_syn_$name = Rt.new_cache ${string(name)}")
            line("let circ_$name = Rt.new_circular ()")
        }
        for (name in module.inherited.keys) line("let cache_inh_$name = Rt.new_cache ${string(name)}")
        for (name in s.collectionNames) line("let cache_coll_$name = Rt.new_cache ${string(name)}")
        for (fn in module.functions) {
            if (fn.body != null || isBuiltinFunction(fn)) continue
            val arity = fn.parameters.size + (if (fn.receiver != null) 1 else 0)
            val type = if (arity == 0) "unit -> Rt.v" else List(arity) { "Rt.v" }.joinToString(" -> ") + " -> Rt.v"
            line("let ext_${s.functionName(fn)} : ($type) ref = ref (fun ${if (arity == 0) "()" else List(arity) { "_" }.joinToString(" ")} -> Rt.fail ${string("external '${s.functionName(fn)}' is not set")})")
        }
        module.parsers.forEach { parserConstants(it) }
        line()

        line("let rec __forge_unused () = Null")
        generateAttributes()
        module.functions.forEach { generateFunction(it) }
        module.graphs.forEachIndexed { i, g -> generateGraph(g, i) }
        module.parsers.forEach { parserEntries(it) }
        line()
        module.parsers.forEach { parserBodies(it) }
        if (module.graphs.isNotEmpty()) {
            line("let () = Rt.flow_rules := (fun gid s n -> match gid with ${module.graphs.withIndex().joinToString(" | ") { (i, g) -> "$i -> flow_${g.name} s n" }} | _ -> false)")
            line("let () = Rt.flow_is_root := (fun gid n -> match gid with ${module.graphs.withIndex().joinToString(" | ") { (i, g) -> "$i -> ${isNode(g.root, "n")}" }} | _ -> false)")
        }
        return out.toString()
    }

    private fun isBuiltinFunction(fn: Function) = fn.receiver == null && fn.name in setOf("graphOf", "spanOf")
    private fun itemConst(item: EnumItem) = "e_${item.enumName}_${item.itemName}"

    private fun functionId(fn: Function): String {
        val name = s.functionName(fn)
        return if (name[0].isUpperCase() || name in OCAML_KEYWORDS || name.startsWith("__")) "f_$name" else name
    }

    // ---- attributes ----------------------------------------------------------------------------------

    private fun dispatchTargets(): List<Pair<String, Node>> =
        s.concrete.map { kinds.getValue(it).toString() to it } + listOf("(-1)" to s.vertex, "(-2)" to s.vertex)

    private fun body(v: Value): String = names.scoped {
        names.alias("this", "self")
        expr(v)
    }

    private fun generateAttributes() {
        for (name in s.attributeNames) {
            val cases = mutableListOf<String>()
            for ((kind, node) in dispatchTargets()) {
                val eq = s.equation(node, name) ?: continue
                cases += when (eq) {
                    is TargetSupport.Equation.Syn -> "  | $kind -> Rt.cached cache_syn_$name self (fun () -> ${body(eq.body)})"
                    is TargetSupport.Equation.Circular -> "  | $kind -> Rt.circular circ_$name self (${body(eq.attr.init)}) (fun () -> ${body(eq.attr.body)})"
                    TargetSupport.Equation.Missing -> "  | $kind -> Rt.fail (\"attribute '$name' is not defined for \" ^ Rt.show self)"
                }
            }
            line("and attr_$name self = match Rt.kind self with")
            cases.forEach { line(it) }
            line("  | _ -> Rt.fail (\"attribute '$name' is not defined for \" ^ Rt.show self)")
        }

        for (inh in module.inherited.values) {
            val name = inh.name
            line("and inh_$name self = Rt.cached cache_inh_$name self (fun () -> match Rt.parent self with None -> ${body(inh.init)} | Some p -> pass_$name p self)")
            line("and pass_$name self child = match Rt.kind self with")
            for (node in s.concrete) {
                val eq = node.inhEquations[name] ?: continue
                val code = names.scoped {
                    names.alias("this", "self")
                    var rest = "inh_$name self"
                    for (d in eq.delegates.reversed()) {
                        val index = node.fields.keys.indexOf(d.field)
                        val field = "(Rt.field self $index)"
                        val key = d.key
                        rest = if (key == null || node.fields[d.field] !is ListType) {
                            "(if Rt.same child $field then ${expr(d.value)} else $rest)"
                        } else {
                            names.scoped {
                                val b = d.binder?.let { names.bind(it.name) } ?: "_"
                                "(Rt.inh_list $field child (fun $b -> ${expr(key)}) (fun $b -> ${expr(d.value)}) (fun () -> $rest))"
                            }
                        }
                    }
                    rest
                }
                line("  | ${kinds.getValue(node)} -> $code")
            }
            line("  | _ -> inh_$name self")
        }

        for (name in s.collectionNames) {
            line("and coll_$name self = match Rt.kind self with")
            for (node in s.concrete) {
                val coll = node.collections[name] ?: continue
                val acc = names.fresh("acc")
                val n = names.fresh("n")
                val steps = coll.contributions.map { c ->
                    names.scoped {
                        names.alias("this", n)
                        val target = expr(c.target)
                        val value = names.scoped {
                            val alias = names.bind(c.alias)
                            "(let $alias = $acc in ${expr(c.value)})"
                        }
                        "let $acc = if ${isNode(c.source, n)} && Rt.same ($target) self then $value else $acc in"
                    }
                }
                line("  | ${kinds.getValue(node)} -> Rt.cached cache_coll_$name self (fun () -> List.fold_left (fun $acc $n -> ${steps.joinToString(" ")} $acc) (${body(coll.init)}) (Rt.preorder (Rt.root (Rt.node_of self))))")
            }
            line("  | _ -> Rt.fail (\"collection '$name' is not defined for \" ^ Rt.show self)")
        }
    }

    // ---- functions -----------------------------------------------------------------------------------

    private fun generateFunction(fn: Function) {
        val body = fn.body ?: return
        names.scoped {
            val params = mutableListOf<String>()
            if (fn.receiver != null) {
                params += "self"
                names.alias("this", "self")
            }
            for (p in fn.parameters) params += names.bind(p.name)
            line("and ${functionId(fn)} ${if (params.isEmpty()) "()" else params.joinToString(" ")} = ${expr(body)}")
        }
    }

    // ---- graphs --------------------------------------------------------------------------------------

    private fun generateGraph(graph: FlowGraphDecl, index: Int) {
        graphIds[graph] = index
        val cases = s.flowRules(graph).map { rule ->
            names.scoped {
                names.alias("this", "n")
                val stmts = mutableListOf<String>()
                for ((local, field) in rule.binders) {
                    val v = names.bind(local)
                    stmts += "let $v = Rt.field n ${rule.node.fields.keys.indexOf(field)} in"
                }
                rule.body.forEach { flowStmt(it, stmts) }
                "if ${isNode(rule.node, "n")} then (${stmts.joinToString(" ") { if (it.endsWith(" in")) it else "$it;" }} true)"
            }
        }
        line("and flow_${graph.name} _s n = ${cases.joinToString(" else ")}${if (cases.isEmpty()) "false" else " else false"}")
    }

    private val graphIds = mutableMapOf<FlowGraphDecl, Int>()

    private fun flowStmt(stmt: FlowStmt, into: MutableList<String>) {
        fun block(stmts: List<FlowStmt>): String = names.scoped {
            val inner = mutableListOf<String>()
            stmts.forEach { flowStmt(it, inner) }
            "(${inner.joinToString(" ") { if (it.endsWith(" in")) it else "$it;" }} ())"
        }
        when (stmt) {
            is FlowEntry -> into += "Rt.f_entry _s (${expr(stmt.target)})"
            is FlowConnect -> into += "Rt.f_connect _s (${expr(stmt.source)}) (${expr(stmt.target)}) (${stmt.label?.let { expr(it) } ?: "Null"})"
            is FlowSequence -> into += "Rt.f_sequence _s (${expr(stmt.items)})"
            is FlowVertex -> {
                val label = stmt.label?.let { expr(it) } ?: "(Str ${string(stmt.name)})"
                val v = names.bind(stmt.name)
                into += "let $v = Rt.f_vertex _s (Rt.synthetic_vertex $label n) in"
            }
            is FlowIf -> into += "(if Rt.truth (${expr(stmt.cond)}) then ${block(stmt.then)} else ${block(stmt.alt)})"
            is FlowFor -> {
                val iterable = expr(stmt.iterable)
                names.scoped {
                    val v = names.bind(stmt.name)
                    into += "Array.iter (fun $v -> ${block(stmt.body)}) (Rt.items ($iterable))"
                }
            }
        }
    }

    // ---- parsers -------------------------------------------------------------------------------------

    private fun regex(regex: String): String {
        val p = RegexProgram.compile(regex)
        return "{ Rt.code = [| ${p.code.joinToString("; ")} |]; sets = [| ${p.sets.joinToString("; ") { "[| ${it.joinToString("; ")} |]" }} |]; slots = ${p.slots} }"
    }

    private fun parserConstants(parser: ParserDecl) {
        val p = parser.name
        line("let skip_$p = ${parser.skip?.let { "Some ${regex(it)}" } ?: "None"}")
        line("let keywords_$p = [ ${parser.keywords.joinToString("; ") { string(it) }} ]")
        s.terminals(parser).forEachIndexed { i, t ->
            line("let term_${p}_$i = { Rt.re = ${regex(t.regex)}; literal = ${t.literal?.let { "Some ${string(it)}" } ?: "None"}; display = ${string(s.display(t))} }")
        }
        s.bitPatterns(parser).forEachIndexed { i, b ->
            line("let bits_${p}_$i = { Rt.bits = [| ${b.bits.map { it == '1' }.joinToString("; ")} |]; bdisplay = ${string(b.description)} }")
        }
        for (rule in parser.rules.values) line("let rule_${p}_${rule.name} = Rt.new_rule ${string(rule.name)} ${rule.isAbstract}")
    }

    private fun parserEntries(parser: ParserDecl) {
        for (rule in parser.rules.values) {
            val entry = if (parser.binary) "Rt.parse_binary" else "Rt.parse_text"
            line("and parse_${parser.name}_${rule.name} input = $entry rule_${parser.name}_${rule.name} skip_${parser.name} keywords_${parser.name} input")
        }
    }

    private var terminalNames: Map<GTerminal, String> = emptyMap()
    private var bitNames: Map<GBits, String> = emptyMap()
    private var parserName = ""
    private var left: String? = null

    private fun parserBodies(parser: ParserDecl) {
        val p = parser.name
        parserName = p
        terminalNames = s.terminals(parser).withIndex().associate { (i, t) -> t to "term_${p}_$i" }
        bitNames = s.bitPatterns(parser).withIndex().associate { (i, b) -> b to "bits_${p}_$i" }
        for (rule in parser.rules.values) {
            val r = "rule_${p}_${rule.name}"
            if (!rule.isAbstract) {
                line("let () = $r.body <- (fun _s -> ${alternative(rule.alternatives.single(), null)})")
                continue
            }
            for (alt in rule.alternatives) {
                when (alt.operator) {
                    null -> line("let () = Rt.on $r (fun _s -> ${alternative(alt, null)})")
                    OperatorKind.PREFIX -> line("let () = Rt.prefix $r (${alt.precedence}) (fun _s -> ${alternative(alt, null)})")
                    else -> {
                        val method = when (alt.operator) {
                            OperatorKind.INFIX_LEFT -> "infix_left"
                            OperatorKind.INFIX_RIGHT -> "infix_right"
                            else -> "postfix"
                        }
                        line("let () = Rt.$method $r (${alt.precedence}) (fun _s _left -> ${alternative(alt, "_left")})")
                    }
                }
            }
        }
    }

    private fun alternative(alt: GrammarAlternative, leftName: String?): String {
        left = leftName
        val options = alt.options.map { option(it) }
        return options.singleOrNull() ?: "(Rt.one_of _s [ ${options.joinToString("; ") { "(fun () -> $it)" }} ])"
    }

    private fun option(option: GrammarOption): String = names.scoped {
        val cells = option.labels.map { (name, _) ->
            val cell = names.fresh("label_$name")
            names.alias(name, "(Rt.label_get $cell)")
            name to cell
        }
        val labels = cells.toMap()
        val body = grammar(option.body, labels)
        var result = if (option.producer == null) body else "(let _ = $body in ${expr(option.producer!!)})"
        for ((name, cell) in cells.reversed()) result = "(let $cell = Rt.new_label ${string(name)} in $result)"
        result
    }

    private fun grammar(e: GExpr, labels: Map<String, String>): String = when (e) {
        is GTerminal -> "(Rt.terminal _s ${terminalNames.getValue(e)})"
        is GBits -> "(Rt.bits _s ${bitNames.getValue(e)})"
        is GPrimitive -> "(Rt.${e.name} _s${e.argument?.let { " (${expr(it)})" } ?: ""})"
        is GNonterminal -> when (e.role) {
            NonterminalRole.RULE -> "(Rt.apply _s rule_${parserName}_${e.rule})"
            NonterminalRole.LEFT -> left ?: "Null"
            NonterminalRole.OPERAND -> "(Rt.operand _s)"
        }
        is GRepeat -> {
            val body = "(fun () -> ${grammar(e.expr, labels)})"
            when (e.kind) {
                RepeatKind.OPTIONAL -> "(Rt.optional _s $body)"
                RepeatKind.MANY -> "(Rt.many _s $body)"
                RepeatKind.SOME -> "(Rt.some _s $body)"
                RepeatKind.COUNT -> "(Rt.repeat _s (${expr(e.count!!)}) $body)"
            }
        }
        is GPredicate -> if (e.negate) "(Rt.not_ _s ${string(s.describe(e.expr))} (fun () -> ${grammar(e.expr, labels)}))"
            else "(Rt.and_ _s (fun () -> ${grammar(e.expr, labels)}))"
        is GChoice -> "(Rt.one_of _s [ ${e.alternatives.joinToString("; ") { "(fun () -> ${grammar(it, labels)})" }} ])"
        is GSequence -> {
            val items = e.items.joinToString("; ") { item ->
                "((fun () -> ${grammar(item.expr, labels)}), ${item.label?.let { "Some ${labels.getValue(it)}" } ?: "None"})"
            }
            "(Rt.seq _s [ $items ] (${e.valueIndex ?: -2}))"
        }
    }

    // ---- values --------------------------------------------------------------------------------------

    private fun string(text: String): String = buildString {
        append('"')
        for (b in text.toByteArray(Charsets.UTF_8)) {
            val c = b.toInt() and 0xFF
            when {
                c == '\\'.code -> append("\\\\")
                c == '"'.code -> append("\\\"")
                c == '\n'.code -> append("\\n")
                c == '\t'.code -> append("\\t")
                c == '\r'.code -> append("\\r")
                c < 32 || c > 126 -> append("\\%03d".format(c))
                else -> append(c.toChar())
            }
        }
        append('"')
    }

    private fun isNode(node: Node, v: String): String =
        if (node === s.vertex) "Rt.is_vertex $v" else "Rt.kind_in $v [| ${s.concreteOf(node).joinToString("; ") { kinds.getValue(it).toString() }} |]"

    private fun isTest(type: Type, v: String): String = when {
        type is OptionalType -> "(Rt.is_null $v || ${isTest(type.elem, v)})"
        type == IntType -> "(match $v with Int _ -> true | _ -> false)"
        type == LongType -> "(match $v with Long _ -> true | _ -> false)"
        type is TupleType -> "(match $v with List _ -> true | _ -> false)"
        type is FunctionType -> "(match $v with Fn _ -> true | _ -> false)"
        type == FloatType -> "(match $v with Float _ -> true | _ -> false)"
        type == BoolType -> "(match $v with Bool _ -> true | _ -> false)"
        type == StrType -> "(match $v with Str _ -> true | _ -> false)"
        type is ListType -> "(match $v with List _ -> true | _ -> false)"
        type is MapType -> "(match $v with Map _ -> true | _ -> false)"
        type is SetType -> "(match $v with Set _ -> true | _ -> false)"
        type is ComplexType -> when {
            type.name == EDGE -> "(match $v with Edge _ -> true | _ -> false)"
            type.name == GRAPH -> "(match $v with Graph _ -> true | _ -> false)"
            type.name == SPAN -> "Rt.rec_is $v Rt.span_rid"
            type.name in s.nodeNames -> isNode(s.nodeOf(type)!!, v)
            type.name in s.enumNames -> {
                val items = module.enums.first { it.name == type.name }.items.map { rid(type.name + "." + it.itemName) }
                "(match $v with Rec r -> List.mem r.rid [ ${items.joinToString("; ")} ] | _ -> false)"
            }
            else -> "Rt.rec_is $v ${rid(type.name)}"
        }
        else -> "true"
    }

    private fun bool(v: Value) = "Rt.truth (${expr(v)})"
    private fun int(v: Value) = if (v.type == LongType) "Rt.long_of (${expr(v)})" else "Rt.int_of (${expr(v)})"
    private fun float(v: Value) = "Rt.float_of (${expr(v)})"
    private fun call(fn: String, vararg args: Value) = "($fn ${args.joinToString(" ") { "(${expr(it)})" }})"
    private fun listOfValues(values: List<Value>) = "[| ${values.joinToString("; ") { expr(it) }} |]"

    fun expr(v: Value): String = when (v) {
        is LongValue -> if (v.value == Long.MIN_VALUE) "(Long Int64.min_int)" else "(Long (${v.value}L))"
        is Int2Long -> call("Rt.i2l", v.value)
        is Long2Int -> call("Rt.l2i", v.value)
        is Long2Float -> call("Rt.l2f", v.value)
        is Float2Long -> call("Rt.f2l", v.value)
        is Let -> let(expr(v.value), v.name) { _ -> expr(v.body) }
        is Lambda -> names.scoped {
            val args = names.fresh("args")
            val params = v.params.mapIndexed { index, p -> "let ${names.bind(p.name)} = $args.($index) in " }.joinToString("")
            "(Fn (fun $args -> $params${expr(v.body)}))"
        }
        is CallValue -> "(Rt.call (${expr(v.function)}) ${listOfValues(v.args)})"
        // a tuple is a list: equal as lists are
        is TupleLiteral -> "(List ${listOfValues(v.elems)})"
        is TupleGet -> "(Rt.tuple_get (${expr(v.tuple)}) ${v.index})"
        is IntValue -> if (v.value < 0) "(Int (${v.value}))" else "(Int ${v.value})"
        is FloatValue -> "(Float (Rt.f32 (${v.value.toDouble()})))"
        is BoolValue -> "(Bool ${v.value})"
        is StringValue -> "(Str ${string(v.value)})"
        NullValue -> "Null"

        is Parameter -> names.lookup(v.name)
        is LocalRef -> names.lookup(v.name)
        is This -> names.lookup("this")
        is AccessParentInhAttr -> "(inh_${v.name} ${names.lookup("this")})"

        is ListLiteral -> "(List ${listOfValues(v.list)})"
        is MapLiteral -> "(Rt.map_of [ ${v.entries.joinToString("; ") { (k, x) -> "(${expr(k)}, ${expr(x)})" }} ])"

        is Call -> callOf(v)
        is CreateRecord -> when (v.target.name) {
            EDGE -> "(Rt.new_edge ${v.args.joinToString(" ") { "(${expr(it)})" }})"
            SPAN -> "(Rt.new_span ${v.args.joinToString(" ") { "(${expr(it)})" }})"
            else -> "(Rt.new_rec ${rid(v.target.name)} ${string(v.target.name)} [| ${v.target.fields.keys.joinToString("; ") { string(it) }} |] false ${listOfValues(v.args)})"
        }
        is CreateEnum -> if (v.target.fields.isEmpty()) itemConst(v.target)
            else "(Rt.new_rec ${rid(v.target.enumName + "." + v.target.itemName)} ${string(v.target.itemName)} [| ${v.target.fields.keys.joinToString("; ") { string(it) }} |] true ${listOfValues(v.args)})"
        is CreateNode -> "(Rt.new_node ${kinds.getValue(v.target)} ${listOfValues(v.args)})"

        is AccessRecordField -> when (v.target.name) {
            "List", "Map", "Set", "str" -> call("Rt.size", v.accessed)
            EDGE -> "(Rt.edge_field (${expr(v.accessed)}) ${listOf("from", "to", "label").indexOf(v.name)})"
            GRAPH -> "(Rt.graph_field (${expr(v.accessed)}) ${listOf("entry", "vertices", "edges", "root").indexOf(v.name)})"
            else -> "(Rt.field (${expr(v.accessed)}) ${v.target.fields.keys.indexOf(v.name)})"
        }
        is AccessNodeField -> "(Rt.field (${expr(v.accessed)}) ${v.target.fields.keys.indexOf(v.name)})"
        is AccessNodeAttr -> when {
            v.name in module.inherited -> call("inh_${v.name}", v.receiver)
            v.name in s.collectionNames && v.name !in s.attributeNames -> call("coll_${v.name}", v.receiver)
            else -> call("attr_${v.name}", v.receiver)
        }
        is AccessListContainer -> call("Rt.get", v.container, v.key)
        is AccessMapContainer -> call("Rt.map_at", v.container, v.key)

        is Int2Float -> call("Rt.i2f", v.value)
        is Float2Int -> call("Rt.f2i", v.value)
        is Cast -> {
            val type = v.type
            val node = s.nodeOf(type)
            if (node != null && node !== s.vertex) let(expr(v.value), "cast") { x ->
                "(if ${isNode(node, x)} || Rt.is_null $x then $x else Rt.fail (\"can not cast \" ^ Rt.show $x ^ \" to ${node.name}\"))"
            } else expr(v.value)
        }
        is IsInstanceOf -> let(expr(v.value), "x") { x -> "(Bool (${isTest(v.target, x)}))" }

        is NegateInt -> call("Rt.neg", v.value)
        is NegateFloat -> call("Rt.fneg", v.value)
        is InvertBool -> "(Bool (not (${bool(v.value)})))"
        is InvertInt -> call("Rt.lnot_", v.value)
        is IsNull -> "(Bool (Rt.is_null (${expr(v.checked)})))"
        is NotNull -> call("Rt.nn", v.value)
        is Elvis -> "(Rt.elvis (${expr(v.value)}) (fun () -> ${expr(v.alt)}))"

        is MulInt -> call("Rt.mul", v.lhs, v.rhs)
        is DivInt -> call("Rt.div", v.lhs, v.rhs)
        is ModInt -> call("Rt.rem", v.lhs, v.rhs)
        is AddInt -> call("Rt.add", v.lhs, v.rhs)
        is SubInt -> call("Rt.sub", v.lhs, v.rhs)
        is AndInt, is IAnd -> call("Rt.land_", (v as BinaryValue).lhs, v.rhs)
        is OrInt, is IOr -> call("Rt.lor_", (v as BinaryValue).lhs, v.rhs)
        is XorInt -> call("Rt.lxor_", v.lhs, v.rhs)
        is ShlInt -> call("Rt.shl", v.lhs, v.rhs)
        is ShrInt -> call("Rt.shr", v.lhs, v.rhs)
        is UshrInt -> call("Rt.ushr", v.lhs, v.rhs)
        is SetEquals -> "(Bool (Rt.eq (${expr(v.lhs)}) (${expr(v.rhs)})))"
        is Builtin -> builtin(v)
        is MulFloat -> call("Rt.fmul", v.lhs, v.rhs)
        is DivFloat -> call("Rt.fdiv", v.lhs, v.rhs)
        is AddFloat -> call("Rt.fadd", v.lhs, v.rhs)
        is SubFloat -> call("Rt.fsub", v.lhs, v.rhs)
        is LtInt -> "(Bool (${int(v.lhs)} < ${int(v.rhs)}))"
        is GtInt -> "(Bool (${int(v.lhs)} > ${int(v.rhs)}))"
        is LeqInt -> "(Bool (${int(v.lhs)} <= ${int(v.rhs)}))"
        is GeqInt -> "(Bool (${int(v.lhs)} >= ${int(v.rhs)}))"
        is LtFloat -> "(Bool (${float(v.lhs)} < ${float(v.rhs)}))"
        is GtFloat -> "(Bool (${float(v.lhs)} > ${float(v.rhs)}))"
        is LeqFloat -> "(Bool (${float(v.lhs)} <= ${float(v.rhs)}))"
        is GeqFloat -> "(Bool (${float(v.lhs)} >= ${float(v.rhs)}))"
        is AndBool -> "(Bool (${bool(v.lhs)} && ${bool(v.rhs)}))"
        is OrBool -> "(Bool (${bool(v.lhs)} || ${bool(v.rhs)}))"
        is XorBool -> "(Bool (${bool(v.lhs)} <> ${bool(v.rhs)}))"
        is IntEquals -> "(Bool (${int(v.lhs)} = ${int(v.rhs)}))"
        is FloatEquals -> "(Bool (${float(v.lhs)} = ${float(v.rhs)}))"
        is BoolEquals, is StringEquals, is ListEquals, is MapEquals, is EnumEquals, is RecordEquals, is NodeEquals ->
            "(Bool (Rt.eq (${expr((v as BinaryValue).lhs)}) (${expr(v.rhs)})))"
        is ConcatStr -> call("Rt.concat", v.lhs, v.rhs)
        is MergeLists -> call("Rt.list_concat", v.lhs, v.rhs)
        is MergeMaps -> call("Rt.map_merge", v.lhs, v.rhs)

        is InList -> "(Bool (Rt.contains (${expr(v.list)}) (${expr(v.element)})))"
        is InMapKeys -> "(Bool (Rt.map_has (${expr(v.map)}) (${expr(v.key)})))"
        is AppendListItem -> call("Rt.list_append", v.list, v.element)
        is AppendAllListItems -> call("Rt.list_concat", v.list, v.elements)
        is PutMapItem -> call("Rt.map_put", v.map, v.key, v.value)
        is PutAllMapItems -> call("Rt.map_merge", v.map, v.elements)

        is IfElse -> "(if ${bool(v.cond)} then ${expr(v.then)} else ${expr(v.alt)})"
        is Panic -> "(Rt.fail ${string(v.message)})"

        is MapOp -> {
            val iterable = expr(v.iterable)
            names.scoped {
                val x = names.bind(v.name)
                "(Rt.map_list ($iterable) (fun $x -> ${expr(v.body)}))"
            }
        }
        is FoldOp -> {
            val iterable = expr(v.iterable)
            val init = expr(v.initAcc)
            names.scoped {
                val x = names.bind(v.item)
                val acc = names.bind(v.acc)
                "(Rt.fold ($iterable) ($init) (fun $acc $x -> ${expr(v.body)}))"
            }
        }

        is PortValue -> if (v.port.isNext) "(Port Rt.port_next)" else "(Port port_${v.port.name})"
        is PortRefValue -> "(PortRef (${expr(v.child)}, ${if (v.port.isNext) "Rt.port_next" else "port_${v.port.name}"}))"
        is BoundCheck -> "(Rt.f_bound _s (${expr(v.port)}))"
        is FlowGraphRef -> "(FlowGraph ${module.graphs.indexOf(v.graph)})"

        is Match -> match(v)
    }

    private fun builtin(b: Builtin): String {
        val all = listOfNotNull(b.receiver) + b.args
        fun rt(fn: String) = call("Rt.$fn", *all.toTypedArray())
        return when (b.name) {
            "int.str" -> "(Str (string_of_int (Rt.int_of (${expr(b.receiver!!)}))))"
            "long.str" -> "(Str (Int64.to_string (Rt.long_of (${expr(b.receiver!!)}))))"
            "str.toLong" -> rt("to_long")
            "float.str" -> "(Str (Rt.show_float (Rt.float_of (${expr(b.receiver!!)}))))"
            "bool.str" -> "(Str (Rt.show (${expr(b.receiver!!)})))"
            "str.toInt" -> rt("to_int")
            "str.toFloat" -> rt("to_float")
            "str.indexOf" -> rt("str_index_of")
            "str.startsWith" -> "(Bool ${rt("starts_with")})"
            "str.endsWith" -> "(Bool ${rt("ends_with")})"
            "str.replace" -> rt("replace")
            "str.upper" -> rt("upper")
            "str.lower" -> rt("lower")
            "str.trim" -> rt("trim")
            "str.split" -> rt("split")
            "str.code" -> rt("code")
            "str.utf8" -> rt("utf8")
            "str.unescape" -> rt("unescape")
            "char" -> rt("char")
            "fail" -> "(Rt.fail (Rt.str_of (${expr(b.args[0])})))"
            "str.get" -> rt("char_at")
            "str.slice", "List.slice" -> rt("slice")
            "str.contains" -> "(Bool ${rt("str_contains")})"
            "range" -> rt("range")
            "List.indexOf" -> rt("list_index_of")
            "List.reversed" -> rt("reversed")
            "List.toSet" -> rt("to_set")
            "List.join" -> rt("join")
            "Map.keys" -> rt("map_keys")
            "Map.values" -> rt("map_values")
            "Map.remove" -> rt("map_remove")
            "Set.toList" -> rt("to_list")
            "Set.remove" -> rt("set_remove")
            "Set.of" -> "(Rt.set_of [ ${b.args.joinToString("; ") { expr(it) }} ])"
            "Set.contains" -> "(Bool ${rt("set_contains")})"
            "Set.union" -> rt("set_union")
            else -> throw IllegalStateException("unknown builtin ${b.name}")
        }
    }

    private fun let(value: String, name: String, body: (String) -> String): String = names.scoped {
        val x = names.bind(name)
        "(let $x = $value in ${body(x)})"
    }

    private fun callOf(v: Call): String {
        val fn = v.target
        val owner = fn.receiver
        val receiver = v.receiver
        val all = listOfNotNull(receiver) + v.args
        fun args(values: List<Value>) = if (values.isEmpty()) "()" else values.joinToString(" ") { "(${expr(it)})" }
        return when {
            owner is ParserType -> "(parse_${owner.name}_${fn.name} ${args(v.args)})"
            owner is FlowGraphType -> {
                val id = module.graphs.indexOfFirst { it.name == owner.name }
                val method = mapOf("get" to "fg_get", "of" to "fg_of", "succ" to "fg_succ", "pred" to "fg_pred").getValue(fn.name)
                "(Rt.$method $id ${args(v.args)})"
            }
            owner is ComplexType && owner.name == GRAPH -> {
                val method = mapOf(
                    "succ" to "g_succ", "pred" to "g_pred", "outEdges" to "g_out", "inEdges" to "g_in", "contains" to "g_contains",
                    "indexOf" to "g_index", "exit" to "g_exit", "reachable" to "g_reachable", "postorder" to "g_postorder",
                    "reversePostorder" to "g_rpo", "toDot" to "g_dot",
                ).getValue(fn.name)
                "(Rt.$method ${args(all)})"
            }
            owner == null && fn.body == null && fn.name == "graphOf" -> "(Rt.graph_from ${args(v.args)})"
            owner == null && fn.body == null && fn.name == "spanOf" -> "(Rt.span_of ${args(v.args)})"
            fn.body == null -> "(!ext_${s.functionName(fn)} ${args(all)})"
            else -> "(${functionId(fn)} ${args(all)})"
        }
    }

    private val patterns = object : TargetSupport.Patterns {
        override fun fresh(): String = names.fresh("m")
        override fun isItem(subject: String, item: EnumItem): String = "Rt.rec_is $subject ${rid(item.enumName + "." + item.itemName)}"
        override fun itemField(subject: String, item: EnumItem, field: String): String = "(Rt.field $subject ${item.fields.keys.indexOf(field)})"
        override fun sizeIs(subject: String, size: Int): String = "Array.length (Rt.items $subject) = $size"
        override fun notEmpty(subject: String): String = "Array.length (Rt.items $subject) > 0"
        override fun element(subject: String, index: Int): String = "(Rt.items $subject).($index)"
        override fun tail(subject: String): String = "(Rt.tail $subject)"
        override fun equalTo(subject: String, value: Value): String = "Rt.eq $subject (${expr(value)})"
        override fun bindVariable(variable: LocalRef): String = names.bind(variable.name)
    }

    private fun match(m: Match): String {
        val scrutinee = expr(m.scrutinee)
        return names.scoped {
            val subject = names.fresh("subject")
            val cases = m.cases.map { case ->
                names.scoped {
                    val steps = s.steps(case.pattern, subject, patterns)
                    val guard = case.guard?.let { bool(it) }
                    val body = expr(case.body)
                    var result = if (guard != null) "(if $guard then $body else NoMatch)" else body
                    for (step in steps.reversed()) {
                        result = when (step) {
                            is TargetSupport.Step.Test -> "(if ${step.cond} then $result else NoMatch)"
                            is TargetSupport.Step.Bind -> "(let ${step.name} = ${step.value} in $result)"
                        }
                    }
                    "(fun () -> $result)"
                }
            }
            val alt = m.alt?.let { "(Some (fun () -> ${expr(it)}))" } ?: "None"
            "(let $subject = $scrutinee in Rt.match_cases $subject [ ${cases.joinToString("; ")} ] $alt)"
        }
    }
