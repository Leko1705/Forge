package com.leko.forge.gen

import com.leko.forge.context.Context
import com.leko.forge.llir.Function
import com.leko.forge.llir.*
import com.leko.forge.model.VERTEX
import com.leko.forge.types.*
import com.leko.forge.utils.Options

/**
 * Generates one Kotlin file (JVM) from a module.
 *
 * - nodes become classes extending `__Node` (parent links, children, inherited attributes) and interfaces
 *   extending `Vertex`; attributes become properties whose values are cached per node
 * - `circular` attributes are computed as fixpoints (`__Circular`)
 * - enums become sealed classes, records data classes
 * - `graph` declarations become `__FlowGraph`s, their flows one dispatch function per graph
 *
 * Options: `-p <package>` sets the package of the generated file.
 */
object KotlinTarget : Target {

    private const val INDENT = "    "

    override val extension: String get() = ".kt"

    override val name: String get() = "kotlin"

    override fun generate(module: LLIRModule, context: Context): ByteArray {
        val pkg = Options.instance(context).get("-p")?.firstOrNull()
        return Generation(module, pkg).run().toByteArray()
    }

    private val KEYWORDS = setOf(
        "as", "break", "class", "continue", "do", "else", "false", "for", "fun", "if", "in", "interface", "is",
        "null", "object", "package", "return", "super", "this", "throw", "true", "try", "typealias", "typeof",
        "val", "var", "when", "while",
    )

    /** A Kotlin identifier for a Forge name. */
    private fun id(name: String): String = if (name in KEYWORDS) "`$name`" else name

    private class Generation(private val module: LLIRModule, private val pkg: String?) {

        private val sb = StringBuilder()
        private var labels = 0
        private val nodeNames = module.nodes.map { it.name }.toSet()
        private val vertex = module.nodes.first { it.name == VERTEX }

        fun run(): String {
            sb.appendLine("// Generated by Forge${module.sourceName?.let { " from $it" } ?: ""}. Do not edit.")
            sb.appendLine("@file:Suppress(\"UNCHECKED_CAST\", \"USELESS_CAST\", \"UNUSED_VARIABLE\", \"NAME_SHADOWING\", \"ClassName\", \"FunctionName\", \"PropertyName\", \"ObjectPropertyName\", \"LocalVariableName\", \"RemoveRedundantQualifierName\", \"unused\", \"REDUNDANT_ELSE_IN_WHEN\", \"KotlinConstantConditions\", \"SENSELESS_COMPARISON\", \"USELESS_IS_CHECK\")")
            if (pkg != null) sb.appendLine("\npackage $pkg")
            sb.appendLine(KOTLIN_RUNTIME)
            if (module.parsers.isNotEmpty()) sb.appendLine(KOTLIN_PARSER_RUNTIME)

            generateCaches()
            generatePorts()
            generateNodeBase()
            module.nodes.forEach { generateNode(it) }
            generateRuntimeVertices()
            module.enums.forEach { generateEnum(it) }
            module.records.forEach { generateRecord(it) }
            module.functions.forEach { generateFunction(it) }
            module.graphs.forEach { generateGraph(it) }
            module.parsers.forEach { generateParser(it) }
            generateTuples()
            return sb.toString()
        }

        // ---- declarations ------------------------------------------------------------------

        private fun generateCaches() {
            val names = linkedSetOf<String>()
            for (inh in module.inherited.values) names += "inh_${inh.name}"
            for (node in module.nodes) {
                node.synthetics.values.filter { it.body != null }.forEach { names += "syn_${it.name}" }
                node.collections.values.forEach { names += "coll_${it.name}" }
            }
            for (name in names) {
                sb.appendLine("private val __cache_$name = __Cache<kotlin.Any?>(\"${name.substringAfter('_')}\")")
            }
            val circulars = module.nodes.flatMap { it.circulars.keys }.toSet()
            for (name in circulars) {
                sb.appendLine("private val __circ_$name = __Circular<kotlin.Any?>()")
            }
            sb.appendLine()
        }

        private fun generatePorts() {
            for (port in module.ports) {
                if (port.isNext) continue
                sb.appendLine("val __port_${port.name}: __Port = __Port(\"${port.name}\", ${port.inherited})")
            }
            sb.appendLine()
        }

        /** `__Node`: parent links, children and the inherited attributes, which every node has. */
        private fun generateNodeBase() {
            sb.appendLine("/** The inherited attributes, which every node has. */")
            sb.appendLine("interface __Inherited {")
            for (inh in module.inherited.values) sb.appendLine("${INDENT}val ${id(inh.name)}: ${typeRepr(inh.type)}")
            sb.appendLine("}")
            sb.appendLine()
            sb.appendLine("abstract class __Node : Vertex, __Inherited {")
            sb.appendLine("${INDENT}var __parent: __Node? = null")
            sb.appendLine("${INDENT}/** Set by parsers: where the node was read from. */")
            sb.appendLine("${INDENT}var __span: Span? = null")
            sb.appendLine("${INDENT}abstract val __children: kotlin.collections.List<__Node>")
            sb.appendLine()
            sb.appendLine("${INDENT}/** The root of the tree this node is part of. */")
            sb.appendLine("${INDENT}val __root: __Node get() { var n: __Node = this; while (true) { n = n.__parent ?: return n } }")
            sb.appendLine()
            sb.appendLine("${INDENT}protected fun __adopt() { for (c in __children) c.__parent = this }")
            for (inh in module.inherited.values) {
                val type = typeRepr(inh.type)
                sb.appendLine()
                sb.appendLine("$INDENT// inh ${inh.name}: ${inh.type}")
                sb.append("${INDENT}override val ${id(inh.name)}: $type get() = __cache_inh_${inh.name}.get(this) { val __p = __parent; if (__p != null) __p.__inh_${inh.name}(this) else ")
                value(inh.init)
                sb.appendLine(" } as $type")
                sb.appendLine("$INDENT/** The value of '${inh.name}' this node passes to [__child]; by default its own. */")
                sb.appendLine("${INDENT}open fun __inh_${inh.name}(__child: __Node): $type = ${id(inh.name)}")
            }
            sb.appendLine("}")
            sb.appendLine()
        }

        private fun generateNode(node: Node) {
            if (node.isInterface) generateInterface(node) else generateClass(node)
        }

        private fun generateInterface(node: Node) {
            sb.appendLine(if (node.isBuiltin) "/** A vertex of a graph: a node, or a synthetic or exit vertex of a flow. */" else "// interface node ${node.name}")
            sb.append("interface ${id(node.name)}")
            val supertypes = node.parents.map { id(it.name) } + if (node.isBuiltin) emptyList() else listOf("__Inherited")
            if (supertypes.isNotEmpty()) sb.append(" : ").append(supertypes.joinToString(", "))
            sb.appendLine(" {")
            generateAttributes(node)
            sb.appendLine("}")
            sb.appendLine()
        }

        private fun generateClass(node: Node) {
            sb.appendLine("// node ${node.name}")
            sb.append("class ${id(node.name)}(")
            sb.append(node.fields.entries.joinToString(", ") { (name, type) -> "val ${id(name)}: ${typeRepr(type)}" })
            sb.append(") : __Node()")
            node.parents.filter { it !== vertex }.forEach { sb.append(", ${id(it.name)}") }
            sb.appendLine(" {")

            sb.appendLine("${INDENT}override val __children: kotlin.collections.List<__Node> get() {")
            sb.appendLine("${INDENT}${INDENT}val __c = kotlin.collections.ArrayList<__Node>()")
            for ((name, type) in node.fields) {
                when {
                    isNode(type) -> sb.appendLine("$INDENT${INDENT}__c.add(this.${id(name)} as __Node)")
                    type is OptionalType && isNode(type.elem) -> sb.appendLine("$INDENT${INDENT}this.${id(name)}?.let { __c.add(it as __Node) }")
                    type is ListType && isNode(type.elem) -> sb.appendLine("$INDENT${INDENT}this.${id(name)}.forEach { __c.add(it as __Node) }")
                    type is ListType && type.elem is OptionalType && isNode((type.elem as OptionalType).elem) ->
                        sb.appendLine("$INDENT${INDENT}this.${id(name)}.forEach { if (it != null) __c.add(it as __Node) }")
                }
            }
            sb.appendLine("${INDENT}${INDENT}return __c")
            sb.appendLine("${INDENT}}")
            sb.appendLine()
            sb.appendLine("${INDENT}init { __adopt() }")
            sb.appendLine()

            generateAttributes(node)

            for (eq in node.inhEquations.values) generateInhEquation(node, eq)

            for (coll in node.collections.values) generateColl(node, coll)

            sb.append("${INDENT}override fun toString(): kotlin.String = \"${node.name}(\"")
            node.fields.keys.forEachIndexed { i, name ->
                if (i > 0) sb.append(" + \", \"")
                sb.append(" + this.${id(name)}")
            }
            sb.appendLine(" + \")\"")
            sb.appendLine("}")
            sb.appendLine()
        }

        /** syn and circular attributes declared on [node] (on interfaces: declarations or defaults). */
        private fun generateAttributes(node: Node) {
            for (syn in node.synthetics.values) {
                val type = typeRepr(syn.type)
                val modifier = if (node.inheritsAttribute(syn.name)) "override " else ""
                sb.appendLine("$INDENT// syn ${syn.name}: ${syn.type}")
                val body = syn.body
                if (body == null) {
                    sb.appendLine("$INDENT${modifier}val ${id(syn.name)}: $type")
                }
                else {
                    sb.append("$INDENT${modifier}val ${id(syn.name)}: $type get() = __cache_syn_${syn.name}.get(this) { ")
                    value(body)
                    sb.appendLine(" } as $type")
                }
            }
            for (circular in node.circulars.values) {
                val type = typeRepr(circular.type)
                val modifier = if (node.inheritsAttribute(circular.name)) "override " else ""
                sb.appendLine("$INDENT// circular ${circular.name}: ${circular.type}")
                sb.append("$INDENT${modifier}val ${id(circular.name)}: $type get() = __circ_${circular.name}.get(this, ")
                value(circular.init)
                sb.append(") { ")
                value(circular.body)
                sb.appendLine(" } as $type")
            }
        }

        private fun generateInhEquation(node: Node, eq: InhEquation) {
            val attr = module.inherited[eq.attrName] ?: return
            val type = typeRepr(attr.type)
            sb.appendLine("$INDENT// inh ${node.name}.${eq.attrName}")
            sb.appendLine("${INDENT}override fun __inh_${eq.attrName}(__child: __Node): $type {")
            for (delegate in eq.delegates) {
                val field = "this.${id(delegate.field)}"
                val fieldType = node.fields[delegate.field]
                val key = delegate.key
                if (key == null || fieldType !is ListType) {
                    sb.append("$INDENT${INDENT}if (__child === $field) return ")
                    value(delegate.value)
                    sb.appendLine()
                }
                else {
                    sb.appendLine("$INDENT${INDENT}run {")
                    sb.appendLine("$INDENT$INDENT${INDENT}val __index = $field.indexOfFirst { it === __child }")
                    val binder = delegate.binder
                    if (binder != null) {
                        sb.append("$INDENT$INDENT${INDENT}if (__index >= 0) for (${id(binder.name)} in 0 until $field.size) if ((")
                    } else {
                        sb.append("$INDENT$INDENT${INDENT}if (__index >= 0 && (")
                    }
                    value(key)
                    sb.append(") == __index) return ")
                    value(delegate.value)
                    sb.appendLine()
                    sb.appendLine("$INDENT${INDENT}}")
                }
            }
            sb.appendLine("$INDENT${INDENT}return super.__inh_${eq.attrName}(__child)")
            sb.appendLine("${INDENT}}")
            sb.appendLine()
        }

        /** Folds the contributions of all nodes of the tree (in preorder) that target this node. */
        private fun generateColl(node: Node, coll: CollAttribute) {
            val type = typeRepr(coll.type)
            sb.appendLine("$INDENT// coll ${coll.name}: ${coll.type}")
            sb.appendLine("${INDENT}val ${id(coll.name)}: $type get() = __cache_coll_${coll.name}.get(this) {")
            sb.appendLine("$INDENT${INDENT}val __target = this")
            sb.append("$INDENT${INDENT}var __acc: $type = ")
            value(coll.init)
            sb.appendLine()
            if (coll.contributions.isNotEmpty()) {
                sb.appendLine("$INDENT${INDENT}for (__n in __preorder(this.__root)) {")
                for (c in coll.contributions) {
                    sb.append("$INDENT$INDENT${INDENT}if (__n is ${id(c.source.name)}) __n.run { if ((")
                    value(c.target)
                    sb.append(") === __target) { val ${id(c.alias)}: $type = __acc; __acc = ")
                    value(c.value)
                    sb.appendLine(" } }")
                }
                sb.appendLine("$INDENT${INDENT}}")
            }
            sb.appendLine("$INDENT${INDENT}__acc")
            sb.appendLine("${INDENT}} as $type")
            sb.appendLine()
        }

        /** The exit and synthetic vertices of flows; they implement the attributes declared on `Vertex`. */
        private fun generateRuntimeVertices() {
            val abstract = vertex.synthetics.values.filter { it.body == null }
            fun members(what: String) {
                for (syn in abstract) {
                    sb.appendLine("${INDENT}override val ${id(syn.name)}: ${typeRepr(syn.type)} get() = kotlin.error(\"attribute '${syn.name}' is not defined for \" + this + \" ($what)\")")
                }
            }
            sb.appendLine("/** The vertex an unbound port of a root leads to, e.g. the end of a function. */")
            sb.appendLine("class __ExitVertex(val port: __Port) : Vertex {")
            members("an exit vertex")
            sb.appendLine("${INDENT}override fun toString(): kotlin.String = \"exit(\" + port + \")\"")
            sb.appendLine("}")
            sb.appendLine()
            sb.appendLine("/** A vertex declared in a flow (`vertex name`). */")
            sb.appendLine("class __SyntheticVertex(val name: kotlin.String, val owner: kotlin.Any) : Vertex {")
            members("a synthetic vertex")
            sb.appendLine("${INDENT}override fun toString(): kotlin.String = name")
            sb.appendLine("}")
            sb.appendLine()
        }

        private fun generateEnum(enum: LLIREnum) {
            sb.appendLine("// enum ${enum.name}")
            sb.appendLine("sealed class ${id(enum.name)}${typeParamList(enum.typeParams)} {")
            for (item in enum.items) {
                // an item has the type parameters its fields use; the others are Nothing (generic enums are covariant)
                val own = itemTypeParams(enum, item)
                val supertype = id(enum.name) + if (enum.typeParams.isEmpty()) "" else enum.typeParams.joinToString(", ", "<", ">") { if (it in own) it else "kotlin.Nothing" }
                if (item.fields.isEmpty()) {
                    sb.appendLine("${INDENT}data object ${id(item.itemName)} : $supertype()")
                }
                else {
                    val params = item.fields.entries.joinToString(", ") { (n, t) -> "val ${id(n)}: ${typeRepr(t)}" }
                    sb.appendLine("${INDENT}data class ${id(item.itemName)}${typeParamList(own)}($params) : $supertype()")
                }
            }
            sb.appendLine("}")
            sb.appendLine()
        }

        /** `<out A, out B>`: generic records and enums are covariant. */
        private fun typeParamList(params: List<String>): String = if (params.isEmpty()) "" else params.joinToString(", ", "<", ">") { "out $it" }

        /** The type parameters of a generic enum that the fields of [item] use. */
        private fun itemTypeParams(enum: LLIREnum, item: EnumItem): List<String> {
            val used = item.fields.values.flatMap { it.typeVars() }.toSet()
            return enum.typeParams.filter { it in used }
        }

        private fun generateRecord(record: Record) {
            sb.appendLine("// record ${record.name}")
            if (record.fields.isEmpty()) {
                sb.appendLine("class ${id(record.name)} {")
                sb.appendLine("${INDENT}override fun equals(other: kotlin.Any?): kotlin.Boolean = other is ${id(record.name)}")
                sb.appendLine("${INDENT}override fun hashCode(): kotlin.Int = 0")
                sb.appendLine("${INDENT}override fun toString(): kotlin.String = \"${record.name}()\"")
                sb.appendLine("}")
            }
            else {
                val params = record.fields.entries.joinToString(", ") { (n, t) -> "val ${id(n)}: ${typeRepr(t)}" }
                sb.appendLine("data class ${id(record.name)}${typeParamList(record.typeParams)}($params)")
            }
            sb.appendLine()
        }

        private fun generateFunction(function: Function) {
            val body = function.body ?: return   // external: implemented in Kotlin elsewhere
            sb.appendLine("// function ${function.name}")
            // methods on lists, sets, maps erase to `name(List, ...)` on the JVM, as functions do
            function.receiver?.takeIf { it is ListType || it is SetType || it is MapType || it is OptionalType }?.let {
                val key = typeRepr(it).replace("kotlin.collections.", "").replace("kotlin.", "").replace(Regex("[^A-Za-z0-9]+"), "_").trim('_')
                sb.appendLine("@kotlin.jvm.JvmName(\"${function.name}__$key\")")
            }
            sb.append("fun ")
            if (function.typeParams.isNotEmpty()) {
                // one bound in the list, more after `where`
                sb.append("<" + function.typeParams.joinToString(", ") { tv ->
                    function.typeBounds[tv]?.singleOrNull()?.let { "$tv : ${typeRepr(it)}" } ?: tv
                } + "> ")
            }
            function.receiver?.let { sb.append(typeRepr(it)).append(".") }
            sb.append(id(function.name)).append("(")
            sb.append(function.parameters.joinToString(", ") { "${id(it.name)}: ${typeRepr(it.type)}" })
            sb.append("): ").append(typeRepr(function.returnType))
            val more = function.typeBounds.filterValues { it.size > 1 }
            if (more.isNotEmpty()) sb.append(" where ").append(more.flatMap { (tv, bounds) -> bounds.map { "$tv : ${typeRepr(it)}" } }.joinToString(", "))
            sb.append(" = ")
            value(body)
            sb.appendLine()
            sb.appendLine()
        }

        // ---- parsers -----------------------------------------------------------------------

        private val terminals = linkedMapOf<GTerminal, String>()
        private val bitPatterns = linkedMapOf<GBits, String>()

        /** The label variables of the option being generated: label -> its `__Label`. */
        private var labelSlots: Map<String, String> = emptyMap()

        private var currentRule: GrammarRule? = null

        /**
         * `object P { val __r_x: __Rule<T> = ...; fun x(source): T }`: one rule object per rule, and a function
         * per rule that parses a whole input with it.
         */
        private fun generateParser(parser: ParserDecl) {
            terminals.clear()
            bitPatterns.clear()
            for (rule in parser.rules.values) for (alt in rule.alternatives) for (option in alt.options) collectConstants(option.body)

            sb.appendLine("// parser ${parser.name}")
            sb.appendLine("object ${id(parser.name)} {")
            sb.appendLine("${INDENT}private val __skip: kotlin.String? = ${parser.skip?.let { string(it) } ?: "null"}")
            sb.appendLine("${INDENT}private val __keywords: kotlin.collections.Set<kotlin.String> = kotlin.collections.setOf(${parser.keywords.joinToString(", ") { string(it) }})")
            for ((t, name) in terminals) {
                sb.appendLine("${INDENT}private val $name = __Terminal(${string(t.regex)}, ${t.literal?.let { string(it) } ?: "null"}, ${t.name?.let { string(it) } ?: "null"})")
            }
            for ((b, name) in bitPatterns) {
                sb.appendLine("${INDENT}private val $name = __Bits(${string(b.bits)}, ${string(b.description)})")
            }
            sb.appendLine()

            for (rule in parser.rules.values) {
                val type = typeRepr(rule.type)
                currentRule = rule
                if (rule.isAbstract) {
                    sb.appendLine("${INDENT}val __r_${rule.name}: __AbstractRule<$type> = __AbstractRule(${string(rule.name)})")
                } else {
                    sb.append("${INDENT}val __r_${rule.name}: __Rule<$type> = __Rule(${string(rule.name)}) { ")
                    alternative(rule.alternatives.single())
                    sb.appendLine(" }")
                }
            }
            val abstract = parser.rules.values.filter { it.isAbstract }
            if (abstract.isNotEmpty()) {
                sb.appendLine()
                sb.appendLine("${INDENT}init {")
                for (rule in abstract) {
                    currentRule = rule
                    for (alt in rule.alternatives) {
                        sb.append("$INDENT${INDENT}__r_${rule.name}.")
                        when (alt.operator) {
                            null -> sb.append("on { ")
                            OperatorKind.PREFIX -> sb.append("prefix(${alt.precedence}) { ")
                            OperatorKind.INFIX_LEFT -> sb.append("infixLeft(${alt.precedence}) { __left -> ")
                            OperatorKind.INFIX_RIGHT -> sb.append("infixRight(${alt.precedence}) { __left -> ")
                            OperatorKind.POSTFIX -> sb.append("postfix(${alt.precedence}) { __left -> ")
                        }
                        alternative(alt)
                        sb.appendLine(" }")
                    }
                }
                sb.appendLine("${INDENT}}")
            }
            currentRule = null
            sb.appendLine()

            for (rule in parser.rules.values) {
                val type = typeRepr(rule.type)
                val name = id(rule.name)
                sb.appendLine("$INDENT/** Parses all of [source] as ${rule.name}; throws a [ParseException] if it does not match. */")
                if (parser.binary) {
                    sb.appendLine("${INDENT}fun $name(source: kotlin.ByteArray, sourceName: kotlin.String? = null): $type = __parseBinary(__r_${rule.name}, source, __skip, __keywords, sourceName)")
                    sb.appendLine("${INDENT}fun $name(source: kotlin.collections.List<kotlin.Int>, sourceName: kotlin.String? = null): $type = $name(kotlin.ByteArray(source.size) { source[it].toByte() }, sourceName)")
                } else {
                    sb.appendLine("${INDENT}fun $name(source: kotlin.String, sourceName: kotlin.String? = null): $type = __parseText(__r_${rule.name}, source, __skip, __keywords, sourceName)")
                }
            }
            sb.appendLine("}")
            sb.appendLine()
        }

        private fun collectConstants(e: GExpr) {
            when (e) {
                is GTerminal -> terminals.getOrPut(e) { "__t${terminals.size}" }
                is GBits -> bitPatterns.getOrPut(e) { "__b${bitPatterns.size}" }
                is GPrimitive, is GNonterminal -> {}
                is GRepeat -> collectConstants(e.expr)
                is GPredicate -> collectConstants(e.expr)
                is GChoice -> e.alternatives.forEach { collectConstants(it) }
                is GSequence -> e.items.forEach { collectConstants(it.expr) }
            }
        }

        /** The options of an alternative, tried in order. */
        private fun alternative(alt: GrammarAlternative) {
            val single = alt.options.singleOrNull()
            if (single != null) {
                option(single)
                return
            }
            sb.append("__oneOf(")
            alt.options.forEachIndexed { i, option ->
                if (i > 0) sb.append(", ")
                sb.append("{ ")
                option(option)
                sb.append(" }")
            }
            sb.append(")")
        }

        /** `run { <labels>; val v = <body>; <producer or v> }` */
        private fun option(option: GrammarOption) {
            val outer = labelSlots
            val n = labels++
            labelSlots = option.labels.associate { (name, _) -> name to "__l${n}_$name" }
            sb.append("run { ")
            for ((name, type) in option.labels) {
                val slot = labelSlots.getValue(name)
                sb.append("val $slot = __Label<${typeRepr(type)}>(${string(name)}); val ${id(name)}: ${typeRepr(type)} by $slot; ")
            }
            val producer = option.producer
            if (producer == null) {
                grammar(option.body)
            } else {
                grammar(option.body)
                sb.append("; ")
                value(producer)
            }
            sb.append(" }")
            labelSlots = outer
        }

        private fun lambda(e: GExpr) {
            sb.append("{ ")
            grammar(e)
            sb.append(" }")
        }

        /** A Kotlin expression that parses [e] (in a `__ParseScope`) and evaluates to its value. */
        private fun grammar(e: GExpr) {
            when (e) {
                is GTerminal -> sb.append("__terminal(${terminals.getValue(e)})")
                is GBits -> sb.append("__bits(${bitPatterns.getValue(e)})")
                is GPrimitive -> {
                    sb.append("__${e.name}(")
                    e.argument?.let { value(it) }
                    sb.append(")")
                }
                is GNonterminal -> when (e.role) {
                    NonterminalRole.RULE -> sb.append("__apply(__r_${e.rule})")
                    NonterminalRole.LEFT -> sb.append("__left")
                    NonterminalRole.OPERAND -> sb.append("__operand<${typeRepr(currentRule!!.type)}>()")
                }
                is GRepeat -> {
                    when (e.kind) {
                        RepeatKind.OPTIONAL -> sb.append("__optional ")
                        RepeatKind.MANY -> sb.append("__many ")
                        RepeatKind.SOME -> sb.append("__some ")
                        RepeatKind.COUNT -> {
                            sb.append("__repeat(")
                            value(e.count!!)
                            sb.append(") ")
                        }
                    }
                    lambda(e.expr)
                }
                is GPredicate -> {
                    if (e.negate) sb.append("__not(${string(describe(e.expr))}) ") else sb.append("__and ")
                    lambda(e.expr)
                }
                is GChoice -> {
                    sb.append("__oneOf(")
                    e.alternatives.forEachIndexed { i, alt ->
                        if (i > 0) sb.append(", ")
                        lambda(alt)
                    }
                    sb.append(")")
                }
                is GSequence -> {
                    val n = labels++
                    sb.append("run { ")
                    e.items.forEachIndexed { i, item ->
                        sb.append("val __i${n}_$i = ")
                        grammar(item.expr)
                        sb.append("; ")
                        item.label?.let { sb.append("${labelSlots.getValue(it)}.set(__i${n}_$i); ") }
                    }
                    when (val v = e.valueIndex) {
                        null -> sb.append("kotlin.Unit")
                        -1 -> sb.append("kotlin.collections.listOf(${e.items.indices.joinToString(", ") { "__i${n}_$it" }})")
                        else -> sb.append("__i${n}_$v")
                    }
                    sb.append(" }")
                }
            }
        }

        /** How a parsing expression is named in error messages (`!x`). */
        private fun describe(e: GExpr): String = when (e) {
            is GTerminal -> e.name ?: e.literal?.let { "'$it'" } ?: "/${e.regex}/"
            is GBits -> e.description
            is GPrimitive -> "@${e.name}"
            is GNonterminal -> e.rule
            is GRepeat -> describe(e.expr)
            is GPredicate -> describe(e.expr)
            is GChoice -> e.alternatives.joinToString(" or ") { describe(it) }
            is GSequence -> e.items.joinToString(" ") { describe(it.expr) }
        }

        /** A graph definition and the dispatch of its flows: the most specific node type wins, then the last flow. */
        private fun generateGraph(graph: FlowGraphDecl) {
            val rules = graph.flows.withIndex()
                .sortedWith(compareByDescending<IndexedValue<FlowRule>> { it.value.node.ancestors().size }.thenByDescending { it.index })
                .map { it.value }
            sb.appendLine("// flows of graph ${graph.name}")
            sb.appendLine("private fun __flow_${graph.name}(__s: __FlowScope, __n: kotlin.Any): kotlin.Boolean {")
            sb.appendLine("${INDENT}when (__n) {")
            for (rule in rules) {
                sb.appendLine("$INDENT${INDENT}is ${id(rule.node.name)} -> __n.run {")
                for ((local, field) in rule.binders) {
                    sb.appendLine("$INDENT$INDENT${INDENT}val ${id(local)} = this.${id(field)}")
                }
                rule.body.forEach { flowStmt(it, 3) }
                sb.appendLine("$INDENT$INDENT}")
            }
            sb.appendLine("$INDENT${INDENT}else -> return false")
            sb.appendLine("${INDENT}}")
            sb.appendLine("${INDENT}return true")
            sb.appendLine("}")
            sb.appendLine()
            sb.appendLine("// graph ${graph.name}: ${graph.root.name}")
            sb.appendLine("val ${id(graph.name)}: __FlowGraph<${id(graph.root.name)}> = __FlowGraph({ it is ${id(graph.root.name)} }, ::__flow_${graph.name})")
            sb.appendLine()
        }

        private fun flowStmt(stmt: FlowStmt, depth: Int) {
            val indent = INDENT.repeat(depth)
            when (stmt) {
                is FlowEntry -> {
                    sb.append("${indent}__s.entry(")
                    value(stmt.target)
                    sb.appendLine(")")
                }
                is FlowConnect -> {
                    sb.append("${indent}__s.connect(")
                    value(stmt.source)
                    sb.append(", ")
                    value(stmt.target)
                    sb.append(", ")
                    stmt.label?.let { value(it) } ?: sb.append("null")
                    sb.appendLine(")")
                }
                is FlowSequence -> {
                    sb.append("${indent}__s.sequence(")
                    value(stmt.items)
                    sb.appendLine(")")
                }
                is FlowVertex -> {
                    sb.append("${indent}val ${id(stmt.name)} = __s.vertex(__SyntheticVertex(")
                    stmt.label?.let { value(it) } ?: sb.append(string(stmt.name))
                    sb.appendLine(", this))")
                }
                is FlowIf -> {
                    sb.append("${indent}if (")
                    value(stmt.cond)
                    sb.appendLine(") {")
                    stmt.then.forEach { flowStmt(it, depth + 1) }
                    sb.appendLine("$indent} else {")
                    stmt.alt.forEach { flowStmt(it, depth + 1) }
                    sb.appendLine("$indent}")
                }
                is FlowFor -> {
                    sb.append("${indent}for (${id(stmt.name)} in ")
                    value(stmt.iterable)
                    sb.appendLine(") {")
                    stmt.body.forEach { flowStmt(it, depth + 1) }
                    sb.appendLine("$indent}")
                }
            }
        }

        // ---- types -------------------------------------------------------------------------

        private fun isNode(type: Type): Boolean = type is ComplexType && type.name in nodeNames

        /** The number of type parameters of the generic records and enums. */
        private val genericParams: Map<String, Int> =
            (module.records.map { it.name to it.typeParams.size } + module.enums.map { it.name to it.typeParams.size }).filter { it.second > 0 }.toMap()

        /** The arities of the tuples used; their classes are generated at the end. */
        private val tupleArities = sortedSetOf<Int>()

        private fun tupleClass(arity: Int): String {
            tupleArities += arity
            return "__Tuple$arity"
        }

        private fun generateTuples() {
            for (n in tupleArities) {
                val params = (0 until n).joinToString(", ") { "out A$it" }
                val fields = (0 until n).joinToString(", ") { "val e$it: A$it" }
                sb.appendLine("/** A tuple of $n values: `t.0` is `t.e0`. */")
                sb.appendLine("data class __Tuple$n<$params>($fields) {")
                sb.appendLine("${INDENT}override fun toString(): kotlin.String = \"(\" + ${(0 until n).joinToString(" + \", \" + ") { "e$it" }} + \")\"")
                sb.appendLine("}")
                sb.appendLine()
            }
        }

        /** A type for `is` tests: generic types with `*`, as their type arguments are not known at run time. */
        private fun testedType(type: Type): String = when (type) {
            is ComplexType -> id(type.name) + (genericParams[type.name]?.let { n -> List(n) { "*" }.joinToString(", ", "<", ">") } ?: "")
            is TupleType -> tupleClass(type.elems.size) + List(type.elems.size) { "*" }.joinToString(", ", "<", ">")
            is ListType -> "kotlin.collections.List<*>"
            is SetType -> "kotlin.collections.Set<*>"
            is MapType -> "kotlin.collections.Map<*, *>"
            is FunctionType -> "kotlin.Function${type.parameters.size}<${List(type.parameters.size + 1) { "*" }.joinToString(", ")}>"
            is OptionalType -> testedType(type.elem) + "?"
            else -> typeRepr(type)
        }

        private fun typeRepr(type: Type): String = when (type) {
            BoolType -> "kotlin.Boolean"
            IntType -> "kotlin.Int"
            FloatType -> "kotlin.Float"
            StrType -> "kotlin.String"
            NullType -> "kotlin.Nothing?"
            is ListType -> "kotlin.collections.List<${typeRepr(type.elem)}>"
            is MapType -> "kotlin.collections.Map<${typeRepr(type.key)}, ${typeRepr(type.value)}>"
            is SetType -> "kotlin.collections.Set<${typeRepr(type.elem)}>"
            is OptionalType -> if (type.elem is FunctionType) "(${typeRepr(type.elem)})?" else "${typeRepr(type.elem)}?"
            is ComplexType -> id(type.name) + when {
                type.args.isNotEmpty() -> type.args.joinToString(", ", "<", ">") { typeRepr(it) }
                // a generic type without type arguments (where Forge does not know them): any of its values
                else -> genericParams[type.name]?.let { n -> List(n) { "*" }.joinToString(", ", "<", ">") } ?: ""
            }
            is TupleType -> tupleClass(type.elems.size) + type.elems.joinToString(", ", "<", ">") { typeRepr(it) }
            LongType -> "kotlin.Long"
            is ParserType -> id(type.name)
            is FunctionType -> "(${type.parameters.joinToString(", ") { typeRepr(it) }}) -> ${typeRepr(type.returnType)}"
            is FlowGraphType -> "__FlowGraph<${id(type.root)}>"
            PortType -> "__Port"
            PortRefType -> "__PortRef"
            ArbitraryType -> "kotlin.Any?"
            NothingType -> "kotlin.Nothing"
            is TypeVar -> type.name
            ErrorType, is TerminalRuleProduction -> throw IllegalStateException("should not reach here for $type")
        }

        // ---- values ------------------------------------------------------------------------

        private fun string(s: String): String = buildString {
            append('"')
            for (c in s) {
                when (c) {
                    '\\' -> append("\\\\")
                    '"' -> append("\\\"")
                    '$' -> append("\\$")
                    '\n' -> append("\\n")
                    '\r' -> append("\\r")
                    '\t' -> append("\\t")
                    else -> append(c)
                }
            }
            append('"')
        }

        /** The type arguments of a generic record in a constructor call, as Forge inferred them. */
        private fun typeArgs(type: Type) {
            val args = (type as? ComplexType)?.args.orEmpty()
            if (args.isNotEmpty()) sb.append(args.joinToString(", ", "<", ">") { typeRepr(it) })
        }

        private fun binary(v: BinaryValue, op: String) {
            sb.append("(")
            value(v.lhs)
            sb.append(" $op ")
            value(v.rhs)
            sb.append(")")
        }

        private fun args(values: List<Value>) {
            values.forEachIndexed { i, v ->
                if (i > 0) sb.append(", ")
                value(v)
            }
        }

        private fun postfix(receiver: Value, member: String) {
            sb.append("(")
            value(receiver)
            sb.append(").").append(member)
        }

        private fun value(value: Value) {
            when (value) {
                // -2147483648 would be a Long literal
                is IntValue -> if (value.value == Int.MIN_VALUE) sb.append("kotlin.Int.MIN_VALUE") else sb.append(value.value)
                is LongValue -> if (value.value == Long.MIN_VALUE) sb.append("kotlin.Long.MIN_VALUE") else sb.append(value.value).append("L")
                is FloatValue -> sb.append(value.value).append("f")
                is BoolValue -> sb.append(value.value)
                is StringValue -> sb.append(string(value.value))
                NullValue -> sb.append("null")

                is Parameter -> sb.append(id(value.name))
                is LocalRef -> sb.append(id(value.name))
                is This -> sb.append("this")
                is AccessParentInhAttr -> sb.append(id(value.name))

                is ListLiteral -> {
                    val elem = (value.type as? ListType)?.elem
                    sb.append("kotlin.collections.listOf")
                    if (elem != null && elem != ArbitraryType && elem != ErrorType) sb.append("<${typeRepr(elem)}>")
                    sb.append("(")
                    args(value.list)
                    sb.append(")")
                }
                is MapLiteral -> {
                    val type = value.type as? MapType
                    sb.append("kotlin.collections.mapOf")
                    if (type != null && type.key != ArbitraryType && type.value != ArbitraryType) sb.append("<${typeRepr(type.key)}, ${typeRepr(type.value)}>")
                    sb.append("(")
                    value.entries.forEachIndexed { i, (k, v) ->
                        if (i > 0) sb.append(", ")
                        value(k)
                        sb.append(" to ")
                        value(v)
                    }
                    sb.append(")")
                }

                is Call -> {
                    val receiver = value.receiver
                    val owner = value.target.receiver
                    when {
                        receiver != null -> postfix(receiver, id(value.target.name))
                        owner is ParserType -> sb.append(id(owner.name)).append(".").append(id(value.target.name))
                        else -> sb.append(id(value.target.name))
                    }
                    sb.append("(")
                    args(value.args)
                    sb.append(")")
                }
                is CreateRecord -> {
                    sb.append(id(value.target.name))
                    typeArgs(value.type)
                    sb.append("(")
                    args(value.args)
                    sb.append(")")
                }
                is CreateEnum -> {
                    sb.append(id(value.target.enumName)).append(".").append(id(value.target.itemName))
                    if (value.target.fields.isNotEmpty()) {
                        val enum = module.enums.first { it.name == value.target.enumName }
                        val own = itemTypeParams(enum, value.target)
                        val args = (value.type as? ComplexType)?.args.orEmpty()
                        if (own.isNotEmpty() && args.size == enum.typeParams.size) {
                            sb.append(own.joinToString(", ", "<", ">") { typeRepr(args[enum.typeParams.indexOf(it)]) })
                        }
                        sb.append("(")
                        args(value.args)
                        sb.append(")")
                    }
                }
                is CreateNode -> {
                    sb.append(id(value.target.name)).append("(")
                    args(value.args)
                    sb.append(")")
                }

                is AccessRecordField -> postfix(value.accessed, if (value.target.name == "str" && value.name == "size") "length" else id(value.name))
                is AccessNodeField -> postfix(value.accessed, id(value.name))
                is AccessNodeAttr -> postfix(value.receiver, id(value.name))
                is AccessListContainer -> {
                    sb.append("__index(")
                    value(value.container)
                    sb.append(", ")
                    value(value.key)
                    sb.append(")")
                }
                is AccessMapContainer -> {
                    sb.append("(")
                    value(value.container)
                    sb.append(").getValue(")
                    value(value.key)
                    sb.append(")")
                }

                is Int2Float -> postfix(value.value, "toFloat()")
                is Float2Int -> postfix(value.value, "toInt()")
                is Int2Long -> postfix(value.value, "toLong()")
                is Long2Int -> postfix(value.value, "toInt()")
                is Long2Float -> postfix(value.value, "toFloat()")
                is Float2Long -> postfix(value.value, "toLong()")

                is Let -> {
                    sb.append("run { val ${id(value.name)}: ${typeRepr(value.valueType)} = ")
                    value(value.value)
                    sb.append("; ")
                    value(value.body)
                    sb.append(" }")
                }
                // an anonymous function: its result type is declared, and `this` is the one where it is written
                is Lambda -> {
                    sb.append("(fun(")
                    sb.append(value.params.joinToString(", ") { "${id(it.name)}: ${typeRepr(it.type)}" })
                    sb.append("): ${typeRepr(value.type.returnType)} = ")
                    value(value.body)
                    sb.append(")")
                }
                is CallValue -> {
                    sb.append("(")
                    value(value.function)
                    sb.append(")(")
                    args(value.args)
                    sb.append(")")
                }
                is TupleLiteral -> {
                    sb.append(tupleClass(value.elems.size)).append("(")
                    args(value.elems)
                    sb.append(")")
                }
                is TupleGet -> postfix(value.tuple, "e${value.index}")
                is Cast -> {
                    sb.append("(")
                    value(value.value)
                    sb.append(" as ${typeRepr(value.type)})")
                }
                is IsInstanceOf -> {
                    sb.append("(")
                    value(value.value)
                    sb.append(" is ${testedType(value.target)})")
                }

                is NegateInt -> { sb.append("(-"); value(value.value); sb.append(")") }
                is NegateFloat -> { sb.append("(-"); value(value.value); sb.append(")") }
                is InvertBool -> { sb.append("(!"); value(value.value); sb.append(")") }
                is InvertInt -> postfix(value.value, "inv()")
                is IsNull -> { sb.append("("); value(value.checked); sb.append(" == null)") }
                is NotNull -> { sb.append("("); value(value.value); sb.append("!!)") }
                is Elvis -> { sb.append("("); value(value.value); sb.append(" ?: "); value(value.alt); sb.append(")") }

                is MulInt, is MulFloat -> binary(value as BinaryValue, "*")
                is DivInt, is DivFloat -> binary(value as BinaryValue, "/")
                is ModInt -> binary(value, "%")
                is AddInt, is AddFloat, is ConcatStr, is MergeLists, is MergeMaps -> binary(value as BinaryValue, "+")
                is SubInt, is SubFloat -> binary(value as BinaryValue, "-")
                is AndInt, is IAnd -> binary(value as BinaryValue, "and")
                is ShlInt -> binary(value, "shl")
                is ShrInt -> binary(value, "shr")
                is UshrInt -> binary(value, "ushr")
                is SetEquals -> binary(value, "==")
                is Builtin -> builtin(value)
                is OrInt, is IOr -> binary(value as BinaryValue, "or")
                is XorInt, is XorBool -> binary(value as BinaryValue, "xor")
                is AndBool -> binary(value, "&&")
                is OrBool -> binary(value, "||")
                is LtInt, is LtFloat -> binary(value as BinaryValue, "<")
                is GtInt, is GtFloat -> binary(value as BinaryValue, ">")
                is LeqInt, is LeqFloat -> binary(value as BinaryValue, "<=")
                is GeqInt, is GeqFloat -> binary(value as BinaryValue, ">=")
                is IntEquals, is FloatEquals, is BoolEquals, is StringEquals, is ListEquals, is MapEquals,
                is EnumEquals, is RecordEquals -> binary(value as BinaryValue, "==")
                is NodeEquals -> binary(value, "===")

                is InList -> { sb.append("("); value(value.element); sb.append(" in "); value(value.list); sb.append(")") }
                is InMapKeys -> { sb.append("("); value(value.key); sb.append(" in "); value(value.map); sb.append(")") }
                is AppendListItem -> { sb.append("("); value(value.list); sb.append(" + "); value(value.element); sb.append(")") }
                is AppendAllListItems -> { sb.append("("); value(value.list); sb.append(" + "); value(value.elements); sb.append(")") }
                is PutMapItem -> {
                    sb.append("(")
                    value(value.map)
                    sb.append(" + (")
                    value(value.key)
                    sb.append(" to ")
                    value(value.value)
                    sb.append("))")
                }
                is PutAllMapItems -> { sb.append("("); value(value.map); sb.append(" + "); value(value.elements); sb.append(")") }

                is IfElse -> {
                    sb.append("(if (")
                    value(value.cond)
                    sb.append(") ")
                    value(value.then)
                    sb.append(" else ")
                    value(value.alt)
                    sb.append(")")
                }
                is Panic -> sb.append("kotlin.error(${string(value.message)})")


                is PortValue -> sb.append(if (value.port.isNext) "__Port.next" else "__port_${value.port.name}")
                is PortRefValue -> {
                    sb.append("__PortRef(")
                    value(value.child)
                    sb.append(", ")
                    value(PortValue(value.port))
                    sb.append(")")
                }
                is BoundCheck -> {
                    sb.append("__s.bound(")
                    value(value.port)
                    sb.append(")")
                }
                is FlowGraphRef -> sb.append(id(value.graph.name))

                is Match -> match(value)
            }
        }

        // ---- builtins ----------------------------------------------------------------------

        private fun builtin(b: Builtin) {
            val r = b.receiver
            fun call(fn: String) {
                sb.append(fn).append("(")
                args(listOfNotNull(r) + b.args)
                sb.append(")")
            }
            fun method(member: String) {
                postfix(r!!, member)
                sb.append("(")
                args(b.args)
                sb.append(")")
            }
            fun infix(op: String, left: Value, right: Value) {
                sb.append("(")
                value(left)
                sb.append(" $op ")
                value(right)
                sb.append(")")
            }
            when (b.name) {
                "int.str", "long.str", "float.str", "bool.str" -> method("toString")
                "str.toInt" -> call("__toInt")
                "str.toLong" -> call("__toLong")
                "str.toFloat" -> call("__toFloat")
                "str.indexOf", "List.indexOf" -> method("indexOf")
                "str.startsWith" -> method("startsWith")
                "str.endsWith" -> method("endsWith")
                "str.replace" -> call("__replace")
                "str.upper" -> method("uppercase")
                "str.lower" -> method("lowercase")
                "str.trim" -> method("trim")
                "str.split" -> call("__split")
                "str.code" -> call("__code")
                "str.utf8" -> call("__utf8")
                "str.unescape" -> call("__unescape")
                "char" -> call("__char")
                "fail" -> call("kotlin.error")
                "str.get" -> call("__charAt")
                "str.slice", "List.slice" -> call("__slice")
                "str.contains", "Set.contains" -> infix("in", b.args[0], r!!)
                "range" -> call("__range")
                "List.reversed" -> method("reversed")
                "List.toSet" -> method("toSet")
                "List.join" -> method("joinToString")
                "Map.keys" -> postfix(r!!, "keys.toList()")
                "Map.values" -> postfix(r!!, "values.toList()")
                "Map.remove", "Set.remove" -> infix("-", r!!, b.args[0])
                "Set.toList" -> method("toList")
                "Set.union" -> infix("+", r!!, b.args[0])
                "Set.of" -> {
                    val elem = (b.type as? SetType)?.elem
                    sb.append("kotlin.collections.setOf")
                    if (elem != null && elem != ArbitraryType && elem != ErrorType) sb.append("<${typeRepr(elem)}>")
                    sb.append("(")
                    args(b.args)
                    sb.append(")")
                }
                else -> throw IllegalStateException("unknown builtin ${b.name}")
            }
        }

        // ---- match -------------------------------------------------------------------------

        /**
         * `run<T> m@{ val s = scrutinee; run c@{ <tests, return@c on mismatch>; return@m body } ...; alt }`
         */
        private fun match(m: Match) {
            val id = labels++
            val label = "__m$id"
            val subject = "__s${id}_0"
            sb.append("run<${typeRepr(m.type)}> $label@{ val $subject = ")
            value(m.scrutinee)
            sb.append("; ")
            m.cases.forEachIndexed { i, case ->
                val caseLabel = "__c${id}_$i"
                sb.append("run $caseLabel@{ ")
                var vars = 0
                fun fresh(): String = "__s${id}_${i}_${vars++}"
                fun pattern(p: MatchPattern, s: String) {
                    when (p) {
                        WildcardPattern -> {}
                        is BindPattern -> sb.append("val ${id(p.variable.name)} = $s; ")
                        is ValuePattern -> {
                            sb.append("if ($s != ")
                            value(p.value)
                            sb.append(") return@$caseLabel; ")
                        }
                        is ConstructorPattern -> {
                            val enum = module.enums.first { it.name == p.item.enumName }
                            val own = itemTypeParams(enum, p.item)
                            val star = if (own.isEmpty()) "" else own.joinToString(", ", "<", ">") { "*" }
                            sb.append("if ($s !is ${id(p.item.enumName)}.${id(p.item.itemName)}$star) return@$caseLabel; ")
                            p.item.fields.keys.zip(p.args).forEachIndexed { i, (field, arg) ->
                                if (arg == WildcardPattern) return@forEachIndexed
                                val v = fresh()
                                // the type of the field of this value: of the type arguments of a generic enum
                                val type = p.fieldTypes.getOrNull(i)
                                sb.append("val $v = $s.${id(field)}${if (own.isNotEmpty() && type != null) " as ${typeRepr(type)}" else ""}; ")
                                pattern(arg, v)
                            }
                        }
                        is TuplePattern -> {
                            p.elements.forEachIndexed { i, element ->
                                if (element == WildcardPattern) return@forEachIndexed
                                val v = fresh()
                                sb.append("val $v = $s.e$i; ")
                                pattern(element, v)
                            }
                        }
                        is ListPattern -> {
                            sb.append("if ($s.size != ${p.elements.size}) return@$caseLabel; ")
                            p.elements.forEachIndexed { index, element ->
                                if (element == WildcardPattern) return@forEachIndexed
                                val v = fresh()
                                sb.append("val $v = $s[$index]; ")
                                pattern(element, v)
                            }
                        }
                        is SplitPattern -> {
                            sb.append("if ($s.isEmpty()) return@$caseLabel; ")
                            val head = fresh()
                            val tail = fresh()
                            sb.append("val $head = $s[0]; val $tail = $s.drop(1); ")
                            pattern(p.head, head)
                            pattern(p.tail, tail)
                        }
                    }
                }
                pattern(case.pattern, subject)
                case.guard?.let {
                    sb.append("if (!(")
                    value(it)
                    sb.append(")) return@$caseLabel; ")
                }
                sb.append("return@$label ")
                value(case.body)
                sb.append(" }; ")
            }
            val alt = m.alt
            if (alt != null) value(alt) else sb.append("kotlin.error(\"no match for \" + $subject)")
            sb.append(" }")
        }
    }
