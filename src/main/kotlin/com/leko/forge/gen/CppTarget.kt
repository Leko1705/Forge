/**
 * Generates one C++17 header (standard library only) with the module in a namespace named after the file
 * (or `-p <namespace>`).
 *
 * Values are `rt::V` (`rt::I(1)`, `rt::S("x")`, `rt::L({...})`, nodes, records, ...). Functions take and
 * return them: `report()`, `compile(rt::S("Main"), rt::S(source))`; methods are named after their receiver
 * (`Type_repr`). Attributes are functions too: `attr_type(node)`, `inh_scope(node)`, `coll_diags(node)`.
 * `ext fun`s are declared and must be defined by the program that includes the header, e.g.
 * `rt::V conformance::int_text(rt::V self)`. A failed parse throws `rt::ParseException`.
 */
object CppTarget : Target {
    override val name: String get() = "cpp"
    override val extension: String get() = ".hpp"

    override fun outputName(module: LLIRModule, base: String): String = base.replace(Regex("[^A-Za-z0-9_]"), "_")

    override fun generate(module: LLIRModule, context: Context): ByteArray {
        val options = Options.instance(context)
        val base = java.io.File(options.get("-o")?.firstOrNull() ?: module.sourceName ?: "out").nameWithoutExtension
        val namespace = options.get("-p")?.firstOrNull()?.replace(".", "::") ?: outputName(module, base).lowercase()
        return CppGeneration(module, namespace).run().toByteArray()
    }
}

private val CPP_KEYWORDS = setOf(
    "alignas", "alignof", "and", "and_eq", "asm", "auto", "bitand", "bitor", "bool", "break", "case", "catch", "char",
    "char16_t", "char32_t", "class", "compl", "const", "constexpr", "const_cast", "continue", "decltype", "default",
    "delete", "do", "double", "dynamic_cast", "else", "enum", "explicit", "export", "extern", "false", "float", "for",
    "friend", "goto", "if", "inline", "int", "long", "mutable", "namespace", "new", "noexcept", "not", "not_eq",
    "nullptr", "operator", "or", "or_eq", "private", "protected", "public", "register", "reinterpret_cast", "return",
    "short", "signed", "sizeof", "static", "static_assert", "static_cast", "struct", "switch", "template", "this",
    "thread_local", "throw", "true", "try", "typedef", "typeid", "typename", "union", "unsigned", "using", "virtual",
    "void", "volatile", "wchar_t", "while", "xor", "xor_eq", "rt", "V", "std", "main", "assert", "errno", "NULL",
    "EOF", "stdin", "stdout", "stderr", "exit", "abort",
)

private class CppGeneration(private val module: LLIRModule, private val namespace: String) {
    private val s = TargetSupport(module)
    private val names = Names(CPP_KEYWORDS)
    private val out = StringBuilder()
    private val kinds: Map<Node, Int> = s.concrete.withIndex().associate { (i, n) -> n to i }
    private val rids = mutableMapOf<String, Int>()
    private fun rid(key: String) = rids.getOrPut(key) { rids.size + 1 }

    private fun line(text: String = "") { out.append(text).append('\n') }
    private fun id(name: String) = names.id(name)
    /** Calls are qualified: values are in namespace rt, whose functions argument-dependent lookup would find. */
    private val q = "::$namespace::"

    fun run(): String {
        line("// Generated by Forge${module.sourceName?.let { " from ${java.io.File(it).name}" } ?: ""}. Do not edit.")
        line("#pragma once")
        line(runtimeResource("cpp.hpp"))
        line("namespace $namespace {")
        line("using rt::V;")
        line()
        // declarations: everything may refer to everything
        for (fn in module.functions) {
            if (isBuiltinFunction(fn)) continue
            line("${if (fn.body == null) "" else "inline "}V ${functionId(fn)}(${params(fn).joinToString(", ") { "V $it" }});")
        }
        for (name in s.attributeNames) line("inline V attr_$name(V self);")
        for (name in module.inherited.keys) {
            line("inline V inh_$name(V self);")
            line("inline V pass_$name(V self, V child);")
        }
        for (name in s.collectionNames) line("inline V coll_$name(V self);")
        module.graphs.forEach { line("inline bool flow_${it.name}(rt::Scope& _s, const V& n);") }
        for (parser in module.parsers) {
            line("struct ${parser.name}_grammar;")
            line("inline ${parser.name}_grammar& ${parser.name}_g();")
            for (rule in parser.rules.values) line("inline V parse_${parser.name}_${rule.name}(V input);")
        }
        line()
        for (enum in module.enums) for (item in enum.items) {
            if (item.fields.isEmpty()) line("inline V ${itemConst(item)}() { static V v = rt::new_rec(${rid(enum.name + "." + item.itemName)}, ${string(item.itemName)}, {}, true, {}); return v; }")
        }
        for (port in module.ports) if (!port.isNext) line("inline V port_${port.name}() { static V p = rt::new_port(${string(port.name)}, ${port.inherited}); return p; }")
        for (name in s.attributeNames) {
            line("inline rt::Cache cache_syn_$name{${string(name)}};")
            line("inline rt::Circular circ_$name;")
        }
        for (name in module.inherited.keys) line("inline rt::Cache cache_inh_$name{${string(name)}};")
        for (name in s.collectionNames) line("inline rt::Cache cache_coll_$name{${string(name)}};")
        line()

        generateAttributes()
        module.functions.forEach { generateFunction(it) }
        module.graphs.forEach { generateGraph(it) }
        module.parsers.forEach { generateParser(it) }

        line("inline bool __flow(int graph, rt::Scope& s, const V& n) {")
        line("    switch (graph) {")
        module.graphs.forEachIndexed { i, g -> line("        case $i: return flow_${g.name}(s, n);") }
        line("    }")
        line("    return false;")
        line("}")
        line("inline bool __is_root(int graph, const V& n) {")
        line("    switch (graph) {")
        module.graphs.forEachIndexed { i, g -> line("        case $i: return ${isNode(g.root, "n")};") }
        line("    }")
        line("    return false;")
        line("}")
        line("inline struct __Init {")
        line("    __Init() {")
        line("        rt::kind_names() = {${s.concrete.joinToString(", ") { string(it.name) }}};")
        line("        rt::flow_rule() = &__flow;")
        line("        rt::flow_is_root() = &__is_root;")
        line("    }")
        line("} __init;")
        line()
        line("} // namespace $namespace")
        return out.toString()
    }

    private fun isBuiltinFunction(fn: Function) = fn.receiver == null && fn.body == null && fn.name in setOf("graphOf", "spanOf")
    private fun itemConst(item: EnumItem) = "e_${item.enumName}_${item.itemName}"
    private fun functionId(fn: Function): String = id(s.functionName(fn))

    private fun params(fn: Function): List<String> = names.scoped {
        listOfNotNull(fn.receiver?.let { "self" }) + fn.parameters.map { names.bind(it.name) }
    }

    // ---- attributes ----------------------------------------------------------------------------------

    private fun dispatchTargets(): List<Pair<String, Node>> =
        s.concrete.map { kinds.getValue(it).toString() to it } + listOf("rt::EXIT_KIND" to s.vertex, "rt::SYNTHETIC_KIND" to s.vertex)

    private fun body(v: Value): String = names.scoped {
        names.alias("this", "self")
        expr(v)
    }

    private fun generateAttributes() {
        for (name in s.attributeNames) {
            line("inline V attr_$name(V self) {")
            line("    switch (rt::kind(self)) {")
            for ((kind, node) in dispatchTargets()) {
                when (val eq = s.equation(node, name) ?: continue) {
                    is TargetSupport.Equation.Syn ->
                        line("        case $kind: return rt::cached(cache_syn_$name, self, [&]() -> V { return ${body(eq.body)}; });")
                    is TargetSupport.Equation.Circular ->
                        line("        case $kind: return circ_$name.get(self, ${body(eq.attr.init)}, [&]() -> V { return ${body(eq.attr.body)}; });")
                    TargetSupport.Equation.Missing -> line("        case $kind: break;")
                }
            }
            line("    }")
            line("    rt::fail(\"attribute '$name' is not defined for \" + rt::show(self));")
            line("}")
        }

        for (inh in module.inherited.values) {
            val name = inh.name
            line("inline V inh_$name(V self) {")
            line("    return rt::cached(cache_inh_$name, self, [&]() -> V { V p = rt::node_of(self).parent; return p.is_null() ? ${body(inh.init)} : pass_$name(p, self); });")
            line("}")
            line("inline V pass_$name(V self, V child) {")
            line("    switch (rt::kind(self)) {")
            for (node in s.concrete) {
                val eq = node.inhEquations[name] ?: continue
                line("        case ${kinds.getValue(node)}: {")
                names.scoped {
                    names.alias("this", "self")
                    for (d in eq.delegates) {
                        val field = expr(d.child)
                        val key = d.key
                        if (key == null || d.child.type !is ListType) {
                            line("            if (rt::same(child, $field)) return ${expr(d.value)};")
                        } else {
                            val list = names.fresh("list")
                            val index = names.fresh("index")
                            val k = names.fresh("k")
                            line("            { V $list = $field; int $index = rt::index_of_child($list, child);")
                            names.scoped {
                                val b = d.binder?.let { names.bind(it.name) } ?: names.fresh("i")
                                line("              if ($index >= 0) for (int $k = 0; $k < static_cast<int>(rt::items($list).size()); $k++) { V $b = rt::I($k); if (rt::int_of(${expr(key)}) == $index) return ${expr(d.value)}; } }")
                            }
                        }
                    }
                }
                line("            break;")
                line("        }")
            }
            line("    }")
            line("    return inh_$name(self);")
            line("}")
        }

        for (name in s.collectionNames) {
            line("inline V coll_$name(V self) {")
            line("    switch (rt::kind(self)) {")
            for (node in s.concrete) {
                val coll = node.collections[name] ?: continue
                line("        case ${kinds.getValue(node)}: return rt::cached(cache_coll_$name, self, [&]() -> V {")
                val acc = names.fresh("acc")
                line("            V $acc = ${body(coll.init)};")
                if (coll.contributions.isNotEmpty()) {
                    val n = names.fresh("n")
                    line("            for (const V& $n : rt::preorder(rt::root(self))) {")
                    for (c in coll.contributions) {
                        names.scoped {
                            names.alias("this", n)
                            line("                if (${isNode(c.source, n)} && rt::same(${expr(c.target)}, self)) {")
                            names.scoped {
                                val alias = names.bind(c.alias)
                                line("                    V $alias = $acc;")
                                line("                    $acc = ${expr(c.value)};")
                            }
                            line("                }")
                        }
                    }
                    line("            }")
                }
                line("            return $acc;")
                line("        });")
            }
            line("    }")
            line("    rt::fail(\"collection '$name' is not defined for \" + rt::show(self));")
            line("}")
        }
        line()
    }

    // ---- functions -----------------------------------------------------------------------------------

    private fun generateFunction(fn: Function) {
        val body = fn.body ?: return
        names.scoped {
            val params = mutableListOf<String>()
            if (fn.receiver != null) {
                params += "self"
                names.alias("this", "self")
            }
            for (p in fn.parameters) params += names.bind(p.name)
            line("inline V ${functionId(fn)}(${params.joinToString(", ") { "V $it" }}) {")
            line("    return ${expr(body)};")
            line("}")
        }
    }

    // ---- graphs --------------------------------------------------------------------------------------

    private fun generateGraph(graph: FlowGraphDecl) {
        line("inline bool flow_${graph.name}(rt::Scope& _s, const V& n) {")
        for (rule in s.flowRules(graph)) {
            line("    if (${isNode(rule.node, "n")}) {")
            names.scoped {
                names.alias("this", "n")
                for ((local, field) in rule.binders) {
                    val v = names.bind(local)
                    line("        V $v = rt::field(n, ${rule.node.fields.keys.indexOf(field)});")
                }
                rule.body.forEach { flowStmt(it, "        ") }
            }
            line("        return true;")
            line("    }")
        }
        line("    return false;")
        line("}")
    }

    private fun flowStmt(stmt: FlowStmt, indent: String) {
        when (stmt) {
            is FlowEntry -> line("${indent}rt::f_entry(_s, ${expr(stmt.target)});")
            is FlowConnect -> line("${indent}rt::f_connect(_s, ${expr(stmt.source)}, ${expr(stmt.target)}, ${stmt.label?.let { expr(it) } ?: "rt::Null()"});")
            is FlowSequence -> line("${indent}rt::f_sequence(_s, ${expr(stmt.items)});")
            is FlowVertex -> {
                val label = stmt.label?.let { expr(it) } ?: "rt::S(${string(stmt.name)})"
                val v = names.bind(stmt.name)
                line("${indent}V $v = rt::f_vertex(_s, rt::synthetic_vertex($label, n));")
            }
            is FlowIf -> {
                line("${indent}if (rt::truth(${expr(stmt.cond)})) {")
                names.scoped { stmt.then.forEach { flowStmt(it, "$indent    ") } }
                line("$indent} else {")
                names.scoped { stmt.alt.forEach { flowStmt(it, "$indent    ") } }
                line("$indent}")
            }
            is FlowFor -> {
                val iterable = expr(stmt.iterable)
                names.scoped {
                    val list = names.fresh("list")
                    val v = names.bind(stmt.name)
                    line("${indent}{ V $list = $iterable; for (const V& $v : rt::items($list)) {")
                    stmt.body.forEach { flowStmt(it, "$indent    ") }
                    line("$indent} }")
                }
            }
        }
    }

    // ---- parsers -------------------------------------------------------------------------------------

    private fun regex(regex: String): String {
        val p = RegexProgram.compile(regex)
        return "rt::Regex{{${p.code.joinToString(", ")}}, {${p.sets.joinToString(", ") { "{${it.joinToString(", ")}}" }}}, ${p.slots}}"
    }

    private var terminalNames: Map<GTerminal, String> = emptyMap()
    private var bitNames: Map<GBits, String> = emptyMap()
    private var grammarRef = ""
    private var left: String? = null

    private fun generateParser(parser: ParserDecl) {
        val p = parser.name
        grammarRef = "${p}_g()"
        val terminals = s.terminals(parser)
        val bits = s.bitPatterns(parser)
        terminalNames = terminals.withIndex().associate { (i, t) -> t to "$grammarRef.t$i" }
        bitNames = bits.withIndex().associate { (i, b) -> b to "$grammarRef.b$i" }
        line("struct ${p}_grammar {")
        line("    bool has_skip = ${parser.skip != null};")
        line("    rt::Regex skip = ${parser.skip?.let { regex(it) } ?: "rt::Regex{{5, 0, 0}, {}, 0}"};")
        line("    std::vector<std::string> keywords{${parser.keywords.joinToString(", ") { string(it) }}};")
        terminals.forEachIndexed { i, t ->
            line("    rt::Terminal t$i{${regex(t.regex)}, ${t.literal != null}, ${string(t.literal ?: "")}, ${string(s.display(t))}};")
        }
        bits.forEachIndexed { i, b -> line("    rt::Bits b$i{{${b.bits.map { it == '1' }.joinToString(", ")}}, ${string(b.description)}};") }
        for (rule in parser.rules.values) line("    rt::Rule r_${rule.name};")
        line("};")
        for (rule in parser.rules.values) {
            val entry = if (parser.binary) "rt::parse_binary" else "rt::parse_text"
            line("inline V parse_${p}_${rule.name}(V input) { auto& g = ${p}_g(); return $entry(g.r_${rule.name}, g.has_skip ? &g.skip : nullptr, &g.keywords, input); }")
        }
        line("inline ${p}_grammar& ${p}_g() {")
        line("    static ${p}_grammar* grammar = [] {")
        line("        auto* g = new ${p}_grammar();")
        for (rule in parser.rules.values) {
            val r = "g->r_${rule.name}"
            line("        $r.name = ${string(rule.name)};")
            if (!rule.isAbstract) {
                line("        $r.body = [](rt::PScope& _s) -> V { return ${alternative(rule.alternatives.single(), null)}; };")
                continue
            }
            line("        $r.abstract = true;")
            for (alt in rule.alternatives) {
                when (alt.operator) {
                    null -> line("        $r.on([](rt::PScope& _s) -> V { return ${alternative(alt, null)}; });")
                    OperatorKind.PREFIX -> line("        $r.prefix(${alt.precedence}, [](rt::PScope& _s) -> V { return ${alternative(alt, null)}; });")
                    else -> {
                        val method = when (alt.operator) {
                            OperatorKind.INFIX_LEFT -> "infix_left"
                            OperatorKind.INFIX_RIGHT -> "infix_right"
                            else -> "postfix"
                        }
                        line("        $r.$method(${alt.precedence}, [](rt::PScope& _s, const V& _left) -> V { return ${alternative(alt, "_left")}; });")
                    }
                }
            }
        }
        line("        return g;")
        line("    }();")
        line("    return *grammar;")
        line("}")
        line()
    }

    private fun thunk(code: String) = "[&]() -> V { return $code; }"

    private fun alternative(alt: GrammarAlternative, leftName: String?): String {
        left = leftName
        val options = alt.options.map { option(it) }
        return options.singleOrNull() ?: "_s.one_of({${options.joinToString(", ") { thunk(it) }}})"
    }

    private fun option(option: GrammarOption): String = names.scoped {
        val cells = option.labels.map { (name, _) ->
            val cell = names.fresh("label_$name")
            names.alias(name, "$cell.get()")
            name to cell
        }
        val labels = cells.toMap()
        val body = grammar(option.body, labels)
        if (cells.isEmpty() && option.producer == null) body
        else {
            val declarations = cells.joinToString(" ") { (name, cell) -> "rt::Label $cell(${string(name)});" }
            val result = if (option.producer == null) "return $body;" else "$body; return ${expr(option.producer!!)};"
            "[&]() -> V { $declarations $result }()"
        }
    }

    private fun grammar(e: GExpr, labels: Map<String, String>): String = when (e) {
        is GTerminal -> "_s.terminal(${terminalNames.getValue(e)})"
        is GBits -> "_s.bits(${bitNames.getValue(e)})"
        is GPrimitive -> "_s.${e.name}(${e.argument?.let { expr(it) } ?: ""})"
        is GNonterminal -> when (e.role) {
            NonterminalRole.RULE -> "_s.apply($grammarRef.r_${e.rule})"
            NonterminalRole.LEFT -> left ?: "rt::Null()"
            NonterminalRole.OPERAND -> "_s.operand()"
        }
        is GRepeat -> {
            val body = thunk(grammar(e.expr, labels))
            when (e.kind) {
                RepeatKind.OPTIONAL -> "_s.optional($body)"
                RepeatKind.MANY -> "_s.many($body)"
                RepeatKind.SOME -> "_s.some($body)"
                RepeatKind.COUNT -> "_s.repeat(${expr(e.count!!)}, $body)"
            }
        }
        is GPredicate -> if (e.negate) "_s.not_(${string(s.describe(e.expr))}, ${thunk(grammar(e.expr, labels))})"
            else "_s.and_(${thunk(grammar(e.expr, labels))})"
        is GChoice -> "_s.one_of({${e.alternatives.joinToString(", ") { thunk(grammar(it, labels)) }}})"
        is GSequence -> {
            val items = e.items.joinToString(", ") { item ->
                "{${thunk(grammar(item.expr, labels))}, ${item.label?.let { "&" + labels.getValue(it) } ?: "nullptr"}}"
            }
            "_s.seq({$items}, ${e.valueIndex ?: -2})"
        }
    }

    // ---- values --------------------------------------------------------------------------------------

    private fun string(text: String): String = buildString {
        append('"')
        for (b in text.toByteArray(Charsets.UTF_8)) {
            val c = b.toInt() and 0xFF
            when {
                c == '\\'.code -> append("\\\\")
                c == '"'.code -> append("\\\"")
                c == '\n'.code -> append("\\n")
                c == '\t'.code -> append("\\t")
                c == '\r'.code -> append("\\r")
                c == '?'.code -> append("\\?")
                c < 32 || c > 126 -> append("\\%03o".format(c))
                else -> append(c.toChar())
            }
        }
        append('"')
    }

    private fun isNode(node: Node, v: String): String =
        if (node === s.vertex) "rt::is_vertex($v)" else "rt::kind_in($v, {${s.concreteOf(node).joinToString(", ") { kinds.getValue(it).toString() }}})"

    private fun isTest(type: Type, v: String): String = when {
        type is OptionalType -> "($v.is_null() || ${isTest(type.elem, v)})"
        type == IntType -> "($v.tag == V::INT)"
        type == LongType -> "($v.tag == V::LONG)"
        type is TupleType -> "($v.tag == V::LIST)"
        type is FunctionType -> "($v.tag == V::FN)"
        type == FloatType -> "($v.tag == V::FLOAT)"
        type == BoolType -> "($v.tag == V::BOOL)"
        type == StrType -> "($v.tag == V::STR)"
        type is ListType -> "($v.tag == V::LIST)"
        type is MapType -> "($v.tag == V::MAP)"
        type is SetType -> "($v.tag == V::SET)"
        type is ComplexType -> when {
            type.name == EDGE -> "($v.tag == V::EDGE)"
            type.name == GRAPH -> "($v.tag == V::GRAPH)"
            type.name == SPAN -> "rt::rec_is($v, rt::SPAN_RID)"
            type.name in s.nodeNames -> isNode(s.nodeOf(type)!!, v)
            type.name in s.enumNames -> module.enums.first { it.name == type.name }.items
                .joinToString(" || ", "(", ")") { "rt::rec_is($v, ${rid(type.name + "." + it.itemName)})" }
            else -> "rt::rec_is($v, ${rid(type.name)})"
        }
        else -> "true"
    }

    private fun b(v: Value) = "rt::truth(${expr(v)})"
    private fun i(v: Value) = if (v.type == LongType) "rt::long_of(${expr(v)})" else "rt::int_of(${expr(v)})"
    private fun f(v: Value) = "rt::float_of(${expr(v)})"
    private fun call(fn: String, vararg args: Value) = "$fn(${args.joinToString(", ") { expr(it) }})"
    private fun list(values: List<Value>) = "{${values.joinToString(", ") { expr(it) }}}"

    private fun let(value: String, name: String, body: (String) -> String): String = names.scoped {
        val x = names.bind(name)
        "[&]() -> V { V $x = $value; return ${body(x)}; }()"
    }

    fun expr(v: Value): String = when (v) {
        is LongValue -> if (v.value == Long.MIN_VALUE) "rt::Lg(INT64_MIN)" else "rt::Lg(INT64_C(${v.value}))"
        is Int2Long -> call("rt::i2l", v.value)
        is Long2Int -> call("rt::l2i", v.value)
        is Long2Float -> call("rt::l2f", v.value)
        is Float2Long -> call("rt::f2l", v.value)
        is Let -> let(expr(v.value), v.name) { _ -> expr(v.body) }
        // the variables it uses are copied into it: it may be called after they are gone
        is Lambda -> names.scoped {
            val args = names.fresh("args")
            val params = v.params.mapIndexed { index, p -> "V ${names.bind(p.name)} = $args[$index]; " }.joinToString("")
            "rt::fn([=](const rt::List& $args) -> V { ${params}return ${expr(v.body)}; })"
        }
        is CallValue -> "rt::call(${expr(v.function)}, ${list(v.args)})"
        // a tuple is a list: equal as lists are
        is TupleLiteral -> "rt::L(${list(v.elems)})"
        is TupleGet -> "rt::tuple_get(${expr(v.tuple)}, ${v.index})"
        is IntValue -> if (v.value == Int.MIN_VALUE) "rt::I(-2147483647 - 1)" else "rt::I(${v.value})"
        is FloatValue -> "rt::F(${v.value}f)"
        is BoolValue -> "rt::B(${v.value})"
        is StringValue -> "rt::S(${string(v.value)})"
        NullValue -> "rt::Null()"

        is Parameter -> names.lookup(v.name)
        is LocalRef -> names.lookup(v.name)
        is This -> names.lookup("this")
        is AccessParentInhAttr -> "${q}inh_${v.name}(${names.lookup("this")})"

        is ListLiteral -> "rt::L(${list(v.list)})"
        is MapLiteral -> "rt::M({${v.entries.joinToString(", ") { (k, x) -> "{${expr(k)}, ${expr(x)}}" }}})"

        is Call -> callOf(v)
        is CreateRecord -> when (v.target.name) {
            EDGE -> call("rt::new_edge", *v.args.toTypedArray())
            SPAN -> call("rt::new_span", *v.args.toTypedArray())
            else -> "rt::new_rec(${rid(v.target.name)}, ${string(v.target.name)}, {${v.target.fields.keys.joinToString(", ") { string(it) }}}, false, ${list(v.args)})"
        }
        is CreateEnum -> if (v.target.fields.isEmpty()) "${itemConst(v.target)}()"
            else "rt::new_rec(${rid(v.target.enumName + "." + v.target.itemName)}, ${string(v.target.itemName)}, {${v.target.fields.keys.joinToString(", ") { string(it) }}}, true, ${list(v.args)})"
        is CreateNode -> "rt::new_node(${kinds.getValue(v.target)}, ${list(v.args)})"

        is AccessRecordField -> when (v.target.name) {
            "List", "Map", "Set", "str" -> call("rt::size", v.accessed)
            EDGE -> "rt::edge_field(${expr(v.accessed)}, ${listOf("from", "to", "label").indexOf(v.name)})"
            GRAPH -> "rt::graph_field(${expr(v.accessed)}, ${listOf("entry", "vertices", "edges", "root").indexOf(v.name)})"
            else -> "rt::field(${expr(v.accessed)}, ${v.target.fields.keys.indexOf(v.name)})"
        }
        is AccessNodeField -> "rt::field(${expr(v.accessed)}, ${v.target.fields.keys.indexOf(v.name)})"
        is AccessNodeAttr -> when {
            v.name in module.inherited -> call("${q}inh_${v.name}", v.receiver)
            v.name in s.collectionNames && v.name !in s.attributeNames -> call("${q}coll_${v.name}", v.receiver)
            else -> call("${q}attr_${v.name}", v.receiver)
        }
        is AccessListContainer -> call("rt::get", v.container, v.key)
        is AccessMapContainer -> call("rt::map_at", v.container, v.key)

        is Int2Float -> call("rt::i2f", v.value)
        is Float2Int -> call("rt::f2i", v.value)
        is Cast -> {
            val node = s.nodeOf(v.type)
            if (node != null && node !== s.vertex) let(expr(v.value), "cast") { x ->
                "(${isNode(node, x)} || $x.is_null() ? $x : (rt::fail(\"can not cast \" + rt::show($x) + \" to ${node.name}\"), $x))"
            } else expr(v.value)
        }
        is IsInstanceOf -> let(expr(v.value), "x") { x -> "rt::B(${isTest(v.target, x)})" }

        is NegateInt -> call("rt::neg", v.value)
        is NegateFloat -> call("rt::fneg", v.value)
        is InvertBool -> "rt::B(!${b(v.value)})"
        is InvertInt -> call("rt::bnot", v.value)
        is IsNull -> "rt::B(${expr(v.checked)}.is_null())"
        is NotNull -> call("rt::nn", v.value)
        is Elvis -> "rt::elvis(${expr(v.value)}, [&]() -> V { return ${expr(v.alt)}; })"

        is MulInt -> call("rt::mul", v.lhs, v.rhs)
        is DivInt -> call("rt::div", v.lhs, v.rhs)
        is ModInt -> call("rt::rem", v.lhs, v.rhs)
        is AddInt -> call("rt::add", v.lhs, v.rhs)
        is SubInt -> call("rt::sub", v.lhs, v.rhs)
        is AndInt, is IAnd -> call("rt::band", (v as BinaryValue).lhs, v.rhs)
        is OrInt, is IOr -> call("rt::bor", (v as BinaryValue).lhs, v.rhs)
        is XorInt -> call("rt::bxor", v.lhs, v.rhs)
        is ShlInt -> call("rt::shl", v.lhs, v.rhs)
        is ShrInt -> call("rt::shr", v.lhs, v.rhs)
        is UshrInt -> call("rt::ushr", v.lhs, v.rhs)
        is SetEquals -> "rt::B(rt::eq(${expr(v.lhs)}, ${expr(v.rhs)}))"
        is Builtin -> builtin(v)
        is MulFloat -> call("rt::fmul", v.lhs, v.rhs)
        is DivFloat -> call("rt::fdiv", v.lhs, v.rhs)
        is AddFloat -> call("rt::fadd", v.lhs, v.rhs)
        is SubFloat -> call("rt::fsub", v.lhs, v.rhs)
        is LtInt -> "rt::B(${i(v.lhs)} < ${i(v.rhs)})"
        is GtInt -> "rt::B(${i(v.lhs)} > ${i(v.rhs)})"
        is LeqInt -> "rt::B(${i(v.lhs)} <= ${i(v.rhs)})"
        is GeqInt -> "rt::B(${i(v.lhs)} >= ${i(v.rhs)})"
        is LtFloat -> "rt::B(${f(v.lhs)} < ${f(v.rhs)})"
        is GtFloat -> "rt::B(${f(v.lhs)} > ${f(v.rhs)})"
        is LeqFloat -> "rt::B(${f(v.lhs)} <= ${f(v.rhs)})"
        is GeqFloat -> "rt::B(${f(v.lhs)} >= ${f(v.rhs)})"
        is AndBool -> "rt::B(${b(v.lhs)} && ${b(v.rhs)})"
        is OrBool -> "rt::B(${b(v.lhs)} || ${b(v.rhs)})"
        is XorBool -> "rt::B(${b(v.lhs)} != ${b(v.rhs)})"
        is IntEquals -> "rt::B(${i(v.lhs)} == ${i(v.rhs)})"
        is FloatEquals -> "rt::B(${f(v.lhs)} == ${f(v.rhs)})"
        is BoolEquals, is StringEquals, is ListEquals, is MapEquals, is EnumEquals, is RecordEquals, is NodeEquals ->
            "rt::B(rt::eq(${expr((v as BinaryValue).lhs)}, ${expr(v.rhs)}))"
        is ConcatStr -> call("rt::concat", v.lhs, v.rhs)
        is MergeLists -> call("rt::list_concat", v.lhs, v.rhs)
        is MergeMaps -> call("rt::map_merge", v.lhs, v.rhs)

        is InList -> "rt::B(rt::contains(${expr(v.list)}, ${expr(v.element)}))"
        is InMapKeys -> "rt::B(rt::map_has(${expr(v.map)}, ${expr(v.key)}))"
        is AppendListItem -> call("rt::list_append", v.list, v.element)
        is AppendAllListItems -> call("rt::list_concat", v.list, v.elements)
        is PutMapItem -> call("rt::map_put", v.map, v.key, v.value)
        is PutAllMapItems -> call("rt::map_merge", v.map, v.elements)

        is IfElse -> "(${b(v.cond)} ? ${expr(v.then)} : ${expr(v.alt)})"
        is Panic -> "(rt::fail(${string(v.message)}), rt::Null())"


        is PortValue -> if (v.port.isNext) "rt::port_next()" else "port_${v.port.name}()"
        is PortRefValue -> "rt::port_ref(${expr(v.child)}, ${expr(PortValue(v.port))})"
        is BoundCheck -> "rt::f_bound(_s, ${expr(v.port)})"
        is FlowGraphRef -> "rt::flow_graph(${module.graphs.indexOf(v.graph)})"

        is Match -> match(v)
    }

    private fun builtin(b: Builtin): String {
        val all = (listOfNotNull(b.receiver) + b.args).toTypedArray()
        fun rt(fn: String) = call("rt::$fn", *all)
        return when (b.name) {
            "int.str" -> "rt::S(std::to_string(rt::int_of(${expr(b.receiver!!)})))"
            "long.str" -> "rt::S(std::to_string(rt::long_of(${expr(b.receiver!!)})))"
            "str.toLong" -> rt("to_long")
            "float.str" -> "rt::S(rt::show_float(rt::float_of(${expr(b.receiver!!)})))"
            "str.toInt" -> rt("to_int")
            "str.toFloat" -> rt("to_float")
            "str.indexOf" -> rt("str_index_of")
            "str.startsWith" -> rt("starts_with")
            "str.endsWith" -> rt("ends_with")
            "str.replace" -> rt("replace")
            "str.upper" -> rt("upper")
            "str.lower" -> rt("lower")
            "str.trim" -> rt("trim")
            "str.split" -> rt("split")
            "str.code" -> rt("code")
            "str.utf8" -> rt("utf8")
            "str.unescape" -> rt("unescape")
            "char" -> rt("char_of")
            "fail" -> "(rt::fail(rt::str_of(${expr(b.args[0])})), rt::Null())"
            "str.get" -> rt("char_at")
            "str.slice", "List.slice" -> rt("slice")
            "str.contains" -> rt("str_contains")
            "range" -> rt("range")
            "List.indexOf" -> rt("list_index_of")
            "List.reversed" -> rt("reversed")
            "node.adopt" -> rt("adopt_children")
            "List.toSet" -> rt("to_set")
            "List.join" -> rt("join_str")
            "Map.keys" -> rt("map_keys")
            "Map.values" -> rt("map_values")
            "Map.remove" -> rt("map_remove")
            "Set.toList" -> rt("to_list")
            "Set.remove" -> rt("set_remove")
            "Set.of" -> "rt::make_set(${list(b.args)})"
            "Set.contains" -> rt("set_contains")
            "Set.union" -> rt("set_union")
            else -> throw IllegalStateException("unknown builtin ${b.name}")
        }
    }

    private fun callOf(v: Call): String {
        val fn = v.target
        val owner = fn.receiver
        val all = listOfNotNull(v.receiver) + v.args
        fun args(values: List<Value>) = values.joinToString(", ") { expr(it) }
        return when {
            owner is ParserType -> "${q}parse_${owner.name}_${fn.name}(${args(v.args)})"
            owner is FlowGraphType -> {
                val id = module.graphs.indexOfFirst { it.name == owner.name }
                val method = mapOf("get" to "fg_get", "of" to "fg_of", "succ" to "fg_succ", "pred" to "fg_pred").getValue(fn.name)
                "rt::$method($id, ${args(v.args)})"
            }
            owner is ComplexType && owner.name == GRAPH -> {
                val method = mapOf(
                    "succ" to "g_succ", "pred" to "g_pred", "outEdges" to "g_out", "inEdges" to "g_in", "contains" to "g_contains",
                    "indexOf" to "g_index", "exit" to "g_exit", "reachable" to "g_reachable", "postorder" to "g_postorder",
                    "reversePostorder" to "g_rpo", "toDot" to "g_dot",
                ).getValue(fn.name)
                "rt::$method(${args(all)})"
            }
            owner == null && fn.body == null && fn.name == "graphOf" -> "rt::graph_from(${args(v.args)})"
            owner == null && fn.body == null && fn.name == "spanOf" -> "rt::span_of(${args(v.args)})"
            else -> "$q${functionId(fn)}(${args(all)})"
        }
    }

    private val patterns = object : TargetSupport.Patterns {
        override fun fresh(): String = names.fresh("m")
        override fun isItem(subject: String, item: EnumItem): String = "rt::rec_is($subject, ${rid(item.enumName + "." + item.itemName)})"
        override fun itemField(subject: String, item: EnumItem, field: String): String = "rt::field($subject, ${item.fields.keys.indexOf(field)})"
        override fun sizeIs(subject: String, size: Int): String = "rt::items($subject).size() == $size"
        override fun notEmpty(subject: String): String = "!rt::items($subject).empty()"
        override fun element(subject: String, index: Int): String = "rt::items($subject)[$index]"
        override fun tail(subject: String): String = "rt::tail($subject)"
        override fun equalTo(subject: String, value: Value): String = "rt::eq($subject, ${expr(value)})"
        override fun bindVariable(variable: LocalRef): String = names.bind(variable.name)
    }

    /** An immediately called lambda: the cases are nested tests, the first one that holds returns. */
    private fun match(m: Match): String {
        val scrutinee = expr(m.scrutinee)
        return names.scoped {
            val subject = names.fresh("subject")
            val sb = StringBuilder("[&]() -> V { V $subject = $scrutinee; ")
            for (case in m.cases) {
                names.scoped {
                    val steps = s.steps(case.pattern, subject, patterns)
                    val guard = case.guard?.let { b(it) }
                    val body = expr(case.body)
                    var code = if (guard != null) "if ($guard) { return $body; }" else "return $body;"
                    for (step in steps.reversed()) {
                        code = when (step) {
                            is TargetSupport.Step.Test -> "if (${step.cond}) { $code }"
                            is TargetSupport.Step.Bind -> "{ V ${step.name} = ${step.value}; $code }"
                        }
                    }
                    sb.append("{ $code } ")
                }
            }
            val alt = m.alt
            if (alt != null) sb.append("return ${expr(alt)}; }()")
            else sb.append("rt::fail(\"no match for \" + rt::show($subject)); }()")
            sb.toString()
        }
    }
